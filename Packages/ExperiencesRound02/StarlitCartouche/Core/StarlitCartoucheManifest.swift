// round2.md, the R02-G16 level table; `python3 scripts/planning_index.py levels --experience R02-G16`): number, planned
// seed, band, moves budget (the table's "Moves budget") and control emphasis (the table's "Distinct control emphasis"),
// which shapes a level's hazards and windows. Modelled on `VoxelOrigamiManifest` (feature 442).

/// One planned level: its number, planned seed, band, moves budget and control emphasis.
public struct StarlitCartoucheManifestEntry: Sendable, Equatable, Hashable, Codable {
    /// The level number, 1 … 100.
    public let number: Int
    /// The planned seed the level's candidates derive from.
    public let seed: UInt64
    /// The band, 1 … 5.
    public let band: Int
    /// The moves budget, which becomes the level's action budget (8 … 19).
    public let budget: Int
    /// The control emphasis of the archived table ("avoid hazard", "time launch", "commit glyph", "place route
    /// waypoint" or "adjust arc").
    public let emphasis: String

    /// An entry of the given values.
    public init(number: Int, seed: UInt64, band: Int, budget: Int, emphasis: String) {
        self.number = number
        self.seed = seed
        self.band = band
        self.budget = budget
        self.emphasis = emphasis
    }
}

