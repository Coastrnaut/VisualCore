// WaveKnotKeeperExperienceCore — feature 323 (R02-G03-03) T-R02G0303-005 (FR-R02G0303-003, 005; SC-R02G0303-002;
// clarification Q5; data-model.md "WaveKnotKeeperExperienceCore"; contracts/api.md). The adapter of the Wave Knot Keeper
// kernel to the shared experience contract. The core holds the level number, the kernel's `WaveKnotKeeperPlay` and the
// selected control point (presentation only); it never draws and reads no clock. The presenter asks for an immutable
// `WaveKnotKeeperSceneSnapshot` with its own presentation time (`snapshot(time:)`), so the picture can move while the
// state and its digest stay put (renderer purity, R2-G03-INV-10).
//
// Preparation: the certified level number `seed % 100 + 1` of `WaveKnotKeeperManifest`, generated by
// `WaveKnotKeeperGenerator`, begun (and its tutorial dismissed) so the play is in stage `playing`.
//
// Actions (the engine refuses an undeclared control, a wrong value count, a non-finite or out-of-range value before the
// core sees it; called directly, the core refuses them itself with the same reasons):
//   point.move [0…15, 0…5]  control point and direction (an index into `WaveKnotKeeperDirection.allCases`: +x, −x, +y,
//                           −y, +z, −z); whole numbers (`r02-g03.not-whole` otherwise); applied with the play's current
//                           fingerprint as the expected one, so a point outside the rope, a step out of bounds, onto
//                           another point, through a strand outside a gate or over the tension bound is refused by the
//                           kernel (`r02-g03.move`), as is a move after the allowance (`r02-g03.allowance`) or outside
//                           stage `playing` (`r02-g03.stage`);
//   point.select [0…15]     presentation only: the selected handle; no digest change; a point outside the rope is
//                           refused with `r02-g03.move`, a fraction with `r02-g03.not-whole`;
//   play.undo, play.redo    no values; the kernel's undo and redo;
//   level.next              no values; the next certified level (100 wraps to 1) with a fresh play and no selection.
// A kernel refusal (`WaveKnotKeeperError`) becomes `.rule(code: error.reasonCode)`. A refused action changes nothing.
//
// Digest ("r02-g03.wave-knot-keeper.v1"): the level number and the play's fingerprint (not its record history, so undo
// restores the earlier digest exactly); never the selection, the quality tier or a time. Snapshot schema 1: the JSON
// object `{"level", "records"}` with sorted keys; restoring replays the records on a fresh play of that level
// (`WaveKnotKeeperPlay.replay`) and throws `WaveKnotKeeperRestoreRefusal` for a damaged payload, a level number outside
// 1 … 100 or a trace the kernel refuses (a record of a newer schema among them).
//
// Quality: three host tiers, best first as the contract requires (`qualityProfile` level 0 is the best and no budget
// may rise). Host tier `t` draws `WaveKnotKeeperTier.of(t)`: level-0 = 16 sides, 8 corner samples, 2 glow shells;
// level-1 = 10, 4, 1; level-2 = 6, 2, 0. Outcome: `won` or `failed` while the play is in that stage, otherwise nil.
import Foundation
import Synchronization
import VisualCoreDiagnostics
import VisualCoreExperience
import VisualCorePersistence

/// The rule codes of Wave Knot Keeper's adapter refusals (feature 323).
public enum WaveKnotKeeperExperienceRule {
    /// A value that must be a whole number (point, direction) and is not.
    public static let notWhole = "r02-g03.not-whole"
}

/// Why a saved Wave Knot Keeper state was refused on restore (feature 323). A refused restore changes nothing.
public enum WaveKnotKeeperRestoreRefusal: Error, Equatable, Sendable {
    /// The payload is not the JSON object `{"level", "records"}` or a field has the wrong type.
    case damaged
    /// The level number is outside 1 … 100; the value is that number.
    case levelNumber(Int)
    /// The kernel refused the level's generation or the record trace; the value is that refusal.
    case kernel(WaveKnotKeeperError)
}

/// The state of Wave Knot Keeper as an experience (see the file header). Snapshot schema 1.
public struct WaveKnotKeeperExperienceCore: ExperienceCore, Equatable {
    /// The experience's id in the catalog.
    public static let experienceID = "r02-g03.wave-knot-keeper"
    /// The snapshot schema this build writes.
    public static let schemaVersion = 1
    /// The digest's domain string (schema 1).
    public static let digestDomain = "r02-g03.wave-knot-keeper.v1"
    /// The action ids in declaration order.
    public static let actionIDs = ["point.move", "point.select", "play.undo", "play.redo", "level.next"]
    /// The level numbers of the catalog.
    public static let levelNumbers: ClosedRange<Int> = 1...100
    /// The directions in the order of `point.move`'s second value: +x, −x, +y, −y, +z, −z.
    public static let directionOrder: [WaveKnotKeeperDirection] = WaveKnotKeeperDirection.allCases
    /// The outcome code of a won play.
    public static let wonCode = "won"
    /// The outcome code of a failed play.
    public static let failedCode = "failed"

    /// The number of the certified level being played (1 … 100).
    public private(set) var levelNumber: Int
    /// The kernel's play of that level.
    public private(set) var play: WaveKnotKeeperPlay
    /// The selected control point, if any; presentation only — not in the digest, the snapshot payload or `==`.
    public private(set) var selected: Int?
    /// The level number the seed chose; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    public let openingNumber: Int
    /// The fresh play of the opening level; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    private let openingPlay: WaveKnotKeeperPlay
    /// The host quality tier (0 = level-0, the best, … 2, clamped); presentation only — not in the digest, the
    /// snapshot or `==`.
    public private(set) var qualityTier = 0

    /// A state playing `play` of level `levelNumber`, whose reset returns to `openingPlay` of `openingNumber`.
    init(levelNumber: Int, play: WaveKnotKeeperPlay, openingNumber: Int, openingPlay: WaveKnotKeeperPlay) {
        self.levelNumber = levelNumber
        self.play = play
        self.openingNumber = openingNumber
        self.openingPlay = openingPlay
    }

    /// The level number a seed chooses: `seed % 100 + 1`.
    public static func levelNumber(forSeed seed: UInt64) -> Int {
        Int(seed % UInt64(levelNumbers.count)) + 1
    }

    /// The certified level of manifest number `number` (1 … 100).
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func level(number: Int) throws(WaveKnotKeeperError) -> WaveKnotKeeperLevel {
        try generated(number: number).level
    }

    /// The certified levels generated so far, by manifest number: generation is deterministic and costs 0.1 … 2 s in a
    /// debug build, so each level is generated once per process (feature 323).
    private static let generatedCache = Mutex<[Int: WaveKnotKeeperGenerated]>([:])

    /// The certified level and solution of manifest number `number` (1 … 100), generated once per process.
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func generated(number: Int) throws(WaveKnotKeeperError) -> WaveKnotKeeperGenerated {
        guard levelNumbers.contains(number) else { throw .level("number") }
        if let cached = generatedCache.withLock({ $0[number] }) { return cached }
        let fresh = try WaveKnotKeeperGenerator.generate(WaveKnotKeeperManifest.entries[number - 1])
        generatedCache.withLock { $0[number] = fresh }
        return fresh
    }

    /// A fresh play of `level` in stage `playing`: begun, with its tutorial dismissed when it has one.
    ///
    /// - Throws: the kernel's refusal of `begin` or `dismissTutorial` (never for a new play).
    public static func freshPlay(of level: WaveKnotKeeperLevel) throws(WaveKnotKeeperError) -> WaveKnotKeeperPlay {
        try WaveKnotKeeperPlay.replay(level: level, records: [])
    }

    /// The opening state of manifest number `number`.
    ///
    /// - Throws: as ``level(number:)``.
    public static func opening(number: Int) throws(WaveKnotKeeperError) -> WaveKnotKeeperExperienceCore {
        let play = try freshPlay(of: try level(number: number))
        return WaveKnotKeeperExperienceCore(levelNumber: number, play: play, openingNumber: number, openingPlay: play)
    }

    /// An immutable copy of the play, the level number and the selection for drawing at the presenter's presentation
    /// time `time` (seconds). Reads only; the state and its digest do not change.
    public func snapshot(time: Double) -> WaveKnotKeeperSceneSnapshot {
        WaveKnotKeeperSceneSnapshot(play: play, levelNumber: levelNumber, selected: selected, time: time)
    }

    /// The tier the host quality tier draws: `WaveKnotKeeperTier.of(qualityTier)` (both ordered richest first).
    public var renderTier: WaveKnotKeeperTier { WaveKnotKeeperTier.of(qualityTier) }

    // MARK: Quality

    /// Three quality tiers: level-0 (richest) … level-2 (cheapest).
    public static var qualityTiers: Int { WaveKnotKeeperTier.all.count }

    /// One level per host tier, best first: the element share is the tube's sides over 16, the iteration share the
    /// corner samples over 8 and the effect passes the glow shells; every level draws at the full resolution.
    public static var qualityProfile: QualityProfile {
        let best = WaveKnotKeeperTier.all[0]
        var levels: [QualityLevel] = []
        for hostTier in 0..<WaveKnotKeeperTier.all.count {
            let tier = WaveKnotKeeperTier.of(hostTier)
            levels.append(QualityLevel(name: tier.name, resolutionShare: 1,
                                       elementShare: Double(tier.sides) / Double(best.sides),
                                       iterationShare: Double(tier.cornerSamples) / Double(best.cornerSamples),
                                       effectPasses: tier.glowShells))
        }
        return (try? QualityProfile(levels: levels)) ?? .uniform(levels: levels.count)
    }

    /// Stores `tier` clamped to 0 ..< `qualityTiers`; the state and its digest do not change.
    public mutating func setQualityTier(_ tier: Int) {
        qualityTier = min(max(tier, 0), Self.qualityTiers - 1)
    }

    /// Equal states: the level number and the play (not the selection, the quality tier or the opening level).
    public static func == (lhs: WaveKnotKeeperExperienceCore, rhs: WaveKnotKeeperExperienceCore) -> Bool {
        lhs.levelNumber == rhs.levelNumber && lhs.play == rhs.play
    }

    // MARK: Contract

    /// Schema 1, the first version: no migration steps.
    public static var migrations: MigrationChain { MigrationChain(currentVersion: schemaVersion) }

    /// The declared controls, built once.
    private static let declaredControls: [ExperienceControl] = [
        ExperienceControl(id: "point.move", ranges: [0...15, 0...5]),
        ExperienceControl(id: "point.select", ranges: [0...15]),
        ExperienceControl(id: "play.undo"),
        ExperienceControl(id: "play.redo"),
        ExperienceControl(id: "level.next"),
    ]

    /// The five controls with their declared ranges (see the file header); the last three take no values.
    public static var controls: [ExperienceControl] { declaredControls }

    /// The opening state of level `seed % 100 + 1`, in stage `playing`; no clock is read.
    ///
    /// - Throws: `ExperienceFailure` with the kernel's reason code when the level cannot be generated.
    public static func prepare(seed: UInt64) async throws -> WaveKnotKeeperExperienceCore {
        try Task.checkCancellation()
        let number = levelNumber(forSeed: seed)
        do throws(WaveKnotKeeperError) {
            return try opening(number: number)
        } catch {
            throw ExperienceFailure(code: error.reasonCode, message: "Wave Knot Keeper level \(number): \(error)")
        }
    }

    /// A host step changes nothing: the caustic pulses move with the presenter's time, not the state.
    public mutating func update(step: Int) {}

    /// Carries out a well-formed action (see the file header); a refused action changes nothing.
    public mutating func apply(_ action: ExperienceAction) -> ActionResult {
        if let refusal = ExperienceInput.validate(control: action.control, values: action.values,
                                                  controls: Self.declaredControls) {
            return .rejected(refusal)
        }
        do throws(WaveKnotKeeperError) {
            switch action.control {
            case "point.move":
                guard let point = Self.whole(action.values[0]), let direction = Self.whole(action.values[1]) else {
                    return .rejected(.rule(code: WaveKnotKeeperExperienceRule.notWhole))
                }
                let move = WaveKnotKeeperMove(point: point, direction: Self.directionOrder[direction])
                try play.apply(move, expecting: play.fingerprint)
            case "point.select":
                guard let point = Self.whole(action.values[0]) else {
                    return .rejected(.rule(code: WaveKnotKeeperExperienceRule.notWhole))
                }
                guard play.points.indices.contains(point) else { throw .move("range") }
                selected = point
            case "play.undo":
                try play.undo()
            case "play.redo":
                try play.redo()
            default:   // level.next
                let next = levelNumber % Self.levelNumbers.upperBound + 1
                let fresh = try Self.freshPlay(of: try Self.level(number: next))
                levelNumber = next
                play = fresh
                selected = nil
            }
        } catch {
            return .rejected(.rule(code: error.reasonCode))
        }
        return .accepted
    }

    /// `value` as an `Int` when it is a finite whole number; nil otherwise.
    static func whole(_ value: Double) -> Int? {
        guard value.isFinite, value == value.rounded() else { return nil }
        return Int(value)
    }

    /// Back to the fresh play of the level the seed chose with no selection; the quality tier, which is not state, is
    /// kept.
    public mutating func reset() {
        levelNumber = openingNumber
        play = openingPlay
        selected = nil
    }

    /// `won` or `failed` while the play is in that stage; nil otherwise.
    public var outcome: ExperienceOutcome? {
        switch play.stage {
        case .won: ExperienceOutcome(code: Self.wonCode)
        case .failed: ExperienceOutcome(code: Self.failedCode)
        default: nil
        }
    }

    /// "r02-g03.wave-knot-keeper.v1", then the level number and the play's fingerprint (level, rope, moves spent,
    /// stage).
    public func writeDigest(into builder: inout DigestBuilder) throws(DigestError) {
        builder.add(Self.digestDomain)
        builder.add(levelNumber)
        // The play's fingerprint and not its record history, so undo restores the earlier digest exactly.
        builder.add(play.fingerprint)
    }

    // MARK: Snapshot

    /// The payload's JSON form.
    private struct Payload: Codable {
        var level: Int
        var records: [WaveKnotKeeperRecord]
    }

    /// The JSON object `{"level", "records"}` with sorted keys and unescaped slashes.
    public func snapshotPayload() throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try encoder.encode(Payload(level: levelNumber, records: play.records))
    }

    /// The core of `payload`: the records replayed on a fresh play of the saved level, with no selection; a reset
    /// returns to the level `seed` chooses.
    ///
    /// - Throws: ``WaveKnotKeeperRestoreRefusal`` for a damaged payload, a level number outside 1 … 100 or a level or
    ///   trace the kernel refuses.
    public static func restore(payload: Data, seed: UInt64) throws -> WaveKnotKeeperExperienceCore {
        guard let decoded = try? JSONDecoder().decode(Payload.self, from: payload) else {
            throw WaveKnotKeeperRestoreRefusal.damaged
        }
        guard levelNumbers.contains(decoded.level) else {
            throw WaveKnotKeeperRestoreRefusal.levelNumber(decoded.level)
        }
        do throws(WaveKnotKeeperError) {
            let saved = try level(number: decoded.level)
            let play = try WaveKnotKeeperPlay.replay(level: saved, records: decoded.records)
            let openingNumber = levelNumber(forSeed: seed)
            let openingPlay = openingNumber == decoded.level
                ? try freshPlay(of: saved)
                : try freshPlay(of: try Self.level(number: openingNumber))
            return WaveKnotKeeperExperienceCore(levelNumber: decoded.level, play: play, openingNumber: openingNumber,
                                                openingPlay: openingPlay)
        } catch {
            throw WaveKnotKeeperRestoreRefusal.kernel(error)
        }
    }
}
