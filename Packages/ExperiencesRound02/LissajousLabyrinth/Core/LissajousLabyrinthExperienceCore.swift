// LissajousLabyrinthExperienceCore — feature 313 (R02-G02-03) T-R02G0203-005 (FR-R02G0203-003, 005; clarification Q5;
// data-model.md "LissajousLabyrinthExperienceCore"; contracts/api.md). The adapter of the Lissajous Labyrinth kernel to
// the shared experience contract. The core holds the level number and the kernel's `LissajousLabyrinthPlay`; it never
// draws and reads no clock. The presenter asks for an immutable `LissajousLabyrinthSceneSnapshot` with its own
// presentation time (`snapshot(time:)`), so the picture can move while the state and its digest stay put (renderer
// purity, R2-G02-INV-10).
//
// Preparation: the certified level number `seed % 100 + 1` of `LissajousLabyrinthManifest`, generated by
// `LissajousLabyrinthGenerator`, begun (and its tutorial dismissed) so the play is in stage `playing`.
//
// Actions (the engine refuses an undeclared control, a wrong value count, a non-finite or out-of-range value before the
// core sees it; called directly, the core refuses them itself with the same reasons):
//   dial.set [0…3, 0…15]   dial (0 = frequencyA, 1 = frequencyB, 2 = phaseA, 3 = phaseC) and its new value; whole
//                          numbers (`r02-g02.not-whole` otherwise); applied with the play's current fingerprint as the
//                          expected one, so a value outside the dial's own range (frequencies 1 … 9), the current
//                          value or non-coprime frequencies are refused by the kernel (`r02-g02.move`);
//   play.undo, play.redo   no values; the kernel's undo and redo;
//   level.next             no values; the next certified level (100 wraps to 1) with a fresh play.
// A kernel refusal (`LissajousLabyrinthError`) becomes `.rule(code: error.reasonCode)`, for example `r02-g02.move`,
// `r02-g02.stage` or `r02-g02.allowance`. A refused action changes nothing.
//
// Digest ("r02-g02.lissajous-labyrinth.v1"): the level number and the play's fingerprint (not its record history, so undo
// restores the earlier digest exactly); never the quality tier or a time. Snapshot schema 1: the JSON object
// `{"level", "records"}` with sorted keys; restoring replays the records on a fresh play of that level
// (`LissajousLabyrinthPlay.replay`) and throws `LissajousLabyrinthRestoreRefusal` for a damaged payload, a level number
// outside 1 … 100 or a trace the kernel refuses.
//
// Quality: three host tiers, best first as the contract requires (`qualityProfile` level 0 is the best and no budget
// may rise). Host tier `t` draws `LissajousLabyrinthTier.of(t)`: level-0 = 4,096 samples, 2 glow passes, trail 512;
// level-1 = 2,048, 1, 256; level-2 = 1,024, 0, 128. Outcome: `won` or `failed` while the play is in that stage,
// otherwise nil.
import Foundation
import Synchronization
import VisualCoreDiagnostics
import VisualCoreExperience
import VisualCorePersistence

/// The rule codes of Lissajous Labyrinth's adapter refusals (feature 313).
public enum LissajousLabyrinthExperienceRule {
    /// A value that must be a whole number (dial, value) and is not.
    public static let notWhole = "r02-g02.not-whole"
}

/// Why a saved Lissajous Labyrinth state was refused on restore (feature 313). A refused restore changes nothing.
public enum LissajousLabyrinthRestoreRefusal: Error, Equatable, Sendable {
    /// The payload is not the JSON object `{"level", "records"}` or a field has the wrong type.
    case damaged
    /// The level number is outside 1 … 100; the value is that number.
    case levelNumber(Int)
    /// The kernel refused the level's generation or the record trace; the value is that refusal.
    case kernel(LissajousLabyrinthError)
}

/// The state of Lissajous Labyrinth as an experience (see the file header). Snapshot schema 1.
public struct LissajousLabyrinthExperienceCore: ExperienceCore, Equatable {
    /// The experience's id in the catalog.
    public static let experienceID = "r02-g02.lissajous-labyrinth"
    /// The snapshot schema this build writes.
    public static let schemaVersion = 1
    /// The digest's domain string (schema 1).
    public static let digestDomain = "r02-g02.lissajous-labyrinth.v1"
    /// The action ids in declaration order.
    public static let actionIDs = ["dial.set", "play.undo", "play.redo", "level.next"]
    /// The level numbers of the catalog.
    public static let levelNumbers: ClosedRange<Int> = 1...100
    /// The dials in the order of `dial.set`'s first value: frequencyA, frequencyB, phaseA, phaseC.
    public static let dialOrder: [LissajousLabyrinthDial] = LissajousLabyrinthDial.allCases
    /// The outcome code of a won play.
    public static let wonCode = "won"
    /// The outcome code of a failed play.
    public static let failedCode = "failed"

    /// The number of the certified level being played (1 … 100).
    public private(set) var levelNumber: Int
    /// The kernel's play of that level.
    public private(set) var play: LissajousLabyrinthPlay
    /// The level number the seed chose; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    public let openingNumber: Int
    /// The fresh play of the opening level; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    private let openingPlay: LissajousLabyrinthPlay
    /// The host quality tier (0 = level-0, the best, … 2, clamped); presentation only — not in the digest, the
    /// snapshot or `==`.
    public private(set) var qualityTier = 0

    /// A state playing `play` of level `levelNumber`, whose reset returns to `openingPlay` of `openingNumber`.
    init(levelNumber: Int, play: LissajousLabyrinthPlay, openingNumber: Int, openingPlay: LissajousLabyrinthPlay) {
        self.levelNumber = levelNumber
        self.play = play
        self.openingNumber = openingNumber
        self.openingPlay = openingPlay
    }

    /// The level number a seed chooses: `seed % 100 + 1`.
    public static func levelNumber(forSeed seed: UInt64) -> Int {
        Int(seed % UInt64(levelNumbers.count)) + 1
    }

    /// The certified level of manifest number `number` (1 … 100).
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func level(number: Int) throws(LissajousLabyrinthError) -> LissajousLabyrinthLevel {
        try generated(number: number).level
    }

    /// The certified levels generated so far, by manifest number: generation is deterministic and costs about 0.1 s in
    /// a debug build, so each level is generated once per process (feature 313).
    private static let generatedCache = Mutex<[Int: LissajousLabyrinthGenerated]>([:])

    /// The certified level and solution of manifest number `number` (1 … 100), generated once per process.
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func generated(number: Int) throws(LissajousLabyrinthError) -> LissajousLabyrinthGenerated {
        guard levelNumbers.contains(number) else { throw .level("number") }
        if let cached = generatedCache.withLock({ $0[number] }) { return cached }
        let fresh = try LissajousLabyrinthGenerator.generate(LissajousLabyrinthManifest.entries[number - 1])
        generatedCache.withLock { $0[number] = fresh }
        return fresh
    }

    /// A fresh play of `level` in stage `playing`: begun, with its tutorial dismissed when it has one.
    ///
    /// - Throws: the kernel's refusal of `begin` or `dismissTutorial` (never for a new play).
    public static func freshPlay(of level: LissajousLabyrinthLevel) throws(LissajousLabyrinthError)
        -> LissajousLabyrinthPlay {
        try LissajousLabyrinthPlay.replay(level: level, records: [])
    }

    /// The opening state of manifest number `number`.
    ///
    /// - Throws: as ``level(number:)``.
    public static func opening(number: Int) throws(LissajousLabyrinthError) -> LissajousLabyrinthExperienceCore {
        let play = try freshPlay(of: try level(number: number))
        return LissajousLabyrinthExperienceCore(levelNumber: number, play: play, openingNumber: number,
                                                openingPlay: play)
    }

    /// An immutable copy of the play for drawing at the presenter's presentation time `time` (seconds). Reads only;
    /// the state and its digest do not change.
    public func snapshot(time: Double) -> LissajousLabyrinthSceneSnapshot {
        LissajousLabyrinthSceneSnapshot(play: play, time: time)
    }

    /// The tier the host quality tier draws: `LissajousLabyrinthTier.of(qualityTier)` (both ordered richest first).
    public var renderTier: LissajousLabyrinthTier { LissajousLabyrinthTier.of(qualityTier) }

    // MARK: Quality

    /// Three quality tiers: level-0 (richest) … level-2 (cheapest).
    public static var qualityTiers: Int { LissajousLabyrinthTier.all.count }

    /// One level per host tier, best first: the element share is the drawn samples over 4,096, the iteration share the
    /// trail over 512 ticks and the effect passes the glow passes; every level draws at the full resolution.
    public static var qualityProfile: QualityProfile {
        let best = LissajousLabyrinthTier.all[0]
        var levels: [QualityLevel] = []
        for hostTier in 0..<LissajousLabyrinthTier.all.count {
            let tier = LissajousLabyrinthTier.of(hostTier)
            levels.append(QualityLevel(name: tier.name, resolutionShare: 1,
                                       elementShare: Double(tier.samples) / Double(best.samples),
                                       iterationShare: Double(tier.trail) / Double(best.trail),
                                       effectPasses: tier.glowPasses))
        }
        return (try? QualityProfile(levels: levels)) ?? .uniform(levels: levels.count)
    }

    /// Stores `tier` clamped to 0 ..< `qualityTiers`; the state and its digest do not change.
    public mutating func setQualityTier(_ tier: Int) {
        qualityTier = min(max(tier, 0), Self.qualityTiers - 1)
    }

    /// Equal states: the level number and the play (not the quality tier or the opening level).
    public static func == (lhs: LissajousLabyrinthExperienceCore, rhs: LissajousLabyrinthExperienceCore) -> Bool {
        lhs.levelNumber == rhs.levelNumber && lhs.play == rhs.play
    }

    // MARK: Contract

    /// Schema 1, the first version: no migration steps.
    public static var migrations: MigrationChain { MigrationChain(currentVersion: schemaVersion) }

    /// The declared controls, built once.
    private static let declaredControls: [ExperienceControl] = [
        ExperienceControl(id: "dial.set", ranges: [0...3, 0...15]),
        ExperienceControl(id: "play.undo"),
        ExperienceControl(id: "play.redo"),
        ExperienceControl(id: "level.next"),
    ]

    /// The four controls with their declared ranges (see the file header); the last three take no values.
    public static var controls: [ExperienceControl] { declaredControls }

    /// The opening state of level `seed % 100 + 1`, in stage `playing`; no clock is read.
    ///
    /// - Throws: `ExperienceFailure` with the kernel's reason code when the level cannot be generated.
    public static func prepare(seed: UInt64) async throws -> LissajousLabyrinthExperienceCore {
        try Task.checkCancellation()
        let number = levelNumber(forSeed: seed)
        do throws(LissajousLabyrinthError) {
            return try opening(number: number)
        } catch {
            throw ExperienceFailure(code: error.reasonCode, message: "Lissajous Labyrinth level \(number): \(error)")
        }
    }

    /// A host step changes nothing: the tracer head and the shimmer move with the presenter's time, not the state.
    public mutating func update(step: Int) {}

    /// Carries out a well-formed action (see the file header); a refused action changes nothing.
    public mutating func apply(_ action: ExperienceAction) -> ActionResult {
        if let refusal = ExperienceInput.validate(control: action.control, values: action.values,
                                                  controls: Self.declaredControls) {
            return .rejected(refusal)
        }
        do throws(LissajousLabyrinthError) {
            switch action.control {
            case "dial.set":
                guard let dial = Self.whole(action.values[0]), let value = Self.whole(action.values[1]) else {
                    return .rejected(.rule(code: LissajousLabyrinthExperienceRule.notWhole))
                }
                let move = LissajousLabyrinthAction(dial: Self.dialOrder[dial], value: value)
                try play.apply(move, expecting: play.fingerprint)
            case "play.undo":
                try play.undo()
            case "play.redo":
                try play.redo()
            default:   // level.next
                let next = levelNumber % Self.levelNumbers.upperBound + 1
                let fresh = try Self.freshPlay(of: try Self.level(number: next))
                levelNumber = next
                play = fresh
            }
        } catch {
            return .rejected(.rule(code: error.reasonCode))
        }
        return .accepted
    }

    /// `value` as an `Int` when it is a finite whole number; nil otherwise.
    static func whole(_ value: Double) -> Int? {
        guard value.isFinite, value == value.rounded() else { return nil }
        return Int(value)
    }

    /// Back to the fresh play of the level the seed chose; the quality tier, which is not state, is kept.
    public mutating func reset() {
        levelNumber = openingNumber
        play = openingPlay
    }

    /// `won` or `failed` while the play is in that stage; nil otherwise.
    public var outcome: ExperienceOutcome? {
        switch play.stage {
        case .won: ExperienceOutcome(code: Self.wonCode)
        case .failed: ExperienceOutcome(code: Self.failedCode)
        default: nil
        }
    }

    /// "r02-g02.lissajous-labyrinth.v1", then the level number and the play's fingerprint (level, dials, actions
    /// spent, stage).
    public func writeDigest(into builder: inout DigestBuilder) throws(DigestError) {
        builder.add(Self.digestDomain)
        builder.add(levelNumber)
        // The play's fingerprint and not its record history, so undo restores the earlier digest exactly.
        builder.add(play.fingerprint)
    }

    // MARK: Snapshot

    /// The payload's JSON form.
    private struct Payload: Codable {
        var level: Int
        var records: [LissajousLabyrinthRecord]
    }

    /// The JSON object `{"level", "records"}` with sorted keys and unescaped slashes.
    public func snapshotPayload() throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try encoder.encode(Payload(level: levelNumber, records: play.records))
    }

    /// The core of `payload`: the records replayed on a fresh play of the saved level; a reset returns to the level
    /// `seed` chooses.
    ///
    /// - Throws: ``LissajousLabyrinthRestoreRefusal`` for a damaged payload, a level number outside 1 … 100 or a level
    ///   or trace the kernel refuses.
    public static func restore(payload: Data, seed: UInt64) throws -> LissajousLabyrinthExperienceCore {
        guard let decoded = try? JSONDecoder().decode(Payload.self, from: payload) else {
            throw LissajousLabyrinthRestoreRefusal.damaged
        }
        guard levelNumbers.contains(decoded.level) else {
            throw LissajousLabyrinthRestoreRefusal.levelNumber(decoded.level)
        }
        do throws(LissajousLabyrinthError) {
            let saved = try level(number: decoded.level)
            let play = try LissajousLabyrinthPlay.replay(level: saved, records: decoded.records)
            let openingNumber = levelNumber(forSeed: seed)
            let openingPlay = openingNumber == decoded.level
                ? try freshPlay(of: saved)
                : try freshPlay(of: try Self.level(number: openingNumber))
            return LissajousLabyrinthExperienceCore(levelNumber: decoded.level, play: play,
                                                    openingNumber: openingNumber, openingPlay: openingPlay)
        } catch {
            throw LissajousLabyrinthRestoreRefusal.kernel(error)
        }
    }
}
