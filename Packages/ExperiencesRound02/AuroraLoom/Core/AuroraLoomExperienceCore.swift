// AuroraLoomExperienceCore — feature 303 (R02-G01-03) T-R02G0103-005 (FR-R02G0103-005; clarification Q5; data-model.md
// "AuroraLoomExperienceCore"; contracts/api.md). The adapter of the Aurora Loom kernel to the shared experience
// contract. The core holds the level number and the kernel's `AuroraLoomPlay`; it never draws and reads no clock. The
// presenter asks for an immutable `AuroraLoomSceneSnapshot` with its own frame time (`snapshot(time:)`), so the picture
// can move while the state and its digest stay put (renderer purity, INV-10).
//
// Preparation: the certified level number `seed % 100 + 1` of `AuroraLoomManifest`, generated by `AuroraLoomGenerator`,
// begun (and its tutorial dismissed) so the play is in stage `playing`.
//
// Actions (the engine refuses an undeclared control, a wrong value count, a non-finite or out-of-range value before the
// core sees it; called directly, the core refuses them itself with the same reasons):
//   ribbon.move [0…2, 0…1, 0…15]   ribbon, control (0 = wave, 1 = phase), step; whole numbers (`r02-g01.not-whole`
//                                  otherwise); applied with the play's current fingerprint as the expected one;
//   play.undo, play.redo           no values; the kernel's undo and redo;
//   level.next                     no values; the next certified level (100 wraps to 1) with a fresh play.
// A kernel refusal (`AuroraLoomError`) becomes `.rule(code: error.reasonCode)`, for example `r02-g01.move` or
// `r02-g01.stage`. A refused action changes nothing.
//
// Digest ("r02-g01.aurora-loom.v1"): the level number, the play's fingerprint and the number of its records; never the
// quality tier or a time. Snapshot schema 1: the JSON object `{"level", "records"}` with sorted keys; restoring
// replays the records on a fresh play of that level (`AuroraLoomPlay.replay`) and throws
// `AuroraLoomRestoreRefusal` for a damaged payload, a level number outside 1 … 100 or a trace the kernel refuses.
//
// Quality: three host tiers, best first as the contract requires (`qualityProfile` level 0 is the best and no budget
// may rise). Host tier `t` draws `AuroraLoomTier.of(t)`: level-0 = 5 layers, 128 segments, 2 glow passes;
// level-1 = 3, 64, 1; level-2 = 1, 32, 0. Outcome: `won` or `failed` while the play is in that stage, otherwise nil.
import Foundation
import VisualCoreDiagnostics
import VisualCoreExperience
import VisualCorePersistence

/// The rule codes of Aurora Loom's adapter refusals (feature 303).
public enum AuroraLoomExperienceRule {
    /// A value that must be a whole number (ribbon, control, step) and is not.
    public static let notWhole = "r02-g01.not-whole"
}

/// Why a saved Aurora Loom state was refused on restore (feature 303). A refused restore changes nothing.
public enum AuroraLoomRestoreRefusal: Error, Equatable, Sendable {
    /// The payload is not the JSON object `{"level", "records"}` or a field has the wrong type.
    case damaged
    /// The level number is outside 1 … 100; the value is that number.
    case levelNumber(Int)
    /// The kernel refused the level's generation or the record trace; the value is that refusal.
    case kernel(AuroraLoomError)
}

/// The state of Aurora Loom as an experience (see the file header). Snapshot schema 1.
public struct AuroraLoomExperienceCore: ExperienceCore, Equatable {
    /// The experience's id in the catalog.
    public static let experienceID = "r02-g01.aurora-loom"
    /// The snapshot schema this build writes.
    public static let schemaVersion = 1
    /// The digest's domain string (schema 1).
    public static let digestDomain = "r02-g01.aurora-loom.v1"
    /// The action ids in declaration order.
    public static let actionIDs = ["ribbon.move", "play.undo", "play.redo", "level.next"]
    /// The level numbers of the catalog.
    public static let levelNumbers: ClosedRange<Int> = 1...100
    /// The outcome code of a won play.
    public static let wonCode = "won"
    /// The outcome code of a failed play.
    public static let failedCode = "failed"

    /// The number of the certified level being played (1 … 100).
    public private(set) var levelNumber: Int
    /// The kernel's play of that level.
    public private(set) var play: AuroraLoomPlay
    /// The level number the seed chose; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    public let openingNumber: Int
    /// The fresh play of the opening level; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    private let openingPlay: AuroraLoomPlay
    /// The host quality tier (0 = level-0, the best, … 2, clamped); presentation only — not in the digest, the
    /// snapshot or `==`.
    public private(set) var qualityTier = 0

    /// A state playing `play` of level `levelNumber`, whose reset returns to `openingPlay` of `openingNumber`.
    init(levelNumber: Int, play: AuroraLoomPlay, openingNumber: Int, openingPlay: AuroraLoomPlay) {
        self.levelNumber = levelNumber
        self.play = play
        self.openingNumber = openingNumber
        self.openingPlay = openingPlay
    }

    /// The level number a seed chooses: `seed % 100 + 1`.
    public static func levelNumber(forSeed seed: UInt64) -> Int {
        Int(seed % UInt64(levelNumbers.count)) + 1
    }

    /// The certified level of manifest number `number` (1 … 100).
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func level(number: Int) throws(AuroraLoomError) -> AuroraLoomLevel {
        guard levelNumbers.contains(number) else { throw .level("number") }
        return try AuroraLoomGenerator.generate(AuroraLoomManifest.entries[number - 1]).level
    }

    /// A fresh play of `level` in stage `playing`: begun, with its tutorial dismissed when it has one.
    ///
    /// - Throws: the kernel's refusal of `begin` or `dismissTutorial` (never for a new play).
    public static func freshPlay(of level: AuroraLoomLevel) throws(AuroraLoomError) -> AuroraLoomPlay {
        try AuroraLoomPlay.replay(level: level, records: [])
    }

    /// The opening state of manifest number `number`.
    ///
    /// - Throws: as ``level(number:)``.
    public static func opening(number: Int) throws(AuroraLoomError) -> AuroraLoomExperienceCore {
        let play = try freshPlay(of: try level(number: number))
        return AuroraLoomExperienceCore(levelNumber: number, play: play, openingNumber: number, openingPlay: play)
    }

    /// An immutable copy of the play for drawing at the presenter's frame time `time` (ticks of 1/120 s). Reads only;
    /// the state and its digest do not change.
    public func snapshot(time: Double) -> AuroraLoomSceneSnapshot {
        AuroraLoomSceneSnapshot(play: play, time: time)
    }

    /// The tier the host quality tier draws: `AuroraLoomTier.of(qualityTier)` (both ordered richest first).
    public var renderTier: AuroraLoomTier { AuroraLoomTier.of(qualityTier) }

    // MARK: Quality

    /// Three quality tiers: level-0 (richest) … level-2 (cheapest).
    public static var qualityTiers: Int { AuroraLoomTier.all.count }

    /// One level per host tier, best first: the element share is the drawn layers over 5, the iteration share the
    /// segments over 128 and the effect passes the glow passes; every level draws at the full resolution.
    public static var qualityProfile: QualityProfile {
        let best = AuroraLoomTier.all[0]
        var levels: [QualityLevel] = []
        for hostTier in 0..<AuroraLoomTier.all.count {
            let tier = AuroraLoomTier.of(hostTier)
            levels.append(QualityLevel(name: "level-\(hostTier)", resolutionShare: 1,
                                       elementShare: Double(tier.layers) / Double(best.layers),
                                       iterationShare: Double(tier.segments) / Double(best.segments),
                                       effectPasses: tier.glowPasses))
        }
        return (try? QualityProfile(levels: levels)) ?? .uniform(levels: levels.count)
    }

    /// Stores `tier` clamped to 0 ..< `qualityTiers`; the state and its digest do not change.
    public mutating func setQualityTier(_ tier: Int) {
        qualityTier = min(max(tier, 0), Self.qualityTiers - 1)
    }

    /// Equal states: the level number and the play (not the quality tier or the opening level).
    public static func == (lhs: AuroraLoomExperienceCore, rhs: AuroraLoomExperienceCore) -> Bool {
        lhs.levelNumber == rhs.levelNumber && lhs.play == rhs.play
    }

    // MARK: Contract

    /// Schema 1, the first version: no migration steps.
    public static var migrations: MigrationChain { MigrationChain(currentVersion: schemaVersion) }

    /// The declared controls, built once.
    private static let declaredControls: [ExperienceControl] = [
        ExperienceControl(id: "ribbon.move", ranges: [0...2, 0...1, 0...15]),
        ExperienceControl(id: "play.undo"),
        ExperienceControl(id: "play.redo"),
        ExperienceControl(id: "level.next"),
    ]

    /// The four controls with their declared ranges (see the file header); the last three take no values.
    public static var controls: [ExperienceControl] { declaredControls }

    /// The opening state of level `seed % 100 + 1`, in stage `playing`; no clock is read.
    ///
    /// - Throws: `ExperienceFailure` with the kernel's reason code when the level cannot be generated.
    public static func prepare(seed: UInt64) async throws -> AuroraLoomExperienceCore {
        try Task.checkCancellation()
        let number = levelNumber(forSeed: seed)
        do throws(AuroraLoomError) {
            return try opening(number: number)
        } catch {
            throw ExperienceFailure(code: error.reasonCode, message: "Aurora Loom level \(number): \(error)")
        }
    }

    /// A host step changes nothing: the wave travel and shimmer move with the presenter's frame time, not the state.
    public mutating func update(step: Int) {}

    /// Carries out a well-formed action (see the file header); a refused action changes nothing.
    public mutating func apply(_ action: ExperienceAction) -> ActionResult {
        if let refusal = ExperienceInput.validate(control: action.control, values: action.values,
                                                  controls: Self.declaredControls) {
            return .rejected(refusal)
        }
        do throws(AuroraLoomError) {
            switch action.control {
            case "ribbon.move":
                guard let ribbon = Self.whole(action.values[0]), let control = Self.whole(action.values[1]),
                      let step = Self.whole(action.values[2]) else {
                    return .rejected(.rule(code: AuroraLoomExperienceRule.notWhole))
                }
                let move = AuroraLoomMove(ribbon: ribbon, control: control == 0 ? .wave : .phase, step: step)
                try play.apply(move, expecting: play.fingerprint)
            case "play.undo":
                try play.undo()
            case "play.redo":
                try play.redo()
            default:   // level.next
                let next = levelNumber % Self.levelNumbers.upperBound + 1
                let fresh = try Self.freshPlay(of: try Self.level(number: next))
                levelNumber = next
                play = fresh
            }
        } catch {
            return .rejected(.rule(code: error.reasonCode))
        }
        return .accepted
    }

    /// `value` as an `Int` when it is a finite whole number; nil otherwise.
    static func whole(_ value: Double) -> Int? {
        guard value.isFinite, value == value.rounded() else { return nil }
        return Int(value)
    }

    /// Back to the fresh play of the level the seed chose; the quality tier, which is not state, is kept.
    public mutating func reset() {
        levelNumber = openingNumber
        play = openingPlay
    }

    /// `won` or `failed` while the play is in that stage; nil otherwise.
    public var outcome: ExperienceOutcome? {
        switch play.stage {
        case .won: ExperienceOutcome(code: Self.wonCode)
        case .failed: ExperienceOutcome(code: Self.failedCode)
        default: nil
        }
    }

    /// "r02-g01.aurora-loom.v1", then the level number, the play's fingerprint (level, steps, moves spent, stage) and
    /// the number of its records.
    public func writeDigest(into builder: inout DigestBuilder) throws(DigestError) {
        builder.add(Self.digestDomain)
        builder.add(levelNumber)
        builder.add(play.fingerprint)
        builder.add(play.records.count)
    }

    // MARK: Snapshot

    /// The payload's JSON form.
    private struct Payload: Codable {
        var level: Int
        var records: [AuroraLoomRecord]
    }

    /// The JSON object `{"level", "records"}` with sorted keys and unescaped slashes.
    public func snapshotPayload() throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try encoder.encode(Payload(level: levelNumber, records: play.records))
    }

    /// The core of `payload`: the records replayed on a fresh play of the saved level; a reset returns to the level
    /// `seed` chooses.
    ///
    /// - Throws: ``AuroraLoomRestoreRefusal`` for a damaged payload, a level number outside 1 … 100 or a level or
    ///   trace the kernel refuses.
    public static func restore(payload: Data, seed: UInt64) throws -> AuroraLoomExperienceCore {
        guard let decoded = try? JSONDecoder().decode(Payload.self, from: payload) else {
            throw AuroraLoomRestoreRefusal.damaged
        }
        guard levelNumbers.contains(decoded.level) else {
            throw AuroraLoomRestoreRefusal.levelNumber(decoded.level)
        }
        do throws(AuroraLoomError) {
            let saved = try level(number: decoded.level)
            let play = try AuroraLoomPlay.replay(level: saved, records: decoded.records)
            let openingNumber = levelNumber(forSeed: seed)
            let openingPlay = openingNumber == decoded.level
                ? try freshPlay(of: saved)
                : try freshPlay(of: try Self.level(number: openingNumber))
            return AuroraLoomExperienceCore(levelNumber: decoded.level, play: play, openingNumber: openingNumber,
                                            openingPlay: openingPlay)
        } catch {
            throw AuroraLoomRestoreRefusal.kernel(error)
        }
    }
}
