// AuroraLoomExperienceCore — feature 303 (R02-G01-03) T-R02G0103-005 (FR-R02G0103-005; clarification Q5; data-model.md
// "AuroraLoomExperienceCore"; contracts/api.md); progression and teaching from feature 305 (R02-G01-05) T-R02G0105-004
// (FR-R02G0105-001, 004, 005, 006, 007; clarifications Q2–Q5). The adapter of the Aurora Loom kernel to the shared
// experience contract. The core holds the level number, the kernel's `AuroraLoomPlay`, the player's progress, the mode
// and the tutorial step; it never draws and reads no clock. The presenter asks for an immutable
// `AuroraLoomSceneSnapshot` with its own frame time (`snapshot(time:)`), so the picture can move while the state and its
// digest stay put (renderer purity, INV-10).
//
// Preparation: the certified level number `seed % 100 + 1` of `AuroraLoomManifest`, generated by `AuroraLoomGenerator`,
// begun (and the kernel's tutorial stage dismissed) so the play is in stage `playing`; campaign mode; progress with the
// levels up to that number open (the seed picks where the session starts, so its level is always open; seed 0 opens
// level 1 only); the tutorial at its first step on levels 1 … 3 (`AuroraLoomGenerator.tutorialLevels`), else done.
//
// Actions (the engine refuses an undeclared control, a wrong value count, a non-finite or out-of-range value before the
// core sees it; called directly, the core refuses them itself with the same reasons):
//   ribbon.move [0…2, 0…1, 0…15]   ribbon, control (0 = wave, 1 = phase), step; whole numbers (`r02-g01.not-whole`
//                                  otherwise); applied with the play's current fingerprint as the expected one; the
//                                  tutorial advances (`AuroraLoomTutorialStep.advanced`); a win in campaign or daily
//                                  mode records the result (stars against the certified shortest); only campaign opens
//                                  the next level;
//   play.undo, play.redo           no values; the kernel's undo and redo (the tutorial never moves back);
//   level.next                     no values; the next open level after the current one, in cyclic order (level 1 is
//                                  always open), in campaign mode with a fresh play;
//   level.select [1…100]           an open level in campaign mode with a fresh play; `r02-g01.locked` for a closed one;
//   mode.daily [1…9999, 1…12, 1…31] the daily level of that calendar date (`AuroraLoomProgress.dailyLevel`) with a fresh
//                                  play; `r02-g01.date` for an invalid date;
//   mode.practice                  a fresh play of the current level with the allowance raised to 64 (no stars, no
//                                  unlocks);
//   mode.campaign                  a fresh play of the current level in campaign mode when it is open, otherwise of the
//                                  highest open level;
//   tutorial.dismiss               no values; the tutorial ends (already done: accepted, nothing changes).
// A kernel refusal (`AuroraLoomError`) becomes `.rule(code: error.reasonCode)`, for example `r02-g01.move` or
// `r02-g01.stage`. A refused action changes nothing.
//
// Digest ("r02-g01.aurora-loom.v2"): the level number, the play's fingerprint (not its record history, so undo restores
// the earlier digest; feature 304), the mode, the tutorial step and the progress (frontier, then each solved level in
// order with its best moves and stars); never the quality tier or a time. Snapshot schema 2: the JSON object
// `{"level", "mode", "progress", "records", "tutorial"}` with sorted keys; restoring replays the records on a fresh play
// of that level (the practice copy in practice mode) and throws `AuroraLoomRestoreRefusal` for a damaged payload, a level
// number outside 1 … 100 or a trace the kernel refuses. Migration 1 → 2: a schema-1 `{"level", "records"}` gains campaign
// mode, progress with the levels up to the saved one open and no tutorial key (restored as the level's first step).
//
// Quality: three host tiers, best first as the contract requires (`qualityProfile` level 0 is the best and no budget
// may rise). Host tier `t` draws `AuroraLoomTier.of(t)`: level-0 = 5 layers, 128 segments, 2 glow passes;
// level-1 = 3, 64, 1; level-2 = 1, 32, 0. Outcome: `won` or `failed` while the play is in that stage, otherwise nil.
import Foundation
import VisualCoreDiagnostics
import VisualCoreExperience
import VisualCorePersistence

/// The rule codes of Aurora Loom's adapter refusals (features 303 and 305).
public enum AuroraLoomExperienceRule {
    /// A value that must be a whole number (ribbon, control, step, level, date) and is not.
    public static let notWhole = "r02-g01.not-whole"
    /// `level.select` of a level that is not open yet (feature 305).
    public static let locked = "r02-g01.locked"
    /// `mode.daily` with a date that is not a calendar date (feature 305).
    public static let date = "r02-g01.date"
}

/// Why a saved Aurora Loom state was refused on restore (feature 303). A refused restore changes nothing.
public enum AuroraLoomRestoreRefusal: Error, Equatable, Sendable {
    /// The payload is not the schema-2 JSON object or a field has the wrong type.
    case damaged
    /// The level number is outside 1 … 100; the value is that number.
    case levelNumber(Int)
    /// The kernel refused the level's generation or the record trace; the value is that refusal.
    case kernel(AuroraLoomError)
}

/// The state of Aurora Loom as an experience (see the file header). Snapshot schema 2.
public struct AuroraLoomExperienceCore: ExperienceCore, Equatable {
    /// The experience's id in the catalog.
    public static let experienceID = "r02-g01.aurora-loom"
    /// The snapshot schema this build writes.
    public static let schemaVersion = 2
    /// The digest's domain string (schema 2).
    public static let digestDomain = "r02-g01.aurora-loom.v2"
    /// The action ids in declaration order.
    public static let actionIDs = ["ribbon.move", "play.undo", "play.redo", "level.next", "level.select", "mode.daily",
                                   "mode.practice", "mode.campaign", "tutorial.dismiss"]
    /// The level numbers of the catalog.
    public static let levelNumbers: ClosedRange<Int> = 1...100
    /// The move allowance of practice mode: the kernel's maximum (feature 305, research R4).
    public static let practiceAllowance = 64
    /// The outcome code of a won play.
    public static let wonCode = "won"
    /// The outcome code of a failed play.
    public static let failedCode = "failed"

    /// The number of the certified level being played (1 … 100).
    public private(set) var levelNumber: Int
    /// The kernel's play of that level (of its practice copy in practice mode).
    public private(set) var play: AuroraLoomPlay
    /// The player's progress: the open levels and each solved level's best moves and stars.
    public private(set) var progress: AuroraLoomProgress
    /// The mode: campaign, practice or the daily level.
    public private(set) var mode: AuroraLoomMode
    /// The tutorial step shown on this level (`done` when none is shown).
    public private(set) var tutorial: AuroraLoomTutorialStep
    /// The certified shortest solution of the level, the goal shown with the allowance and the measure of stars.
    /// Derived from the level number, so not in the digest or `==`.
    public private(set) var certifiedShortest: Int
    /// The state a reset returns to, derived from the seed (not in the digest or `==`).
    private let opening: Opening
    /// The host quality tier (0 = level-0, the best, … 2, clamped); presentation only — not in the digest, the
    /// snapshot or `==`.
    public private(set) var qualityTier = 0

    /// The seed's opening state, kept for `reset()`.
    private struct Opening: Equatable, Sendable {
        var levelNumber: Int
        var play: AuroraLoomPlay
        var progress: AuroraLoomProgress
        var tutorial: AuroraLoomTutorialStep
        var certifiedShortest: Int
    }

    /// The level number of the opening state (the one the seed chose); a reset returns to it.
    public var openingNumber: Int { opening.levelNumber }

    /// A state of the given parts in campaign mode unless `mode` says otherwise.
    private init(levelNumber: Int, play: AuroraLoomPlay, progress: AuroraLoomProgress, mode: AuroraLoomMode,
                 tutorial: AuroraLoomTutorialStep, certifiedShortest: Int, opening: Opening) {
        self.levelNumber = levelNumber
        self.play = play
        self.progress = progress
        self.mode = mode
        self.tutorial = tutorial
        self.certifiedShortest = certifiedShortest
        self.opening = opening
    }

    /// The level number a seed chooses: `seed % 100 + 1`.
    public static func levelNumber(forSeed seed: UInt64) -> Int {
        Int(seed % UInt64(levelNumbers.count)) + 1
    }

    /// The certified level and solution of manifest number `number` (1 … 100).
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func generated(number: Int) throws(AuroraLoomError) -> AuroraLoomGenerated {
        guard levelNumbers.contains(number) else { throw .level("number") }
        return try AuroraLoomGenerator.generate(AuroraLoomManifest.entries[number - 1])
    }

    /// The certified level of manifest number `number` (1 … 100).
    ///
    /// - Throws: as ``generated(number:)``.
    public static func level(number: Int) throws(AuroraLoomError) -> AuroraLoomLevel {
        try generated(number: number).level
    }

    /// The practice copy of `level`: every field kept, the allowance raised to ``practiceAllowance``.
    ///
    /// - Throws: the kernel's refusal of the copy (never for a certified level).
    public static func practiceLevel(of level: AuroraLoomLevel) throws(AuroraLoomError) -> AuroraLoomLevel {
        try AuroraLoomLevel(id: level.id, seed: level.seed, band: level.band, ribbons: level.ribbons, gates: level.gates,
                            omega: level.omega, tolerance: level.tolerance, allowance: practiceAllowance,
                            tutorial: level.tutorial)
    }

    /// A fresh play of `level` in stage `playing`: begun, with its kernel tutorial stage dismissed when it has one.
    ///
    /// - Throws: the kernel's refusal of `begin` or `dismissTutorial` (never for a new play).
    public static func freshPlay(of level: AuroraLoomLevel) throws(AuroraLoomError) -> AuroraLoomPlay {
        try AuroraLoomPlay.replay(level: level, records: [])
    }

    /// The first tutorial step of a fresh play of manifest number `number`: `wave(r)` on levels 1 … 3, with `r` the
    /// level-1 hint's ribbon; `done` on every other level.
    public static func firstTutorialStep(number: Int, play: AuroraLoomPlay) -> AuroraLoomTutorialStep {
        guard AuroraLoomGenerator.tutorialLevels.contains(number),
              let hint = AuroraLoomHints.hint(level: 1, play: play) else { return .done }
        return .first(ribbon: hint.ribbon)
    }

    /// The opening state of manifest number `number`: campaign mode, the levels up to `number` open.
    ///
    /// - Throws: as ``generated(number:)``.
    public static func opening(number: Int) throws(AuroraLoomError) -> AuroraLoomExperienceCore {
        let certified = try generated(number: number)
        let play = try freshPlay(of: certified.level)
        var progress = AuroraLoomProgress()
        progress.frontier = number
        let tutorial = firstTutorialStep(number: number, play: play)
        let opening = Opening(levelNumber: number, play: play, progress: progress, tutorial: tutorial,
                              certifiedShortest: certified.solution.shortest)
        return AuroraLoomExperienceCore(levelNumber: number, play: play, progress: progress, mode: .campaign,
                                        tutorial: tutorial, certifiedShortest: certified.solution.shortest,
                                        opening: opening)
    }

    /// An immutable copy of the play for drawing at the presenter's frame time `time` (ticks of 1/120 s). Reads only;
    /// the state and its digest do not change.
    public func snapshot(time: Double) -> AuroraLoomSceneSnapshot {
        AuroraLoomSceneSnapshot(play: play, time: time)
    }

    /// The tier the host quality tier draws: `AuroraLoomTier.of(qualityTier)` (both ordered richest first).
    public var renderTier: AuroraLoomTier { AuroraLoomTier.of(qualityTier) }

    // MARK: Teaching (feature 305)

    /// The hint of `level` (1 … 3, clamped) for the current play; nil once the play has ended. Reads only.
    public func hint(level: Int) -> AuroraLoomHint? {
        AuroraLoomHints.hint(level: level, play: play)
    }

    /// The explanation of the current failure; nil unless the play has failed. Reads only.
    public var failureExplanation: AuroraLoomFailureExplanation? {
        AuroraLoomFailureExplanation(play: play)
    }

    // MARK: Quality

    /// Three quality tiers: level-0 (richest) … level-2 (cheapest).
    public static var qualityTiers: Int { AuroraLoomTier.all.count }

    /// One level per host tier, best first: the element share is the drawn layers over 5, the iteration share the
    /// segments over 128 and the effect passes the glow passes; every level draws at the full resolution.
    public static var qualityProfile: QualityProfile {
        let best = AuroraLoomTier.all[0]
        var levels: [QualityLevel] = []
        for hostTier in 0..<AuroraLoomTier.all.count {
            let tier = AuroraLoomTier.of(hostTier)
            levels.append(QualityLevel(name: "level-\(hostTier)", resolutionShare: 1,
                                       elementShare: Double(tier.layers) / Double(best.layers),
                                       iterationShare: Double(tier.segments) / Double(best.segments),
                                       effectPasses: tier.glowPasses))
        }
        return (try? QualityProfile(levels: levels)) ?? .uniform(levels: levels.count)
    }

    /// Stores `tier` clamped to 0 ..< `qualityTiers`; the state and its digest do not change.
    public mutating func setQualityTier(_ tier: Int) {
        qualityTier = min(max(tier, 0), Self.qualityTiers - 1)
    }

    /// Equal states: the level number, the play, the progress, the mode and the tutorial step (not the quality tier
    /// or the opening state).
    public static func == (lhs: AuroraLoomExperienceCore, rhs: AuroraLoomExperienceCore) -> Bool {
        lhs.levelNumber == rhs.levelNumber && lhs.play == rhs.play && lhs.progress == rhs.progress
            && lhs.mode == rhs.mode && lhs.tutorial == rhs.tutorial
    }

    // MARK: Contract

    /// Schema 2 with the step 1 → 2 (``migratedToSchemaTwo(_:)``); a payload that does not decode is refused by its
    /// step.
    public static var migrations: MigrationChain {
        MigrationChain(currentVersion: schemaVersion, steps: [1: { payload in try migratedToSchemaTwo(payload) }])
    }

    /// The declared controls, built once.
    private static let declaredControls: [ExperienceControl] = [
        ExperienceControl(id: "ribbon.move", ranges: [0...2, 0...1, 0...15]),
        ExperienceControl(id: "play.undo"),
        ExperienceControl(id: "play.redo"),
        ExperienceControl(id: "level.next"),
        ExperienceControl(id: "level.select", ranges: [1...100]),
        ExperienceControl(id: "mode.daily", ranges: [1...9999, 1...12, 1...31]),
        ExperienceControl(id: "mode.practice"),
        ExperienceControl(id: "mode.campaign"),
        ExperienceControl(id: "tutorial.dismiss"),
    ]

    /// The nine controls with their declared ranges (see the file header).
    public static var controls: [ExperienceControl] { declaredControls }

    /// The opening state of level `seed % 100 + 1`, in stage `playing`; no clock is read.
    ///
    /// - Throws: `ExperienceFailure` with the kernel's reason code when the level cannot be generated.
    public static func prepare(seed: UInt64) async throws -> AuroraLoomExperienceCore {
        try Task.checkCancellation()
        let number = levelNumber(forSeed: seed)
        do throws(AuroraLoomError) {
            return try opening(number: number)
        } catch {
            throw ExperienceFailure(code: error.reasonCode, message: "Aurora Loom level \(number): \(error)")
        }
    }

    /// A host step changes nothing: the wave travel and shimmer move with the presenter's frame time, not the state.
    public mutating func update(step: Int) {}

    /// Carries out a well-formed action (see the file header); a refused action changes nothing.
    public mutating func apply(_ action: ExperienceAction) -> ActionResult {
        if let refusal = ExperienceInput.validate(control: action.control, values: action.values,
                                                  controls: Self.declaredControls) {
            return .rejected(refusal)
        }
        var wholeValues: [Int] = []
        for value in action.values {
            guard let whole = Self.whole(value) else { return .rejected(.rule(code: AuroraLoomExperienceRule.notWhole)) }
            wholeValues.append(whole)
        }
        do throws(AuroraLoomError) {
            switch action.control {
            case "ribbon.move":
                let move = AuroraLoomMove(ribbon: wholeValues[0], control: wholeValues[1] == 0 ? .wave : .phase,
                                          step: wholeValues[2])
                try play.apply(move, expecting: play.fingerprint)
                afterAcceptedPlay()
            case "play.undo":
                try play.undo()
                afterAcceptedPlay()
            case "play.redo":
                try play.redo()
                afterAcceptedPlay()
            case "level.next":
                var next = levelNumber % Self.levelNumbers.upperBound + 1
                while !progress.isOpen(next) { next = next % Self.levelNumbers.upperBound + 1 }
                try open(number: next, mode: .campaign)
            case "level.select":
                guard progress.isOpen(wholeValues[0]) else {
                    return .rejected(.rule(code: AuroraLoomExperienceRule.locked))
                }
                try open(number: wholeValues[0], mode: .campaign)
            case "mode.daily":
                guard let daily = AuroraLoomProgress.dailyLevel(year: wholeValues[0], month: wholeValues[1],
                                                                day: wholeValues[2]) else {
                    return .rejected(.rule(code: AuroraLoomExperienceRule.date))
                }
                try open(number: daily, mode: .daily(level: daily))
            case "mode.practice":
                try open(number: levelNumber, mode: .practice)
            case "mode.campaign":
                try open(number: progress.isOpen(levelNumber) ? levelNumber : progress.frontier, mode: .campaign)
            default:   // tutorial.dismiss
                tutorial = .done
            }
        } catch {
            return .rejected(.rule(code: error.reasonCode))
        }
        return .accepted
    }

    /// A fresh play of manifest number `number` in `mode` (the practice copy in practice mode), with the level's first
    /// tutorial step; changes nothing when the kernel refuses.
    private mutating func open(number: Int, mode: AuroraLoomMode) throws(AuroraLoomError) {
        let certified = try Self.generated(number: number)
        let level = mode == .practice ? try Self.practiceLevel(of: certified.level) : certified.level
        let fresh = try Self.freshPlay(of: level)
        levelNumber = number
        play = fresh
        self.mode = mode
        certifiedShortest = certified.solution.shortest
        tutorial = Self.firstTutorialStep(number: number, play: fresh)
    }

    /// After an accepted move, undo or redo: the tutorial advances by the latest record (the next instruction names
    /// the level-1 hint's ribbon) and a win outside practice records the result; only campaign opens the next level.
    private mutating func afterAcceptedPlay() {
        if let record = play.records.last {
            let ribbon = AuroraLoomHints.hint(level: 1, play: play)?.ribbon ?? record.ribbon
            tutorial = tutorial.advanced(by: record, stage: play.stage, hintRibbon: ribbon)
        }
        guard play.stage == .won else { return }
        switch mode {
        case .campaign:
            progress.record(level: levelNumber, moves: play.spent, shortest: certifiedShortest)
        case .daily:
            let frontier = progress.frontier
            progress.record(level: levelNumber, moves: play.spent, shortest: certifiedShortest)
            progress.frontier = frontier
        case .practice:
            break
        }
    }

    /// `value` as an `Int` when it is a finite whole number; nil otherwise.
    static func whole(_ value: Double) -> Int? {
        guard value.isFinite, value == value.rounded() else { return nil }
        return Int(value)
    }

    /// Back to the opening state the seed chose; the quality tier, which is not state, is kept.
    public mutating func reset() {
        levelNumber = opening.levelNumber
        play = opening.play
        progress = opening.progress
        mode = .campaign
        tutorial = opening.tutorial
        certifiedShortest = opening.certifiedShortest
    }

    /// `won` or `failed` while the play is in that stage; nil otherwise.
    public var outcome: ExperienceOutcome? {
        switch play.stage {
        case .won: ExperienceOutcome(code: Self.wonCode)
        case .failed: ExperienceOutcome(code: Self.failedCode)
        default: nil
        }
    }

    /// The digest form of a mode: "campaign", "practice" or "daily-<level>".
    static func digestText(_ mode: AuroraLoomMode) -> String {
        switch mode {
        case .campaign: "campaign"
        case .practice: "practice"
        case .daily(let level): "daily-\(level)"
        }
    }

    /// The digest form of a tutorial step: "wave-<r>", "phase-<r>", "harmony" or "done".
    static func digestText(_ step: AuroraLoomTutorialStep) -> String {
        switch step {
        case .wave(let ribbon): "wave-\(ribbon)"
        case .phase(let ribbon): "phase-\(ribbon)"
        case .harmony: "harmony"
        case .done: "done"
        }
    }

    /// "r02-g01.aurora-loom.v2", then the level number, the play's fingerprint, the mode, the tutorial step, the
    /// frontier and each solved level in order with its best moves and stars.
    public func writeDigest(into builder: inout DigestBuilder) throws(DigestError) {
        builder.add(Self.digestDomain)
        builder.add(levelNumber)
        // The play's fingerprint (steps, moves spent, stage) and not its record history, so undo restores the earlier
        // digest exactly (R2-G01-INV-05; feature 304 T-R02G0104-005).
        builder.add(play.fingerprint)
        builder.add(Self.digestText(mode))
        builder.add(Self.digestText(tutorial))
        builder.add(progress.frontier)
        let solved = progress.solved.keys.sorted()
        builder.add(count: solved.count)
        for level in solved {
            guard let result = progress.solved[level] else { continue }
            builder.add(level)
            builder.add(result.bestMoves)
            builder.add(result.stars)
        }
    }

    // MARK: Snapshot

    /// The schema-2 payload's JSON form; a missing tutorial is the level's first step.
    private struct Payload: Codable {
        var level: Int
        var records: [AuroraLoomRecord]
        var progress: AuroraLoomProgress
        var mode: AuroraLoomMode
        var tutorial: AuroraLoomTutorialStep?
    }

    /// The JSON encoder of payloads: sorted keys, unescaped slashes.
    private static func payloadEncoder() -> JSONEncoder {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return encoder
    }

    /// The schema-2 object of a schema-1 object `{"level", "records"}`: campaign mode, progress with the levels up to
    /// the saved one open, no tutorial key (restored as the level's first step).
    ///
    /// - Throws: ``AuroraLoomRestoreRefusal/damaged`` when `object` is not a schema-1 object.
    public static func migratedToSchemaTwo(_ object: [String: Any]) throws -> [String: Any] {
        guard let level = object["level"] as? Int, object["records"] is [Any] else {
            throw AuroraLoomRestoreRefusal.damaged
        }
        var progress = AuroraLoomProgress()
        progress.frontier = min(max(level, 1), levelNumbers.upperBound)
        var migrated = object
        migrated["progress"] = try JSONSerialization.jsonObject(with: try payloadEncoder().encode(progress))
        migrated["mode"] = try JSONSerialization.jsonObject(with: try payloadEncoder().encode(AuroraLoomMode.campaign))
        return migrated
    }

    /// The JSON object `{"level", "mode", "progress", "records", "tutorial"}` with sorted keys and unescaped slashes.
    public func snapshotPayload() throws -> Data {
        try Self.payloadEncoder().encode(Payload(level: levelNumber, records: play.records, progress: progress,
                                                 mode: mode, tutorial: tutorial))
    }

    /// The core of `payload`: the records replayed on a fresh play of the saved level (its practice copy in practice
    /// mode) with the saved progress, mode and tutorial step; a reset returns to the opening state `seed` chooses.
    ///
    /// - Throws: ``AuroraLoomRestoreRefusal`` for a damaged payload, a level number outside 1 … 100 or a level or
    ///   trace the kernel refuses.
    public static func restore(payload: Data, seed: UInt64) throws -> AuroraLoomExperienceCore {
        guard let decoded = try? JSONDecoder().decode(Payload.self, from: payload) else {
            throw AuroraLoomRestoreRefusal.damaged
        }
        guard levelNumbers.contains(decoded.level) else {
            throw AuroraLoomRestoreRefusal.levelNumber(decoded.level)
        }
        do throws(AuroraLoomError) {
            let certified = try generated(number: decoded.level)
            let level = decoded.mode == .practice ? try practiceLevel(of: certified.level) : certified.level
            let play = try AuroraLoomPlay.replay(level: level, records: decoded.records)
            var tutorial = AuroraLoomTutorialStep.done
            if let saved = decoded.tutorial {
                tutorial = saved
            } else {
                tutorial = firstTutorialStep(number: decoded.level, play: try freshPlay(of: level))
            }
            let start = try opening(number: levelNumber(forSeed: seed))
            return AuroraLoomExperienceCore(levelNumber: decoded.level, play: play, progress: decoded.progress,
                                            mode: decoded.mode, tutorial: tutorial,
                                            certifiedShortest: certified.solution.shortest, opening: start.opening)
        } catch {
            throw AuroraLoomRestoreRefusal.kernel(error)
        }
    }
}
