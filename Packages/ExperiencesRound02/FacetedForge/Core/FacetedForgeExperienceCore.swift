// FacetedForgeExperienceCore — feature 373 (R02-G08-03) T-R02G0803-005 (FR-R02G0803-005, 008, 009; clarification Q5;
// data-model.md "Controls"; contracts/api.md). The adapter of the Faceted Forge kernel to the shared experience
// contract. The core holds the level number and the kernel's `FacetedForgePlay`; it never draws and reads no clock. The
// presenter asks for an immutable `FacetedForgeSceneSnapshot` with its own preview choice (piece, direction, depth —
// presentation state of the controls, never kernel state) and presentation time (`snapshot(choice:time:)`), so the
// preview plane and the shimmer can move while the state and its digest stay put (renderer purity).
//
// Preparation: the certified level number `seed % 100 + 1` of `FacetedForgeManifest`, generated by
// `FacetedForgeGenerator` once per process (lazily, one level at a time), begun (and its tutorial dismissed) so the
// play is in stage `playing`.
//
// Actions (the engine refuses an undeclared control, a wrong value count, a non-finite or out-of-range value before the
// core sees it; called directly, the core refuses them itself with the same reasons):
//   piece.cut [0…20, 0…12, −24…24]  piece, direction and depth; whole numbers (`r02-g08.not-whole` otherwise); a piece
//                                   the play does not have (pieces … 20) is the kernel's `r02-g08.action`; a plane that
//                                   misses the piece is `r02-g08.miss`; any cut outside stage `playing` is
//                                   `r02-g08.stage`; spends one cut; a sliver fails, the target wins, the budget fails;
//   play.undo, play.redo            the kernel's exact undo and redo (`r02-g08.action` when there is nothing to undo or
//                                   redo; undo works in a failed play and returns it to playing; a won play is final);
//   level.next                      the next certified level (100 wraps to 1) with a fresh play.
// The declared piece range is 0 … 20 because a play has at most budget + 1 ≤ 21 pieces (`FacetedForgeLevel.budgets`).
// Every kernel action is applied with the play's current fingerprint as the expected one. A kernel refusal
// (`FacetedForgeError`) becomes `.rule(code: error.reasonCode)`. A refused action changes nothing.
//
// Digest ("r02-g08.faceted-forge.v1"): the level number and the play's fingerprint (not its record history, so undo
// restores the earlier digest exactly); never the quality tier, the preview choice or a time. Snapshot schema 1: the
// JSON object `{"level", "records"}` with sorted keys; restoring replays the records on a fresh play of that level
// (`FacetedForgePlay.replay`) and throws `FacetedForgeRestoreRefusal` for a damaged payload, a level number outside
// 1 … 100 or a trace the kernel refuses (a record of a newer schema among them). An envelope of a newer schema is
// refused by the engine before the core sees it.
//
// Feature 375 (R02-G08-05) T-R02G0805-004 (FR-R02G0805-001 … 005, 007; clarifications Q1–Q5): the core also holds the
// player's progress (`FacetedForgeProgress`: won levels with the fewest cuts made and stars, the open frontier), the
// mode (campaign, practice with the budget raised to the kernel's maximum 20, daily) and the tutorial step. New
// actions:
//   level.select [1…100]           an open level, fresh, in campaign mode (`r02-g08.locked` otherwise);
//   mode.daily [year, month, day]  the date's daily level, fresh (`r02-g08.date` for an impossible date); a daily level
//                                  still locked in the campaign is playable and is not opened;
//   mode.practice                  the current level fresh with the budget raised to 20;
//   mode.campaign                  the current level fresh in campaign mode (the frontier when it is not open);
//   tutorial.dismiss               the tutorial ends for this opening.
// Choosing daily or practice drops the left level's records (the play starts fresh). `level.next` moves to the next
// open level in campaign mode and is refused with `r02-g08.locked` when there is none (100 does not wrap). A win (the
// play reaching `won` on an accepted cut or redo) records `progress.record(level:cutsMade:smallest:mode:)` with the
// cuts made (the play's cut records, undone ones included) and the certified smallest cut count (campaign opens the
// next level; daily never does; practice records nothing). The tutorial starts at
// `FacetedForgeTutorialStep.initial(level:)` at every opening (levels 1 … 3 in every mode) and advances after each
// accepted new cut (a redo only ends it when it wins); undo and redo never move it otherwise. Digest
// "r02-g08.faceted-forge.v2": level, play fingerprint, progress and mode (never the tutorial step).
// Snapshot schema 2: `{"level", "mode", "progress", "records", "tutorial"}`; schema-1 payloads migrate (no won levels,
// the levels up to the saved level open, campaign mode, the tutorial at its initial step).
//
// Quality: three host tiers, best first as the contract requires (`qualityProfile` level 0 is the best and no budget
// may rise). Host tier `t` draws `FacetedForgeTier.of(t)`: level-0 = 3 bevel segments, 3 dispersion layers, 2 glow
// shells; level-1 = 2, 2, 1; level-2 = 1, 1, 0. Outcome: `won` or `failed` while the play is in that stage, else nil.
