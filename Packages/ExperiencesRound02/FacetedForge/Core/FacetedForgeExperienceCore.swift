// FacetedForgeExperienceCore — feature 373 (R02-G08-03) T-R02G0803-005 (FR-R02G0803-005, 008, 009; clarification Q5;
// data-model.md "Controls"; contracts/api.md). The adapter of the Faceted Forge kernel to the shared experience
// contract. The core holds the level number and the kernel's `FacetedForgePlay`; it never draws and reads no clock. The
// presenter asks for an immutable `FacetedForgeSceneSnapshot` with its own preview choice (piece, direction, depth —
// presentation state of the controls, never kernel state) and presentation time (`snapshot(choice:time:)`), so the
// preview plane and the shimmer can move while the state and its digest stay put (renderer purity).
//
// Preparation: the certified level number `seed % 100 + 1` of `FacetedForgeManifest`, generated by
// `FacetedForgeGenerator` once per process (lazily, one level at a time), begun (and its tutorial dismissed) so the
// play is in stage `playing`.
//
// Actions (the engine refuses an undeclared control, a wrong value count, a non-finite or out-of-range value before the
// core sees it; called directly, the core refuses them itself with the same reasons):
//   piece.cut [0…20, 0…12, −24…24]  piece, direction and depth; whole numbers (`r02-g08.not-whole` otherwise); a piece
//                                   the play does not have (pieces … 20) is the kernel's `r02-g08.action`; a plane that
//                                   misses the piece is `r02-g08.miss`; any cut outside stage `playing` is
//                                   `r02-g08.stage`; spends one cut; a sliver fails, the target wins, the budget fails;
//   play.undo, play.redo            the kernel's exact undo and redo (`r02-g08.action` when there is nothing to undo or
//                                   redo; undo works in a failed play and returns it to playing; a won play is final);
//   level.next                      the next certified level (100 wraps to 1) with a fresh play.
// The declared piece range is 0 … 20 because a play has at most budget + 1 ≤ 21 pieces (`FacetedForgeLevel.budgets`).
// Every kernel action is applied with the play's current fingerprint as the expected one. A kernel refusal
// (`FacetedForgeError`) becomes `.rule(code: error.reasonCode)`. A refused action changes nothing.
//
// Digest ("r02-g08.faceted-forge.v1"): the level number and the play's fingerprint (not its record history, so undo
// restores the earlier digest exactly); never the quality tier, the preview choice or a time. Snapshot schema 1: the
// JSON object `{"level", "records"}` with sorted keys; restoring replays the records on a fresh play of that level
// (`FacetedForgePlay.replay`) and throws `FacetedForgeRestoreRefusal` for a damaged payload, a level number outside
// 1 … 100 or a trace the kernel refuses (a record of a newer schema among them). An envelope of a newer schema is
// refused by the engine before the core sees it.
//
// Quality: three host tiers, best first as the contract requires (`qualityProfile` level 0 is the best and no budget
// may rise). Host tier `t` draws `FacetedForgeTier.of(t)`: level-0 = 3 bevel segments, 3 dispersion layers, 2 glow
// shells; level-1 = 2, 2, 1; level-2 = 1, 1, 0. Outcome: `won` or `failed` while the play is in that stage, else nil.
import Foundation
import Synchronization
import VisualCoreDiagnostics
import VisualCoreExperience
import VisualCorePersistence

/// The rule codes of Faceted Forge's adapter refusals (feature 373).
public enum FacetedForgeExperienceRule {
    /// A value that must be a whole number (piece, direction, depth) and is not.
    public static let notWhole = "r02-g08.not-whole"
}

/// Why a saved Faceted Forge state was refused on restore (feature 373). A refused restore changes nothing.
public enum FacetedForgeRestoreRefusal: Error, Equatable, Sendable {
    /// The payload is not the JSON object `{"level", "records"}` or a field has the wrong type.
    case damaged
    /// The level number is outside 1 … 100; the value is that number.
    case levelNumber(Int)
    /// The kernel refused the level's generation or the record trace; the value is that refusal.
    case kernel(FacetedForgeError)
}

/// The state of Faceted Forge as an experience (see the file header). Snapshot schema 1.
public struct FacetedForgeExperienceCore: ExperienceCore, Equatable {
    /// The experience's id in the catalog.
    public static let experienceID = "r02-g08.faceted-forge"
    /// The snapshot schema this build writes.
    public static let schemaVersion = 1
    /// The digest's domain string (schema 1).
    public static let digestDomain = "r02-g08.faceted-forge.v1"
    /// The action ids in declaration order.
    public static let actionIDs = ["piece.cut", "play.undo", "play.redo", "level.next"]
    /// The level numbers of the catalog.
    public static let levelNumbers: ClosedRange<Int> = 1...100
    /// The declared range of a piece index: a play has at most budget + 1 pieces (`FacetedForgeLevel.budgets`).
    public static let pieceRange: ClosedRange<Int> = 0...FacetedForgeLevel.budgets.upperBound
    /// The declared range of a cut direction: the 13 directions of `FacetedForgeDirection.all`.
    public static let directionRange: ClosedRange<Int> = 0...(FacetedForgeDirection.all.count - 1)
    /// The declared range of a cut depth: `FacetedForgeHalfSpace.depths` (−24 … 24).
    public static let depthRange: ClosedRange<Int> = FacetedForgeHalfSpace.depths
    /// The outcome code of a won play.
    public static let wonCode = "won"
    /// The outcome code of a failed play.
    public static let failedCode = "failed"

    /// The number of the certified level being played (1 … 100).
    public private(set) var levelNumber: Int
    /// The kernel's play of that level.
    public private(set) var play: FacetedForgePlay
    /// The level number the seed chose; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    public let openingNumber: Int
    /// The fresh play of the opening level; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    private let openingPlay: FacetedForgePlay
    /// The host quality tier (0 = level-0, the best, … 2, clamped); presentation only — not in the digest, the snapshot
    /// or `==`.
    public private(set) var qualityTier = 0

    /// A state playing `play` of level `levelNumber`, whose reset returns to `openingPlay` of `openingNumber`.
    init(levelNumber: Int, play: FacetedForgePlay, openingNumber: Int, openingPlay: FacetedForgePlay) {
        self.levelNumber = levelNumber
        self.play = play
        self.openingNumber = openingNumber
        self.openingPlay = openingPlay
    }

    /// The level number a seed chooses: `seed % 100 + 1`.
    public static func levelNumber(forSeed seed: UInt64) -> Int {
        Int(seed % UInt64(levelNumbers.count)) + 1
    }

    /// The certified level of manifest number `number` (1 … 100).
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func level(number: Int) throws(FacetedForgeError) -> FacetedForgeLevel {
        try generated(number: number).level
    }

    /// The certified levels generated so far, by manifest number: generation is deterministic but runs the solver, so
    /// each level is generated once per process, and only when first asked for (feature 373).
    private static let generatedCache = Mutex<[Int: FacetedForgeGenerated]>([:])

    /// The certified level and its solution of manifest number `number` (1 … 100), generated once per process.
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func generated(number: Int) throws(FacetedForgeError) -> FacetedForgeGenerated {
        guard levelNumbers.contains(number) else { throw .level("number") }
        if let cached = generatedCache.withLock({ $0[number] }) { return cached }
        let fresh = try FacetedForgeGenerator.generate(FacetedForgeManifest.entries[number - 1])
        generatedCache.withLock { $0[number] = fresh }
        return fresh
    }

    /// A fresh play of `level` in stage `playing`: begun, with its tutorial dismissed when it has one.
    ///
    /// - Throws: the kernel's refusal of `begin` or `dismissTutorial` (never for a new play).
    public static func freshPlay(of level: FacetedForgeLevel) throws(FacetedForgeError) -> FacetedForgePlay {
        try FacetedForgePlay.replay(level: level, records: [])
    }

    /// The opening state of manifest number `number`.
    ///
    /// - Throws: as ``level(number:)``.
    public static func opening(number: Int) throws(FacetedForgeError) -> FacetedForgeExperienceCore {
        let play = try freshPlay(of: try level(number: number))
        return FacetedForgeExperienceCore(levelNumber: number, play: play, openingNumber: number, openingPlay: play)
    }

    // MARK: Scene snapshots

    /// An immutable copy of the play and the level number with the preview `choice` for drawing at the presenter's
    /// presentation time `time` (seconds; a non-finite time becomes 0). Reads only; the state and its digest do not
    /// change.
    public func snapshot(choice: FacetedForgePreviewChoice, time: Double) -> FacetedForgeSceneSnapshot {
        FacetedForgeSceneSnapshot(play: play, levelNumber: levelNumber, choice: choice, time: time)
    }

    /// As ``snapshot(choice:time:)`` with the choice of `chosen` piece, `direction` and `depth` (contracts/api.md;
    /// the direction and depth are clamped as `FacetedForgePreviewChoice` does).
    public func snapshot(chosen: Int, direction: Int, depth: Int, time: Double) -> FacetedForgeSceneSnapshot {
        snapshot(choice: FacetedForgePreviewChoice(piece: chosen, direction: direction, depth: depth), time: time)
    }

    /// As ``snapshot(choice:time:)`` with the play's opening preview choice, `FacetedForgePreviewChoice.initial(play)`.
    public func snapshot(time: Double) -> FacetedForgeSceneSnapshot {
        snapshot(choice: FacetedForgePreviewChoice.initial(play), time: time)
    }

    /// The tier the host quality tier draws: `FacetedForgeTier.of(qualityTier)` (both ordered richest first).
    public var renderTier: FacetedForgeTier { FacetedForgeTier.of(qualityTier) }

    // MARK: Quality

    /// Three quality tiers: level-0 (richest) … level-2 (cheapest).
    public static var qualityTiers: Int { FacetedForgeTier.all.count }

    /// One level per host tier, best first: the element share is the bevel segments over the best tier's 3, the
    /// iteration share the dispersion layers over 3 and the effect passes the glow shells; every level draws at the
    /// full resolution.
    public static var qualityProfile: QualityProfile {
        let best = FacetedForgeTier.all[0]
        var levels: [QualityLevel] = []
        for hostTier in 0..<FacetedForgeTier.all.count {
            let tier = FacetedForgeTier.of(hostTier)
            levels.append(QualityLevel(name: tier.name, resolutionShare: 1,
                                       elementShare: Double(tier.bevelSegments) / Double(best.bevelSegments),
                                       iterationShare: Double(tier.dispersionLayers) / Double(best.dispersionLayers),
                                       effectPasses: tier.glowShells))
        }
        return (try? QualityProfile(levels: levels)) ?? .uniform(levels: levels.count)
    }

    /// Stores `tier` clamped to 0 ..< `qualityTiers`; the state and its digest do not change.
    public mutating func setQualityTier(_ tier: Int) {
        qualityTier = min(max(tier, 0), Self.qualityTiers - 1)
    }

    /// Equal states: the level number and the play (not the quality tier or the opening level).
    public static func == (lhs: FacetedForgeExperienceCore, rhs: FacetedForgeExperienceCore) -> Bool {
        lhs.levelNumber == rhs.levelNumber && lhs.play == rhs.play
    }

    // MARK: Contract

    /// Schema 1, the first version: no migration steps.
    public static var migrations: MigrationChain { MigrationChain(currentVersion: schemaVersion) }

    /// The declared controls, built once: the piece, direction and depth ranges as `Double` ranges.
    private static let declaredControls: [ExperienceControl] = [
        ExperienceControl(id: "piece.cut",
                          ranges: [declared(pieceRange), declared(directionRange), declared(depthRange)]),
        ExperienceControl(id: "play.undo"),
        ExperienceControl(id: "play.redo"),
        ExperienceControl(id: "level.next"),
    ]

    /// `range` as the `Double` range a control declares.
    private static func declared(_ range: ClosedRange<Int>) -> ClosedRange<Double> {
        Double(range.lowerBound)...Double(range.upperBound)
    }

    /// The four controls with their declared ranges (see the file header); all but `piece.cut` take no values.
    public static var controls: [ExperienceControl] { declaredControls }

    /// The opening state of level `seed % 100 + 1`, in stage `playing`; no clock is read.
    ///
    /// - Throws: `ExperienceFailure` with the kernel's reason code when the level cannot be generated.
    public static func prepare(seed: UInt64) async throws -> FacetedForgeExperienceCore {
        try Task.checkCancellation()
        let number = levelNumber(forSeed: seed)
        do throws(FacetedForgeError) {
            return try opening(number: number)
        } catch {
            throw ExperienceFailure(code: error.reasonCode, message: "Faceted Forge level \(number): \(error)")
        }
    }

    /// A host step changes nothing: the crystal changes only on an action, and the shimmer moves with the presenter's
    /// time, not the state.
    public mutating func update(step: Int) {}

    /// Carries out a well-formed action (see the file header); a refused action changes nothing.
    public mutating func apply(_ action: ExperienceAction) -> ActionResult {
        if let refusal = ExperienceInput.validate(control: action.control, values: action.values,
                                                  controls: Self.declaredControls) {
            return .rejected(refusal)
        }
        var values: [Int] = []
        for value in action.values {
            guard let whole = Self.whole(value) else {
                return .rejected(.rule(code: FacetedForgeExperienceRule.notWhole))
            }
            values.append(whole)
        }
        do throws(FacetedForgeError) {
            switch action.control {
            case "piece.cut":
                try play.apply(.cut(values[0], values[1], values[2]), expecting: play.fingerprint)
            case "play.undo":
                try play.undo()
            case "play.redo":
                try play.redo()
            default:   // level.next
                let next = levelNumber % Self.levelNumbers.upperBound + 1
                let fresh = try Self.freshPlay(of: try Self.level(number: next))
                levelNumber = next
                play = fresh
            }
        } catch {
            return .rejected(.rule(code: error.reasonCode))
        }
        return .accepted
    }

    /// `value` as an `Int` when it is a finite whole number; nil otherwise.
    static func whole(_ value: Double) -> Int? {
        guard value.isFinite, value == value.rounded() else { return nil }
        return Int(value)
    }

    /// Back to the fresh play of the level the seed chose; the quality tier, which is not state, is kept.
    public mutating func reset() {
        levelNumber = openingNumber
        play = openingPlay
    }

    /// `won` or `failed` while the play is in that stage; nil otherwise.
    public var outcome: ExperienceOutcome? {
        switch play.stage {
        case .won: ExperienceOutcome(code: Self.wonCode)
        case .failed: ExperienceOutcome(code: Self.failedCode)
        default: nil
        }
    }

    /// "r02-g08.faceted-forge.v1", then the level number and the play's fingerprint (level, pieces, cuts, stage,
    /// failure).
    public func writeDigest(into builder: inout DigestBuilder) throws(DigestError) {
        builder.add(Self.digestDomain)
        builder.add(levelNumber)
        // The play's fingerprint and not its record history, so undo restores the earlier digest exactly.
        builder.add(play.fingerprint)
    }

    // MARK: Snapshot

    /// The payload's JSON form.
    private struct Payload: Codable {
        var level: Int
        var records: [FacetedForgeRecord]
    }

    /// The JSON object `{"level", "records"}` with sorted keys and unescaped slashes.
    public func snapshotPayload() throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try encoder.encode(Payload(level: levelNumber, records: play.records))
    }

    /// The core of `payload`: the records replayed on a fresh play of the saved level; a reset returns to the level
    /// `seed` chooses.
    ///
    /// - Throws: ``FacetedForgeRestoreRefusal`` for a damaged payload, a level number outside 1 … 100 or a level or
    ///   trace the kernel refuses.
    public static func restore(payload: Data, seed: UInt64) throws -> FacetedForgeExperienceCore {
        guard let decoded = try? JSONDecoder().decode(Payload.self, from: payload) else {
            throw FacetedForgeRestoreRefusal.damaged
        }
        guard levelNumbers.contains(decoded.level) else {
            throw FacetedForgeRestoreRefusal.levelNumber(decoded.level)
        }
        do throws(FacetedForgeError) {
            let saved = try level(number: decoded.level)
            let play = try FacetedForgePlay.replay(level: saved, records: decoded.records)
            let openingNumber = levelNumber(forSeed: seed)
            let openingPlay = openingNumber == decoded.level
                ? try freshPlay(of: saved)
                : try freshPlay(of: try Self.level(number: openingNumber))
            return FacetedForgeExperienceCore(levelNumber: decoded.level, play: play,
                                              openingNumber: openingNumber, openingPlay: openingPlay)
        } catch {
            throw FacetedForgeRestoreRefusal.kernel(error)
        }
    }
}
