/// The rule codes of Chrono Constellator's adapter refusals (feature 353).
public enum ChronoConstellatorExperienceRule {
    /// A value that must be a whole number (star, phase, tick, length) and is not.
    public static let notWhole = "r02-g06.not-whole"
    /// A level that is not open yet, or no next open level (feature 355).
    public static let locked = "r02-g06.locked"
    /// An impossible calendar date (feature 355).
    public static let date = "r02-g06.date"
    /// No verified result with a trace to replay, or a replay control outside replay (feature 357).
    public static let noReplay = "r02-g06.no-replay"
    /// The replay has no further action: the trace is over or the play ended (feature 357).
    public static let replayEnd = "r02-g06.replay-end"
    /// An action that is not allowed during replay (feature 357).
    public static let replay = "r02-g06.replay"
}

/// Why a saved Chrono Constellator state was refused on restore (feature 353). A refused restore changes nothing.
public enum ChronoConstellatorRestoreRefusal: Error, Equatable, Sendable {
    /// The payload is not the JSON object of its schema, a field has the wrong type, or the progress or the mode is
    /// invalid (feature 355).
    case damaged
    /// The level number is outside 1 … 100; the value is that number.
    case levelNumber(Int)
    /// The kernel refused the level's generation or the record trace; the value is that refusal.
    case kernel(ChronoConstellatorError)
}

/// The state of Chrono Constellator as an experience (see the file header). Snapshot schema 3.
public struct ChronoConstellatorExperienceCore: ExperienceCore, Equatable {
    /// The experience's id in the catalog.
    public static let experienceID = "r02-g06.chrono-constellator"
    /// The snapshot schema this build writes.
    public static let schemaVersion = 3
    /// The digest's domain string (schema 3).
    public static let digestDomain = "r02-g06.chrono-constellator.v3"
    /// The action ids in declaration order.
    public static let actionIDs = ["star.phase", "star.hold", "star.release", "time.step", "time.rewind", "play.undo",
                                   "play.redo", "level.next", "level.select", "mode.daily", "mode.practice",
                                   "mode.campaign", "tutorial.dismiss", "replay.start", "replay.step", "replay.stop",
                                   "settings.sound"]
    /// The declared range of `settings.sound`: 0 off, 1 on (feature 357).
    public static let soundRange: ClosedRange<Int> = 0...1
    /// The budget of a practice play: the kernel's maximum (`ChronoConstellatorMode.practiceBudget`, 20).
    public static let practiceBudget = ChronoConstellatorMode.practiceBudget
    /// The level numbers of the catalog.
    public static let levelNumbers: ClosedRange<Int> = 1...100
    /// The declared range of a star index: at most five stars.
    public static let starRange: ClosedRange<Int> = 0...4
    /// The declared range of a start phase: loops have at most 32 cells.
    public static let phaseRange: ClosedRange<Int> = 0...31
    /// The declared range of a hold's first tick: the longest tick limit is 1,200.
    public static let holdStartRange: ClosedRange<Int> = 1...1_200
    /// The outcome code of a won play.
    public static let wonCode = "won"
    /// The outcome code of a failed play.
    public static let failedCode = "failed"

    /// The number of the certified level being played (1 … 100).
    public private(set) var levelNumber: Int
    /// The kernel's play of that level (of its practice copy in practice mode).
    public private(set) var play: ChronoConstellatorPlay
    /// The player's progress (feature 355): in the digest and the snapshot.
    public private(set) var progress: ChronoConstellatorProgress
    /// The mode (feature 355): in the digest and the snapshot.
    public private(set) var mode: ChronoConstellatorMode
    /// The tutorial step (feature 355): in the snapshot, not in the digest.
    public private(set) var tutorial: ChronoConstellatorTutorialStep
    /// The certified smallest edit count of the current level (stars). Derived from the level number.
    public private(set) var certifiedSmallest: Int
    /// How many saved results the last restore dropped because they did not verify (feature 357); not in the digest,
    /// the snapshot or `==`.
    public private(set) var reconciliationDropped = 0
    /// The player's sound choice (feature 357, FR-R02G0607-007), set by `settings.sound`: in the snapshot (key
    /// `"sound"`) and `==`, never in the digest; off at an opening, after a reset and in a migrated save.
    public private(set) var soundOn = false
    /// The level number the seed chose; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    public let openingNumber: Int
    /// The opening state; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    private let opening: Opening

    /// What a reset restores (feature 355).
    struct Opening: Sendable {
        /// The fresh play of the opening level.
        let play: ChronoConstellatorPlay
        /// The opening progress: the levels up to the opening level open, none won.
        let progress: ChronoConstellatorProgress
        /// The opening level's initial tutorial step.
        let tutorial: ChronoConstellatorTutorialStep
        /// The opening level's certified smallest edit count.
        let certifiedSmallest: Int
    }
    /// The host quality tier (0 = level-0, the best, … 2, clamped); presentation only — not in the digest, the
    /// snapshot or `==`.
    public private(set) var qualityTier = 0

    /// A state playing `play` of level `levelNumber` with `progress`, `mode` and `tutorial`, whose reset returns to
    /// `opening` of `openingNumber`.
    init(levelNumber: Int, play: ChronoConstellatorPlay, progress: ChronoConstellatorProgress,
         mode: ChronoConstellatorMode, tutorial: ChronoConstellatorTutorialStep, certifiedSmallest: Int,
         openingNumber: Int, opening: Opening) {
        self.levelNumber = levelNumber
        self.play = play
        self.progress = progress
        self.mode = mode
        self.tutorial = tutorial
        self.certifiedSmallest = certifiedSmallest
        self.openingNumber = openingNumber
        self.opening = opening
    }

    /// The level number a seed chooses: `seed % 100 + 1`.
    public static func levelNumber(forSeed seed: UInt64) -> Int {
        Int(seed % UInt64(levelNumbers.count)) + 1
    }

    /// The certified level of manifest number `number` (1 … 100).
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func level(number: Int) throws(ChronoConstellatorError) -> ChronoConstellatorLevel {
        try generated(number: number).level
    }

    /// The certified levels generated so far, by manifest number: generation is deterministic but runs the solver, so
    /// each level is generated once per process, and only when first asked for (feature 353).
    private static let generatedCache = Mutex<[Int: ChronoConstellatorGenerated]>([:])

    /// The certified level and its proof of manifest number `number` (1 … 100), generated once per process.
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func generated(number: Int) throws(ChronoConstellatorError) -> ChronoConstellatorGenerated {
        guard levelNumbers.contains(number) else { throw .level("number") }
        if let cached = generatedCache.withLock({ $0[number] }) { return cached }
        let fresh = try ChronoConstellatorGenerator.generate(ChronoConstellatorManifest.entries[number - 1])
        generatedCache.withLock { $0[number] = fresh }
        return fresh
    }

    /// A fresh play of `level` in stage `playing`: begun, with its tutorial dismissed when it has one.
    ///
    /// - Throws: the kernel's refusal of `begin` or `dismissTutorial` (never for a new play).
    public static func freshPlay(of level: ChronoConstellatorLevel)
        throws(ChronoConstellatorError) -> ChronoConstellatorPlay {
        try ChronoConstellatorPlay.replay(level: level, records: [])
    }

    /// The practice copy of `level` (feature 355): every field kept, the budget raised to ``practiceBudget``.
    ///
    /// - Throws: the kernel's refusal of the copy (never for a certified level).
    public static func practiceLevel(of level: ChronoConstellatorLevel)
        throws(ChronoConstellatorError) -> ChronoConstellatorLevel {
        try ChronoConstellatorLevel(id: level.id, seed: level.seed, difficulty: level.difficulty, columns: level.columns,
                                    rows: level.rows, stars: level.stars,
                                    budget: ChronoConstellatorMode.practice.budget(base: level.budget),
                                    tickLimit: level.tickLimit, tutorial: level.tutorial)
    }

    /// The level a play of `certified` in `mode` uses: the practice copy in practice mode, otherwise the certified
    /// level.
    ///
    /// - Throws: as ``practiceLevel(of:)``.
    static func playedLevel(of certified: ChronoConstellatorGenerated,
                            mode: ChronoConstellatorMode) throws(ChronoConstellatorError) -> ChronoConstellatorLevel {
        mode == .practice ? try practiceLevel(of: certified.level) : certified.level
    }

    /// The opening state of manifest number `number`: campaign mode, the levels up to `number` open, none won, the
    /// tutorial at its initial step.
    ///
    /// - Throws: as ``level(number:)``.
    public static func opening(number: Int) throws(ChronoConstellatorError) -> ChronoConstellatorExperienceCore {
        let certified = try generated(number: number)
        let play = try freshPlay(of: certified.level)
        var progress = ChronoConstellatorProgress()
        progress.open(through: number)
        let tutorial = ChronoConstellatorTutorialStep.initial(level: number)
        let opening = Opening(play: play, progress: progress, tutorial: tutorial,
                              certifiedSmallest: certified.difficulty.smallest)
        return ChronoConstellatorExperienceCore(levelNumber: number, play: play, progress: progress, mode: .campaign,
                                                tutorial: tutorial, certifiedSmallest: certified.difficulty.smallest,
                                                openingNumber: number, opening: opening)
    }

    /// The hint of `level` (1 … 3) for the current play (``ChronoConstellatorHints/hint(level:play:)``); nil unless
    /// the play is playing, paused or failed. Reads only.
    public func hint(level: Int) -> ChronoConstellatorHint? {
        ChronoConstellatorHints.hint(level: level, play: play)
    }

    /// The explanation of the current play's failure; nil unless the play failed.
    public var failureExplanation: ChronoConstellatorFailureExplanation? {
        ChronoConstellatorFailureExplanation(play: play)
    }

    /// An immutable copy of the play and the level number for drawing at the presenter's presentation time `time`
    /// (seconds; a non-finite time becomes 0). Reads only; the state and its digest do not change.
    public func snapshot(time: Double) -> ChronoConstellatorSceneSnapshot {
        ChronoConstellatorSceneSnapshot(play: play, levelNumber: levelNumber, time: time)
    }

    /// The tier the host quality tier draws: `ChronoConstellatorTier.of(qualityTier)` (both ordered richest first).
    public var renderTier: ChronoConstellatorTier { ChronoConstellatorTier.of(qualityTier) }

    // MARK: Quality

    /// Three quality tiers: level-0 (richest) … level-2 (cheapest).
    public static var qualityTiers: Int { ChronoConstellatorTier.all.count }

    /// One level per host tier, best first: the element share is the ribbon segments drawn (ticks × segments per tick)
    /// over the best tier's 96, the iteration share the ribbon ticks over 24 and the effect passes the glow shells;
    /// every level draws at the full resolution.
    public static var qualityProfile: QualityProfile {
        let best = ChronoConstellatorTier.all[0]
        let bestSegments = Double(best.ribbonTicks * best.segments)
        var levels: [QualityLevel] = []
        for hostTier in 0..<ChronoConstellatorTier.all.count {
            let tier = ChronoConstellatorTier.of(hostTier)
            levels.append(QualityLevel(name: tier.name, resolutionShare: 1,
                                       elementShare: Double(tier.ribbonTicks * tier.segments) / bestSegments,
                                       iterationShare: Double(tier.ribbonTicks) / Double(best.ribbonTicks),
                                       effectPasses: tier.glowShells))
        }
        return (try? QualityProfile(levels: levels)) ?? .uniform(levels: levels.count)
    }

    /// Stores `tier` clamped to 0 ..< `qualityTiers`; the state and its digest do not change.
    public mutating func setQualityTier(_ tier: Int) {
        qualityTier = min(max(tier, 0), Self.qualityTiers - 1)
    }

    /// Equal states: the level number, the play, the progress, the mode, the tutorial step and the sound choice (not the
    /// quality tier, the opening level or the dropped count).
    public static func == (lhs: ChronoConstellatorExperienceCore, rhs: ChronoConstellatorExperienceCore) -> Bool {
        lhs.levelNumber == rhs.levelNumber && lhs.play == rhs.play && lhs.progress == rhs.progress
            && lhs.mode == rhs.mode && lhs.tutorial == rhs.tutorial && lhs.soundOn == rhs.soundOn
    }

    // MARK: Contract

    /// Schema 3 with the steps 1 → 2 (``migratedToSchemaTwo(_:)``) and 2 → 3 (``migratedToSchemaThree(_:)``); a
    /// payload that does not decode is refused.
    public static var migrations: MigrationChain {
        MigrationChain(currentVersion: schemaVersion, steps: [1: { payload in try migratedToSchemaTwo(payload) },
                                                             2: { payload in try migratedToSchemaThree(payload) }])
    }

    /// The schema-3 object of a schema-2 object (feature 357): every solved result gains an empty `trace` and
    /// `verified` false, and the sound choice is off.
    ///
    /// - Throws: ``ChronoConstellatorRestoreRefusal/damaged`` when `object` has no progress with a solved list.
    public static func migratedToSchemaThree(_ object: [String: Any]) throws -> [String: Any] {
        guard var progress = object["progress"] as? [String: Any], let solved = progress["solved"] as? [Any] else {
            throw ChronoConstellatorRestoreRefusal.damaged
        }
        var entries: [Any] = []
        for entry in solved {
            guard var result = entry as? [String: Any] else {
                entries.append(entry)
                continue
            }
            result["trace"] = [Any]()
            result["verified"] = false
            entries.append(result)
        }
        progress["solved"] = entries
        var migrated = object
        migrated["progress"] = progress
        migrated["sound"] = false
        return migrated
    }

    /// The schema-2 object of a schema-1 object `{"level", "records"}` (feature 355): no won levels with the levels up
    /// to the saved level open, campaign mode, no tutorial key (restore starts the tutorial at its initial step).
    ///
    /// - Throws: ``ChronoConstellatorRestoreRefusal/damaged`` when `object` is not a schema-1 object.
    public static func migratedToSchemaTwo(_ object: [String: Any]) throws -> [String: Any] {
        guard let level = object["level"] as? Int, object["records"] is [Any] else {
            throw ChronoConstellatorRestoreRefusal.damaged
        }
        var progress = ChronoConstellatorProgress()
        progress.open(through: level)
        var migrated = object
        migrated["progress"] = try JSONSerialization.jsonObject(with: try payloadEncoder().encode(progress))
        migrated["mode"] = try JSONSerialization.jsonObject(
            with: try payloadEncoder().encode(ChronoConstellatorMode.campaign))
        return migrated
    }

    /// The encoder of payloads and digested values: sorted keys, unescaped slashes.
    static func payloadEncoder() -> JSONEncoder {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return encoder
    }

    /// The declared controls, built once: the star, phase, tick and length ranges as `Double` ranges.
    private static let declaredControls: [ExperienceControl] = [
        ExperienceControl(id: "star.phase", ranges: [declared(starRange), declared(phaseRange)]),
        ExperienceControl(id: "star.hold", ranges: [declared(starRange), declared(holdStartRange),
                                                    declared(ChronoConstellatorTimeline.holdLengths)]),
        ExperienceControl(id: "star.release", ranges: [declared(starRange), declared(holdStartRange)]),
        ExperienceControl(id: "time.step", ranges: [declared(ChronoConstellatorPlay.steps)]),
        ExperienceControl(id: "time.rewind"),
        ExperienceControl(id: "play.undo"),
        ExperienceControl(id: "play.redo"),
        ExperienceControl(id: "level.next"),
        ExperienceControl(id: "level.select", ranges: [declared(levelNumbers)]),
        ExperienceControl(id: "mode.daily", ranges: [declared(ChronoConstellatorProgress.dailyYears), 1...12, 1...31]),
        ExperienceControl(id: "mode.practice"),
        ExperienceControl(id: "mode.campaign"),
        ExperienceControl(id: "tutorial.dismiss"),
        ExperienceControl(id: "replay.start", ranges: [declared(levelNumbers)]),
        ExperienceControl(id: "replay.step"),
        ExperienceControl(id: "replay.stop"),
        ExperienceControl(id: "settings.sound", ranges: [declared(soundRange)]),
    ]

    /// `range` as the `Double` range a control declares.
    private static func declared(_ range: ClosedRange<Int>) -> ClosedRange<Double> {
        Double(range.lowerBound)...Double(range.upperBound)
    }

    /// The seventeen controls with their declared ranges (see the file header); all but the phase, hold, release, step,
    /// `level.select`, `mode.daily`, `replay.start` and `settings.sound` take no values.
    public static var controls: [ExperienceControl] { declaredControls }

    /// The opening state of level `seed % 100 + 1`, in stage `playing`, campaign mode, the levels up to it open; no
    /// clock is read.
    ///
    /// - Throws: `ExperienceFailure` with the kernel's reason code when the level cannot be generated.
    public static func prepare(seed: UInt64) async throws -> ChronoConstellatorExperienceCore {
        try Task.checkCancellation()
        let number = levelNumber(forSeed: seed)
        do throws(ChronoConstellatorError) {
            return try opening(number: number)
        } catch {
            throw ExperienceFailure(code: error.reasonCode, message: "Chrono Constellator level \(number): \(error)")
        }
    }

    /// A host step changes nothing: time runs only on `time.step`, and the ribbons shimmer with the presenter's time,
    /// not the state.
    public mutating func update(step: Int) {}

    /// Carries out a well-formed action (see the file header); a refused action changes nothing.
    public mutating func apply(_ action: ExperienceAction) -> ActionResult {
        if let refusal = ExperienceInput.validate(control: action.control, values: action.values,
                                                  controls: Self.declaredControls) {
            return .rejected(refusal)
        }
        var values: [Int] = []
        for value in action.values {
            guard let whole = Self.whole(value) else {
                return .rejected(.rule(code: ChronoConstellatorExperienceRule.notWhole))
            }
            values.append(whole)
        }
        if case .replay = mode, !Self.replayControls.contains(action.control) {
            return .rejected(.rule(code: ChronoConstellatorExperienceRule.replay))
        }
        do throws(ChronoConstellatorError) {
            switch action.control {
            case "star.phase":
                try play.apply(.phase(values[0], values[1]), expecting: play.fingerprint)
                advanceTutorial()
            case "star.hold":
                try play.apply(.hold(values[0], values[1], values[2]), expecting: play.fingerprint)
                advanceTutorial()
            case "star.release":
                try play.apply(.release(values[0], values[1]), expecting: play.fingerprint)
                advanceTutorial()
            case "time.step":
                try play.apply(.step(values[0]), expecting: play.fingerprint)
                advanceTutorial()
                recordIfWon()
            case "time.rewind":
                try play.apply(.rewind, expecting: play.fingerprint)
                advanceTutorial()
            case "play.undo":
                try play.undo()
            case "play.redo":
                try play.redo()
                advanceTutorial()
                recordIfWon()
            case "level.next":
                guard let next = progress.nextOpen(after: levelNumber) else {
                    return .rejected(.rule(code: ChronoConstellatorExperienceRule.locked))
                }
                try open(number: next, mode: .campaign)
            case "level.select":
                guard progress.isOpen(values[0]) else {
                    return .rejected(.rule(code: ChronoConstellatorExperienceRule.locked))
                }
                try open(number: values[0], mode: .campaign)
            case "mode.daily":
                guard let daily = ChronoConstellatorProgress.dailyLevel(year: values[0], month: values[1],
                                                                        day: values[2]) else {
                    return .rejected(.rule(code: ChronoConstellatorExperienceRule.date))
                }
                try open(number: daily, mode: .daily(level: daily))
            case "mode.practice":
                try open(number: levelNumber, mode: .practice)
            case "mode.campaign":
                try open(number: progress.isOpen(levelNumber) ? levelNumber : progress.frontier, mode: .campaign)
            case "replay.start":
                guard let result = progress.solved[values[0]], result.verified, !result.trace.isEmpty else {
                    return .rejected(.rule(code: ChronoConstellatorExperienceRule.noReplay))
                }
                try open(number: values[0], mode: .replay(level: values[0]))
                tutorial = .done
            case "replay.step":
                guard case .replay(let level) = mode, let result = progress.solved[level], result.verified else {
                    return .rejected(.rule(code: ChronoConstellatorExperienceRule.noReplay))
                }
                // Replay never undoes, so each trace action made exactly one record.
                let index = play.records.count
                guard play.stage == .playing, index < result.trace.count else {
                    return .rejected(.rule(code: ChronoConstellatorExperienceRule.replayEnd))
                }
                try play.apply(result.trace[index], expecting: play.fingerprint)
            case "replay.stop":
                guard case .replay(let level) = mode else {
                    return .rejected(.rule(code: ChronoConstellatorExperienceRule.noReplay))
                }
                try open(number: progress.isOpen(level) ? level : progress.frontier, mode: .campaign)
            case "settings.sound":
                soundOn = values[0] == 1
            default:   // tutorial.dismiss
                tutorial = tutorial.dismissed()
            }
        } catch {
            return .rejected(.rule(code: error.reasonCode))
        }
        return .accepted
    }

    /// `value` as an `Int` when it is a finite whole number; nil otherwise.
    static func whole(_ value: Double) -> Int? {
        guard value.isFinite, value == value.rounded() else { return nil }
        return Int(value)
    }

    /// Advances the tutorial step by the play's latest accepted record
    /// (`ChronoConstellatorTutorialStep.advanced(after:planIsRun:ended:)`): the hint's plan is computed only for a phase
    /// change while the step is `shift`; an undo or a redo never moves the step back.
    private mutating func advanceTutorial() {
        guard tutorial != .done, let kind = play.records.last?.kind else { return }
        let ended = play.stage == .won || play.stage == .failed
        var planIsRun = false
        if !ended, tutorial == .shift, kind == .phase, case .run = ChronoConstellatorHints.plan(play) {
            planIsRun = true
        }
        tutorial = tutorial.advanced(after: kind, planIsRun: planIsRun, ended: ended)
    }

    /// A fresh play of manifest number `number` in `mode` (the practice copy in practice mode) with the level's initial
    /// tutorial step; the records of the level left are dropped. Changes nothing when the kernel refuses.
    private mutating func open(number: Int, mode: ChronoConstellatorMode) throws(ChronoConstellatorError) {
        let certified = try Self.generated(number: number)
        let fresh = try Self.freshPlay(of: try Self.playedLevel(of: certified, mode: mode))
        levelNumber = number
        play = fresh
        self.mode = mode
        certifiedSmallest = certified.difficulty.smallest
        tutorial = ChronoConstellatorTutorialStep.initial(level: number)
    }

    /// After an accepted action that won the play: records the edits in use against the certified smallest edit count
    /// in the current mode (campaign opens the next level; daily does not; practice records nothing). A won play is
    /// final, so a win is recorded once.
    private mutating func recordIfWon() {
        guard play.stage == .won else { return }
        if case .replay = mode { return }
        progress.record(level: levelNumber, edits: play.spent, smallest: certifiedSmallest, mode: mode,
                        trace: winningTrace)
    }

    /// The controls accepted during replay (feature 357); the star pick and the camera are presentation only and send no
    /// action.
    static let replayControls: Set<String> = ["replay.start", "replay.step", "replay.stop", "tutorial.dismiss",
                                              "settings.sound"]

    /// The winning trace of the current play (feature 357): its net actions in order
    /// (``ChronoConstellatorReconciliation/netTrace(_:)``), never an undo or a redo.
    var winningTrace: [ChronoConstellatorAction] { ChronoConstellatorReconciliation.netTrace(play.records) }

    /// Back to the opening state the seed chose (progress included); the quality tier, which is not state, is kept.
    public mutating func reset() {
        levelNumber = openingNumber
        play = opening.play
        progress = opening.progress
        mode = .campaign
        tutorial = opening.tutorial
        certifiedSmallest = opening.certifiedSmallest
        soundOn = false
    }

    /// `won` or `failed` while the play is in that stage; nil otherwise.
    public var outcome: ExperienceOutcome? {
        switch play.stage {
        case .won: ExperienceOutcome(code: Self.wonCode)
        case .failed: ExperienceOutcome(code: Self.failedCode)
        default: nil
        }
    }

    /// "r02-g06.chrono-constellator.v3", then the level number, the play's fingerprint (level, tick, timeline, edits in
    /// use, stage, failure), the progress (with traces) and the mode (their sorted JSON); never the tutorial step, the
    /// sound choice or the dropped count.
    public func writeDigest(into builder: inout DigestBuilder) throws(DigestError) {
        builder.add(Self.digestDomain)
        builder.add(levelNumber)
        // The play's fingerprint and not its record history, so undo restores the earlier digest exactly.
        builder.add(play.fingerprint)
        let encoder = Self.payloadEncoder()
        builder.add(String(decoding: (try? encoder.encode(progress)) ?? Data(), as: UTF8.self))
        builder.add(String(decoding: (try? encoder.encode(mode)) ?? Data(), as: UTF8.self))
    }

    // MARK: Snapshot

    /// The payload's JSON form (schema 3); `tutorial` is absent in a migrated schema-1 payload and `sound` (absent means
    /// off) is written by every schema-3 payload and by the 2 → 3 migration.
    private struct Payload: Codable {
        var level: Int
        var mode: ChronoConstellatorMode
        var progress: ChronoConstellatorProgress
        var records: [ChronoConstellatorRecord]
        var sound: Bool?
        var tutorial: ChronoConstellatorTutorialStep?
    }

    /// The JSON object `{"level", "mode", "progress", "records", "sound", "tutorial"}` with sorted keys and unescaped
    /// slashes.
    public func snapshotPayload() throws -> Data {
        try Self.payloadEncoder().encode(Payload(level: levelNumber, mode: mode, progress: progress,
                                                 records: play.records, sound: soundOn, tutorial: tutorial))
    }

    /// The core of `payload` (schema 3): the records replayed on a fresh play of the saved level (the practice copy in
    /// practice mode) with the reconciled progress (``ChronoConstellatorReconciliation/reconcile(_:)``, the frontier as
    /// saved, the number dropped in ``reconciliationDropped``), the saved mode, tutorial step (the initial step when
    /// absent) and sound choice (off when absent); a saved replay whose result did not survive the check returns to
    /// campaign at that level (the frontier when it is not open). A reset returns to the opening state `seed` chooses.
    ///
    /// - Throws: ``ChronoConstellatorRestoreRefusal`` for a damaged payload (invalid progress, an unknown mode, or a daily
    ///   or replay mode naming another level among them), a level number outside 1 … 100 or a level or trace the kernel
    ///   refuses.
    public static func restore(payload: Data, seed: UInt64) throws -> ChronoConstellatorExperienceCore {
        guard let decoded = try? JSONDecoder().decode(Payload.self, from: payload) else {
            throw ChronoConstellatorRestoreRefusal.damaged
        }
        guard levelNumbers.contains(decoded.level) else {
            throw ChronoConstellatorRestoreRefusal.levelNumber(decoded.level)
        }
        if case .daily(let daily) = decoded.mode, daily != decoded.level {
            throw ChronoConstellatorRestoreRefusal.damaged
        }
        if case .replay(let replayed) = decoded.mode, replayed != decoded.level {
            throw ChronoConstellatorRestoreRefusal.damaged
        }
        do throws(ChronoConstellatorError) {
            let certified = try generated(number: decoded.level)
            let play = try ChronoConstellatorPlay.replay(level: try playedLevel(of: certified, mode: decoded.mode),
                                                         records: decoded.records)
            let tutorial = decoded.tutorial ?? ChronoConstellatorTutorialStep.initial(level: decoded.level)
            let openingCore = try opening(number: levelNumber(forSeed: seed))
            // Feature 357: every saved result is checked by replaying its trace; the frontier stays as saved.
            let reconciled = ChronoConstellatorReconciliation.reconcile(decoded.progress)
            var core = ChronoConstellatorExperienceCore(levelNumber: decoded.level, play: play,
                                                        progress: reconciled.progress, mode: decoded.mode,
                                                        tutorial: tutorial,
                                                        certifiedSmallest: certified.difficulty.smallest,
                                                        openingNumber: openingCore.openingNumber,
                                                        opening: openingCore.opening)
            core.reconciliationDropped = reconciled.dropped
            core.soundOn = decoded.sound ?? false
            // A replay whose result did not survive the check returns to campaign at that level (or the frontier).
            if case .replay(let level) = decoded.mode, reconciled.progress.solved[level]?.verified != true {
                try core.open(number: core.progress.isOpen(level) ? level : core.progress.frontier, mode: .campaign)
            }
            return core
        } catch {
            throw ChronoConstellatorRestoreRefusal.kernel(error)
        }
    }
}
