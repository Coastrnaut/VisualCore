// ChronoConstellatorExperienceCore — feature 353 (R02-G06-03) T-R02G0603-005 (FR-R02G0603-003, 005, 008, 009;
// SC-R02G0603-002, 004; clarifications Q4, Q5; data-model.md "ChronoConstellatorExperienceCore"; contracts/api.md). The
// adapter of the Chrono Constellator kernel to the shared experience contract. The core holds the level number and the
// kernel's `ChronoConstellatorPlay`; it never draws and reads no clock. The presenter asks for an immutable
// `ChronoConstellatorSceneSnapshot` with its own presentation time (`snapshot(time:)`), so the ribbons can shimmer
// while the state and its digest stay put (renderer purity).
//
// Preparation: the certified level number `seed % 100 + 1` of `ChronoConstellatorManifest`, generated by
// `ChronoConstellatorGenerator` once per process (lazily, one level at a time), begun (and its tutorial dismissed) so
// the play is in stage `playing`.
//
// Actions (the engine refuses an undeclared control, a wrong value count, a non-finite or out-of-range value before the
// core sees it; called directly, the core refuses them itself with the same reasons):
//   star.phase [0…4, 0…31]              star and start phase; whole numbers (`r02-g06.not-whole` otherwise); a star or
//                                       phase the level does not have is the kernel's `r02-g06.action`, as are an edit
//                                       after tick 0 and the phase the star already has; an edit above the budget is
//                                       `r02-g06.budget`; any action outside stage `playing` is `r02-g06.stage`;
//   star.hold [0…4, 1…1200, 1…60]       star, first held tick and length; whole; a hold past the tick limit, an
//                                       overlapping or touching hold is `r02-g06.action`; spends one edit;
//   star.release [0…4, 1…1200]          star and the first tick of the hold to remove; whole; no such hold is
//                                       `r02-g06.action`;
//   time.step [1…1200]                  the ticks to replay; whole; spends nothing; stops at the first deciding tick;
//   time.rewind                         back to tick 0 with the timeline kept (also from `failed`, an honest retry);
//   play.undo, play.redo                the kernel's exact undo and redo (`r02-g06.action` when there is nothing to
//                                       undo or redo; undo works in a failed play and returns it to playing; a won play
//                                       is final);
//   level.next                          the next certified level with a fresh play (feature 355: the next open level,
//                                       below).
// Every kernel action is applied with the play's current fingerprint as the expected one. A kernel refusal
// (`ChronoConstellatorError`) becomes `.rule(code: error.reasonCode)`. A refused action changes nothing.
//
// Digest ("r02-g06.chrono-constellator.v1"): the level number and the play's fingerprint (not its record history, so
// undo restores the earlier digest exactly); never the quality tier or a time. Snapshot schema 1: the JSON object
// `{"level", "records"}` with sorted keys; restoring replays the records on a fresh play of that level
// (`ChronoConstellatorPlay.replay`) and throws `ChronoConstellatorRestoreRefusal` for a damaged payload, a level number
// outside 1 … 100 or a trace the kernel refuses (a record of a newer schema among them). An envelope of a newer schema
// is refused by the engine before the core sees it.
//
// Feature 355 (R02-G06-05) T-R02G0605-004 (FR-R02G0605-001 … 005, 007; clarifications Q2–Q5): the core also holds the
// player's progress (`ChronoConstellatorProgress`: won levels with the fewest edits and stars, the open frontier), the
// mode (campaign, practice with the budget raised to the kernel's maximum 20, daily) and the tutorial step. New actions:
//   level.select [1…100]           an open level, fresh, in campaign mode (`r02-g06.locked` otherwise);
//   mode.daily [year, month, day]  the date's daily level, fresh (`r02-g06.date` for an impossible date); a daily level
//                                  still locked in the campaign is playable and is not opened;
//   mode.practice                  the current level fresh with the budget raised to 20;
//   mode.campaign                  the current level fresh in campaign mode (the frontier when it is not open);
//   tutorial.dismiss               the tutorial ends for this opening.
// Choosing daily or practice drops the left level's records (the play starts fresh). `level.next` moves to the next
// open level in campaign mode and is refused with `r02-g06.locked` when there is none (100 does not wrap). A win (the
// play reaching `won` on an accepted action) records `progress.record(level:edits:smallest:mode:)` with the edits in
// use and the certified smallest edit count (campaign opens the next level; daily never does; practice records
// nothing). The tutorial starts at `ChronoConstellatorTutorialStep.initial(level:)` at every opening (levels 1 … 3 in
// every mode) and advances after each accepted kernel action by `advanced(after:planIsRun:ended:)` (the hint's plan is
// computed only for a phase change while the step is `shift`); undo and redo never move it back. Digest
// "r02-g06.chrono-constellator.v2": level, play fingerprint, progress and mode (never the tutorial step). Snapshot
// schema 2: `{"level", "mode", "progress", "records", "tutorial"}`; schema-1 payloads migrate (no won levels, the levels
// up to the saved level open, campaign mode, the tutorial at its initial step).
//
// Feature 357 (R02-G06-07) T-R02G0607-003 (FR-R02G0607-001 … 007; clarifications Q1–Q5; research R2–R6): a campaign or
// daily win records its winning trace (`ChronoConstellatorReconciliation.netTrace` of the play's records: phase changes,
// holds, releases, steps and rewinds, an undone action left out unless redone) as a verified result; restore reconciles
// every result (`ChronoConstellatorReconciliation.reconcile`, the frontier as saved) and exposes `reconciliationDropped`
// (not digested, not in `==`); the replay mode `replay(level)` plays a verified trace action by action:
//   replay.start [1…100]  a fresh play of that level in mode `replay(level)` with the tutorial done
//                         (`r02-g06.no-replay` without a verified result with a trace);
//   replay.step           the next action of the trace (`r02-g06.replay-end` after the last or once the play ended;
//                         `r02-g06.no-replay` outside replay);
//   replay.stop           campaign at that level, the frontier when it is not open (`r02-g06.no-replay` outside replay);
//   settings.sound [0…1]  the sound choice (FR-R02G0607-007): 1 on, 0 off; whole; allowed in every mode.
// In replay every other action except `tutorial.dismiss` and `settings.sound` is refused with `r02-g06.replay`, and
// nothing is recorded. Digest "r02-g06.chrono-constellator.v3" (the same parts as v2; never the sound choice or the
// dropped count); snapshot schema 3 `{"level", "mode", "progress", "records", "sound", "tutorial"}` (results carry
// `trace` and `verified`), migrating 1 → 2 → 3 (2 → 3: every result an empty trace and `verified` false, sound off).
//
// Quality: three host tiers, best first as the contract requires (`qualityProfile` level 0 is the best and no budget
// may rise). Host tier `t` draws `ChronoConstellatorTier.of(t)`: level-0 = ribbons of 24 ticks, 4 segments per tick, 2
// glow shells; level-1 = 12, 2, 1; level-2 = 6, 1, 0. Outcome: `won` or `failed` while the play is in that stage,
// otherwise nil.
