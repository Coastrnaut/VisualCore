// ChronoConstellatorExperienceCore — feature 353 (R02-G06-03) T-R02G0603-005 (FR-R02G0603-003, 005, 008, 009;
// SC-R02G0603-002, 004; clarifications Q4, Q5; data-model.md "ChronoConstellatorExperienceCore"; contracts/api.md). The
// adapter of the Chrono Constellator kernel to the shared experience contract. The core holds the level number and the
// kernel's `ChronoConstellatorPlay`; it never draws and reads no clock. The presenter asks for an immutable
// `ChronoConstellatorSceneSnapshot` with its own presentation time (`snapshot(time:)`), so the ribbons can shimmer
// while the state and its digest stay put (renderer purity).
//
// Preparation: the certified level number `seed % 100 + 1` of `ChronoConstellatorManifest`, generated by
// `ChronoConstellatorGenerator` once per process (lazily, one level at a time), begun (and its tutorial dismissed) so
// the play is in stage `playing`.
//
// Actions (the engine refuses an undeclared control, a wrong value count, a non-finite or out-of-range value before the
// core sees it; called directly, the core refuses them itself with the same reasons):
//   star.phase [0…4, 0…31]              star and start phase; whole numbers (`r02-g06.not-whole` otherwise); a star or
//                                       phase the level does not have is the kernel's `r02-g06.action`, as are an edit
//                                       after tick 0 and the phase the star already has; an edit above the budget is
//                                       `r02-g06.budget`; any action outside stage `playing` is `r02-g06.stage`;
//   star.hold [0…4, 1…1200, 1…60]       star, first held tick and length; whole; a hold past the tick limit, an
//                                       overlapping or touching hold is `r02-g06.action`; spends one edit;
//   star.release [0…4, 1…1200]          star and the first tick of the hold to remove; whole; no such hold is
//                                       `r02-g06.action`;
//   time.step [1…1200]                  the ticks to replay; whole; spends nothing; stops at the first deciding tick;
//   time.rewind                         back to tick 0 with the timeline kept (also from `failed`, an honest retry);
//   play.undo, play.redo                the kernel's exact undo and redo (`r02-g06.action` when there is nothing to
//                                       undo or redo; undo works in a failed play and returns it to playing; a won play
//                                       is final);
//   level.next                          the next certified level (100 wraps to 1) with a fresh play.
// Every kernel action is applied with the play's current fingerprint as the expected one. A kernel refusal
// (`ChronoConstellatorError`) becomes `.rule(code: error.reasonCode)`. A refused action changes nothing.
//
// Digest ("r02-g06.chrono-constellator.v1"): the level number and the play's fingerprint (not its record history, so
// undo restores the earlier digest exactly); never the quality tier or a time. Snapshot schema 1: the JSON object
// `{"level", "records"}` with sorted keys; restoring replays the records on a fresh play of that level
// (`ChronoConstellatorPlay.replay`) and throws `ChronoConstellatorRestoreRefusal` for a damaged payload, a level number
// outside 1 … 100 or a trace the kernel refuses (a record of a newer schema among them). An envelope of a newer schema
// is refused by the engine before the core sees it.
//
// Quality: three host tiers, best first as the contract requires (`qualityProfile` level 0 is the best and no budget
// may rise). Host tier `t` draws `ChronoConstellatorTier.of(t)`: level-0 = ribbons of 24 ticks, 4 segments per tick, 2
// glow shells; level-1 = 12, 2, 1; level-2 = 6, 1, 0. Outcome: `won` or `failed` while the play is in that stage,
// otherwise nil.
import Foundation
import Synchronization
import VisualCoreDiagnostics
import VisualCoreExperience
import VisualCorePersistence

/// The rule codes of Chrono Constellator's adapter refusals (feature 353).
public enum ChronoConstellatorExperienceRule {
    /// A value that must be a whole number (star, phase, tick, length) and is not.
    public static let notWhole = "r02-g06.not-whole"
}

/// Why a saved Chrono Constellator state was refused on restore (feature 353). A refused restore changes nothing.
public enum ChronoConstellatorRestoreRefusal: Error, Equatable, Sendable {
    /// The payload is not the JSON object `{"level", "records"}` or a field has the wrong type.
    case damaged
    /// The level number is outside 1 … 100; the value is that number.
    case levelNumber(Int)
    /// The kernel refused the level's generation or the record trace; the value is that refusal.
    case kernel(ChronoConstellatorError)
}

/// The state of Chrono Constellator as an experience (see the file header). Snapshot schema 1.
public struct ChronoConstellatorExperienceCore: ExperienceCore, Equatable {
    /// The experience's id in the catalog.
    public static let experienceID = "r02-g06.chrono-constellator"
    /// The snapshot schema this build writes.
    public static let schemaVersion = 1
    /// The digest's domain string (schema 1).
    public static let digestDomain = "r02-g06.chrono-constellator.v1"
    /// The action ids in declaration order.
    public static let actionIDs = ["star.phase", "star.hold", "star.release", "time.step", "time.rewind", "play.undo",
                                   "play.redo", "level.next"]
    /// The level numbers of the catalog.
    public static let levelNumbers: ClosedRange<Int> = 1...100
    /// The declared range of a star index: at most five stars.
    public static let starRange: ClosedRange<Int> = 0...4
    /// The declared range of a start phase: loops have at most 32 cells.
    public static let phaseRange: ClosedRange<Int> = 0...31
    /// The declared range of a hold's first tick: the longest tick limit is 1,200.
    public static let holdStartRange: ClosedRange<Int> = 1...1_200
    /// The outcome code of a won play.
    public static let wonCode = "won"
    /// The outcome code of a failed play.
    public static let failedCode = "failed"

    /// The number of the certified level being played (1 … 100).
    public private(set) var levelNumber: Int
    /// The kernel's play of that level.
    public private(set) var play: ChronoConstellatorPlay
    /// The level number the seed chose; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    public let openingNumber: Int
    /// The fresh play of the opening level; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    private let openingPlay: ChronoConstellatorPlay
    /// The host quality tier (0 = level-0, the best, … 2, clamped); presentation only — not in the digest, the
    /// snapshot or `==`.
    public private(set) var qualityTier = 0

    /// A state playing `play` of level `levelNumber`, whose reset returns to `openingPlay` of `openingNumber`.
    init(levelNumber: Int, play: ChronoConstellatorPlay, openingNumber: Int, openingPlay: ChronoConstellatorPlay) {
        self.levelNumber = levelNumber
        self.play = play
        self.openingNumber = openingNumber
        self.openingPlay = openingPlay
    }

    /// The level number a seed chooses: `seed % 100 + 1`.
    public static func levelNumber(forSeed seed: UInt64) -> Int {
        Int(seed % UInt64(levelNumbers.count)) + 1
    }

    /// The certified level of manifest number `number` (1 … 100).
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func level(number: Int) throws(ChronoConstellatorError) -> ChronoConstellatorLevel {
        try generated(number: number).level
    }

    /// The certified levels generated so far, by manifest number: generation is deterministic but runs the solver, so
    /// each level is generated once per process, and only when first asked for (feature 353).
    private static let generatedCache = Mutex<[Int: ChronoConstellatorGenerated]>([:])

    /// The certified level and its proof of manifest number `number` (1 … 100), generated once per process.
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func generated(number: Int) throws(ChronoConstellatorError) -> ChronoConstellatorGenerated {
        guard levelNumbers.contains(number) else { throw .level("number") }
        if let cached = generatedCache.withLock({ $0[number] }) { return cached }
        let fresh = try ChronoConstellatorGenerator.generate(ChronoConstellatorManifest.entries[number - 1])
        generatedCache.withLock { $0[number] = fresh }
        return fresh
    }

    /// A fresh play of `level` in stage `playing`: begun, with its tutorial dismissed when it has one.
    ///
    /// - Throws: the kernel's refusal of `begin` or `dismissTutorial` (never for a new play).
    public static func freshPlay(of level: ChronoConstellatorLevel)
        throws(ChronoConstellatorError) -> ChronoConstellatorPlay {
        try ChronoConstellatorPlay.replay(level: level, records: [])
    }

    /// The opening state of manifest number `number`.
    ///
    /// - Throws: as ``level(number:)``.
    public static func opening(number: Int) throws(ChronoConstellatorError) -> ChronoConstellatorExperienceCore {
        let play = try freshPlay(of: try level(number: number))
        return ChronoConstellatorExperienceCore(levelNumber: number, play: play, openingNumber: number,
                                                openingPlay: play)
    }

    /// An immutable copy of the play and the level number for drawing at the presenter's presentation time `time`
    /// (seconds; a non-finite time becomes 0). Reads only; the state and its digest do not change.
    public func snapshot(time: Double) -> ChronoConstellatorSceneSnapshot {
        ChronoConstellatorSceneSnapshot(play: play, levelNumber: levelNumber, time: time)
    }

    /// The tier the host quality tier draws: `ChronoConstellatorTier.of(qualityTier)` (both ordered richest first).
    public var renderTier: ChronoConstellatorTier { ChronoConstellatorTier.of(qualityTier) }

    // MARK: Quality

    /// Three quality tiers: level-0 (richest) … level-2 (cheapest).
    public static var qualityTiers: Int { ChronoConstellatorTier.all.count }

    /// One level per host tier, best first: the element share is the ribbon segments drawn (ticks × segments per tick)
    /// over the best tier's 96, the iteration share the ribbon ticks over 24 and the effect passes the glow shells;
    /// every level draws at the full resolution.
    public static var qualityProfile: QualityProfile {
        let best = ChronoConstellatorTier.all[0]
        let bestSegments = Double(best.ribbonTicks * best.segments)
        var levels: [QualityLevel] = []
        for hostTier in 0..<ChronoConstellatorTier.all.count {
            let tier = ChronoConstellatorTier.of(hostTier)
            levels.append(QualityLevel(name: tier.name, resolutionShare: 1,
                                       elementShare: Double(tier.ribbonTicks * tier.segments) / bestSegments,
                                       iterationShare: Double(tier.ribbonTicks) / Double(best.ribbonTicks),
                                       effectPasses: tier.glowShells))
        }
        return (try? QualityProfile(levels: levels)) ?? .uniform(levels: levels.count)
    }

    /// Stores `tier` clamped to 0 ..< `qualityTiers`; the state and its digest do not change.
    public mutating func setQualityTier(_ tier: Int) {
        qualityTier = min(max(tier, 0), Self.qualityTiers - 1)
    }

    /// Equal states: the level number and the play (not the quality tier or the opening level).
    public static func == (lhs: ChronoConstellatorExperienceCore, rhs: ChronoConstellatorExperienceCore) -> Bool {
        lhs.levelNumber == rhs.levelNumber && lhs.play == rhs.play
    }

    // MARK: Contract

    /// Schema 1, the first version: no migration steps.
    public static var migrations: MigrationChain { MigrationChain(currentVersion: schemaVersion) }

    /// The declared controls, built once: the star, phase, tick and length ranges as `Double` ranges.
    private static let declaredControls: [ExperienceControl] = [
        ExperienceControl(id: "star.phase", ranges: [declared(starRange), declared(phaseRange)]),
        ExperienceControl(id: "star.hold", ranges: [declared(starRange), declared(holdStartRange),
                                                    declared(ChronoConstellatorTimeline.holdLengths)]),
        ExperienceControl(id: "star.release", ranges: [declared(starRange), declared(holdStartRange)]),
        ExperienceControl(id: "time.step", ranges: [declared(ChronoConstellatorPlay.steps)]),
        ExperienceControl(id: "time.rewind"),
        ExperienceControl(id: "play.undo"),
        ExperienceControl(id: "play.redo"),
        ExperienceControl(id: "level.next"),
    ]

    /// `range` as the `Double` range a control declares.
    private static func declared(_ range: ClosedRange<Int>) -> ClosedRange<Double> {
        Double(range.lowerBound)...Double(range.upperBound)
    }

    /// The eight controls with their declared ranges (see the file header); the rewind, undo, redo and next level take
    /// no values.
    public static var controls: [ExperienceControl] { declaredControls }

    /// The opening state of level `seed % 100 + 1`, in stage `playing`; no clock is read.
    ///
    /// - Throws: `ExperienceFailure` with the kernel's reason code when the level cannot be generated.
    public static func prepare(seed: UInt64) async throws -> ChronoConstellatorExperienceCore {
        try Task.checkCancellation()
        let number = levelNumber(forSeed: seed)
        do throws(ChronoConstellatorError) {
            return try opening(number: number)
        } catch {
            throw ExperienceFailure(code: error.reasonCode, message: "Chrono Constellator level \(number): \(error)")
        }
    }

    /// A host step changes nothing: time runs only on `time.step`, and the ribbons shimmer with the presenter's time,
    /// not the state.
    public mutating func update(step: Int) {}

    /// Carries out a well-formed action (see the file header); a refused action changes nothing.
    public mutating func apply(_ action: ExperienceAction) -> ActionResult {
        if let refusal = ExperienceInput.validate(control: action.control, values: action.values,
                                                  controls: Self.declaredControls) {
            return .rejected(refusal)
        }
        var values: [Int] = []
        for value in action.values {
            guard let whole = Self.whole(value) else {
                return .rejected(.rule(code: ChronoConstellatorExperienceRule.notWhole))
            }
            values.append(whole)
        }
        do throws(ChronoConstellatorError) {
            switch action.control {
            case "star.phase":
                try play.apply(.phase(values[0], values[1]), expecting: play.fingerprint)
            case "star.hold":
                try play.apply(.hold(values[0], values[1], values[2]), expecting: play.fingerprint)
            case "star.release":
                try play.apply(.release(values[0], values[1]), expecting: play.fingerprint)
            case "time.step":
                try play.apply(.step(values[0]), expecting: play.fingerprint)
            case "time.rewind":
                try play.apply(.rewind, expecting: play.fingerprint)
            case "play.undo":
                try play.undo()
            case "play.redo":
                try play.redo()
            default:   // level.next
                let next = levelNumber % Self.levelNumbers.upperBound + 1
                let fresh = try Self.freshPlay(of: try Self.level(number: next))
                levelNumber = next
                play = fresh
            }
        } catch {
            return .rejected(.rule(code: error.reasonCode))
        }
        return .accepted
    }

    /// `value` as an `Int` when it is a finite whole number; nil otherwise.
    static func whole(_ value: Double) -> Int? {
        guard value.isFinite, value == value.rounded() else { return nil }
        return Int(value)
    }

    /// Back to the fresh play of the level the seed chose; the quality tier, which is not state, is kept.
    public mutating func reset() {
        levelNumber = openingNumber
        play = openingPlay
    }

    /// `won` or `failed` while the play is in that stage; nil otherwise.
    public var outcome: ExperienceOutcome? {
        switch play.stage {
        case .won: ExperienceOutcome(code: Self.wonCode)
        case .failed: ExperienceOutcome(code: Self.failedCode)
        default: nil
        }
    }

    /// "r02-g06.chrono-constellator.v1", then the level number and the play's fingerprint (level, tick, timeline, edits
    /// in use, stage, failure).
    public func writeDigest(into builder: inout DigestBuilder) throws(DigestError) {
        builder.add(Self.digestDomain)
        builder.add(levelNumber)
        // The play's fingerprint and not its record history, so undo restores the earlier digest exactly.
        builder.add(play.fingerprint)
    }

    // MARK: Snapshot

    /// The payload's JSON form.
    private struct Payload: Codable {
        var level: Int
        var records: [ChronoConstellatorRecord]
    }

    /// The JSON object `{"level", "records"}` with sorted keys and unescaped slashes.
    public func snapshotPayload() throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try encoder.encode(Payload(level: levelNumber, records: play.records))
    }

    /// The core of `payload`: the records replayed on a fresh play of the saved level; a reset returns to the level
    /// `seed` chooses.
    ///
    /// - Throws: ``ChronoConstellatorRestoreRefusal`` for a damaged payload, a level number outside 1 … 100 or a level
    ///   or trace the kernel refuses.
    public static func restore(payload: Data, seed: UInt64) throws -> ChronoConstellatorExperienceCore {
        guard let decoded = try? JSONDecoder().decode(Payload.self, from: payload) else {
            throw ChronoConstellatorRestoreRefusal.damaged
        }
        guard levelNumbers.contains(decoded.level) else {
            throw ChronoConstellatorRestoreRefusal.levelNumber(decoded.level)
        }
        do throws(ChronoConstellatorError) {
            let saved = try level(number: decoded.level)
            let play = try ChronoConstellatorPlay.replay(level: saved, records: decoded.records)
            let openingNumber = levelNumber(forSeed: seed)
            let openingPlay = openingNumber == decoded.level
                ? try freshPlay(of: saved)
                : try freshPlay(of: try Self.level(number: openingNumber))
            return ChronoConstellatorExperienceCore(levelNumber: decoded.level, play: play,
                                                    openingNumber: openingNumber, openingPlay: openingPlay)
        } catch {
            throw ChronoConstellatorRestoreRefusal.kernel(error)
        }
    }
}
