// AmethystEscapeExperienceCore — feature 363 (R02-G07-03) T-R02G0703-005 (FR-R02G0703-001 … 006; clarifications Q4,
// Q5; data-model.md "AmethystEscapeExperienceCore"; contracts/api.md). The adapter of the Amethyst Escape kernel to the
// shared experience contract. The core holds the level number and the kernel's `AmethystEscapePlay`; it never draws and
// reads no clock. The presenter asks for an immutable `AmethystEscapeSceneSnapshot` with its own presentation time
// (`snapshot(time:)`), so the facet highlights can move while the state and its digest stay put (renderer purity).
//
// Preparation: the certified level number `seed % 100 + 1` of `AmethystEscapeManifest`, generated by
// `AmethystEscapeGenerator` once per process (lazily, one level at a time), begun (and its tutorial dismissed) so the
// play is in stage `playing`.
//
// Actions (the engine refuses an undeclared control, a wrong value count, a non-finite or out-of-range value before the
// core sees it; called directly, the core refuses them itself with the same reasons):
//   shell.rotate [0…4, −1…1]   shell and step; whole numbers (`r02-g07.not-whole` otherwise); a shell the level does not
//                              have (shells − 1 … 4) and the step 0 are the kernel's `r02-g07.action`; any action outside
//                              stage `playing` is `r02-g07.stage`; spends one move;
//   pearl.advance              the pearl's one transition; no aperture lined up with a wall ahead is the kernel's
//                              `r02-g07.stuck`; spends one move; the exit wins, a blocked wedge or the last move of the
//                              budget without a win fails;
//   play.undo, play.redo       the kernel's exact undo and redo (`r02-g07.action` when there is nothing to undo or redo;
//                              undo works in a failed play and returns it to playing; a won play is final);
//   level.next                 the next certified level with a fresh play (feature 365: the next open level, below).
// Every kernel action is applied with the play's current fingerprint as the expected one. A kernel refusal
// (`AmethystEscapeError`) becomes `.rule(code: error.reasonCode)`. A refused action changes nothing.
//
// Digest ("r02-g07.amethyst-escape.v1"): the level number and the play's fingerprint (not its record history, so undo
// restores the earlier digest exactly); never the quality tier or a time. Snapshot schema 1: the JSON object
// `{"level", "records"}` with sorted keys; restoring replays the records on a fresh play of that level
// (`AmethystEscapePlay.replay`) and throws `AmethystEscapeRestoreRefusal` for a damaged payload, a level number outside
// 1 … 100 or a trace the kernel refuses (a record of a newer schema among them). An envelope of a newer schema is refused
// by the engine before the core sees it.
//
// Feature 365 (R02-G07-05) T-R02G0705-004 (FR-R02G0705-001 … 005, 007; clarifications Q1–Q5): the core also holds the
// player's progress (`AmethystEscapeProgress`: won levels with the fewest moves and stars, the open frontier), the mode
// (campaign, practice with the budget raised to the kernel's maximum 60, daily) and the tutorial step. New actions:
//   level.select [1…100]           an open level, fresh, in campaign mode (`r02-g07.locked` otherwise);
//   mode.daily [year, month, day]  the date's daily level, fresh (`r02-g07.date` for an impossible date); a daily level
//                                  still locked in the campaign is playable and is not opened;
//   mode.practice                  the current level fresh with the budget raised to 60;
//   mode.campaign                  the current level fresh in campaign mode (the frontier when it is not open);
//   tutorial.dismiss               the tutorial ends for this opening.
// Choosing daily or practice drops the left level's records (the play starts fresh). `level.next` moves to the next
// open level in campaign mode and is refused with `r02-g07.locked` when there is none (100 does not wrap). A win (the
// play reaching `won` on an accepted turn, advance or redo) records `progress.record(level:moves:smallest:mode:)` with
// the moves spent and the certified smallest move count (campaign opens the next level; daily never does; practice
// records nothing). The tutorial starts at `AmethystEscapeTutorialStep.initial(level:)` at every opening (levels 1 … 3
// in every mode) and advances after each accepted turn, advance or redo by `advanced(after:ended:)`; undo and redo
// never move it back. Digest "r02-g07.amethyst-escape.v2": level, play fingerprint, progress and mode (never the
// tutorial step). Snapshot schema 2: `{"level", "mode", "progress", "records", "tutorial"}`; schema-1 payloads migrate
// (no won levels, the levels up to the saved level open, campaign mode, the tutorial at its initial step).
//
// Quality: three host tiers, best first as the contract requires (`qualityProfile` level 0 is the best and no budget may
// rise). Host tier `t` draws `AmethystEscapeTier.of(t)`: level-0 = 3 bevel segments, 3 highlight layers, 2 glow shells;
// level-1 = 2, 2, 1; level-2 = 1, 1, 0. Outcome: `won` or `failed` while the play is in that stage, otherwise nil.
import Foundation
import Synchronization
import VisualCoreDiagnostics
import VisualCoreExperience
import VisualCorePersistence

/// The rule codes of Amethyst Escape's adapter refusals (feature 363).
public enum AmethystEscapeExperienceRule {
    /// A value that must be a whole number (shell, step) and is not.
    public static let notWhole = "r02-g07.not-whole"
    /// A level that is not open yet, or no next open level (feature 365).
    public static let locked = "r02-g07.locked"
    /// An impossible calendar date (feature 365).
    public static let date = "r02-g07.date"
}

/// Why a saved Amethyst Escape state was refused on restore (feature 363). A refused restore changes nothing.
public enum AmethystEscapeRestoreRefusal: Error, Equatable, Sendable {
    /// The payload is not the JSON object of its schema, a field has the wrong type, or the progress or the mode is
    /// invalid (feature 365).
    case damaged
    /// The level number is outside 1 … 100; the value is that number.
    case levelNumber(Int)
    /// The kernel refused the level's generation or the record trace; the value is that refusal.
    case kernel(AmethystEscapeError)
}

/// The state of Amethyst Escape as an experience (see the file header). Snapshot schema 2.
public struct AmethystEscapeExperienceCore: ExperienceCore, Equatable {
    /// The experience's id in the catalog.
    public static let experienceID = "r02-g07.amethyst-escape"
    /// The snapshot schema this build writes.
    public static let schemaVersion = 2
    /// The digest's domain string (schema 2).
    public static let digestDomain = "r02-g07.amethyst-escape.v2"
    /// The action ids in declaration order.
    public static let actionIDs = ["shell.rotate", "pearl.advance", "play.undo", "play.redo", "level.next",
                                   "level.select", "mode.daily", "mode.practice", "mode.campaign", "tutorial.dismiss"]
    /// The budget of a practice play: the kernel's maximum (`AmethystEscapeMode.practiceBudget`, 60).
    public static let practiceBudget = AmethystEscapeMode.practiceBudget
    /// The level numbers of the catalog.
    public static let levelNumbers: ClosedRange<Int> = 1...100
    /// The declared range of a shell index: levels have at most five shells (`AmethystEscapeLevel.shellCounts`).
    public static let shellRange: ClosedRange<Int> = 0...(AmethystEscapeLevel.shellCounts.upperBound - 1)
    /// The declared range of a rotation step: −1 (anticlockwise) or +1 (clockwise); 0 is the kernel's refusal.
    public static let stepRange: ClosedRange<Int> = -1...1
    /// The outcome code of a won play.
    public static let wonCode = "won"
    /// The outcome code of a failed play.
    public static let failedCode = "failed"

    /// The number of the certified level being played (1 … 100).
    public private(set) var levelNumber: Int
    /// The kernel's play of that level (of its practice copy in practice mode).
    public private(set) var play: AmethystEscapePlay
    /// The player's progress (feature 365): in the digest and the snapshot.
    public private(set) var progress: AmethystEscapeProgress
    /// The mode (feature 365): in the digest and the snapshot.
    public private(set) var mode: AmethystEscapeMode
    /// The tutorial step (feature 365): in the snapshot, not in the digest.
    public private(set) var tutorial: AmethystEscapeTutorialStep
    /// The certified smallest move count of the current level (stars). Derived from the level number.
    public private(set) var certifiedSmallest: Int
    /// The level number the seed chose; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    public let openingNumber: Int
    /// The opening state; a reset returns to it. Derived from the seed, so not in the digest or `==`.
    private let opening: Opening

    /// What a reset restores (feature 365).
    struct Opening: Sendable {
        /// The fresh play of the opening level.
        let play: AmethystEscapePlay
        /// The opening progress: the levels up to the opening level open, none won.
        let progress: AmethystEscapeProgress
        /// The opening level's initial tutorial step.
        let tutorial: AmethystEscapeTutorialStep
        /// The opening level's certified smallest move count.
        let certifiedSmallest: Int
    }
    /// The host quality tier (0 = level-0, the best, … 2, clamped); presentation only — not in the digest, the snapshot
    /// or `==`.
    public private(set) var qualityTier = 0

    /// A state playing `play` of level `levelNumber` with `progress`, `mode` and `tutorial`, whose reset returns to
    /// `opening` of `openingNumber`.
    init(levelNumber: Int, play: AmethystEscapePlay, progress: AmethystEscapeProgress, mode: AmethystEscapeMode,
         tutorial: AmethystEscapeTutorialStep, certifiedSmallest: Int, openingNumber: Int, opening: Opening) {
        self.levelNumber = levelNumber
        self.play = play
        self.progress = progress
        self.mode = mode
        self.tutorial = tutorial
        self.certifiedSmallest = certifiedSmallest
        self.openingNumber = openingNumber
        self.opening = opening
    }

    /// The level number a seed chooses: `seed % 100 + 1`.
    public static func levelNumber(forSeed seed: UInt64) -> Int {
        Int(seed % UInt64(levelNumbers.count)) + 1
    }

    /// The certified level of manifest number `number` (1 … 100).
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func level(number: Int) throws(AmethystEscapeError) -> AmethystEscapeLevel {
        try generated(number: number).level
    }

    /// The certified levels generated so far, by manifest number: generation is deterministic but runs the solver, so
    /// each level is generated once per process, and only when first asked for (feature 363).
    private static let generatedCache = Mutex<[Int: AmethystEscapeGenerated]>([:])

    /// The certified level and its proof of manifest number `number` (1 … 100), generated once per process.
    ///
    /// - Throws: `.level("number")` for a number outside 1 … 100; the generator's `.generation(number)`.
    public static func generated(number: Int) throws(AmethystEscapeError) -> AmethystEscapeGenerated {
        guard levelNumbers.contains(number) else { throw .level("number") }
        if let cached = generatedCache.withLock({ $0[number] }) { return cached }
        let fresh = try AmethystEscapeGenerator.generate(AmethystEscapeManifest.entries[number - 1])
        generatedCache.withLock { $0[number] = fresh }
        return fresh
    }

    /// A fresh play of `level` in stage `playing`: begun, with its tutorial dismissed when it has one.
    ///
    /// - Throws: the kernel's refusal of `begin` or `dismissTutorial` (never for a new play).
    public static func freshPlay(of level: AmethystEscapeLevel) throws(AmethystEscapeError) -> AmethystEscapePlay {
        try AmethystEscapePlay.replay(level: level, records: [])
    }

    /// The practice copy of `level` (feature 365): every field kept, the budget raised to ``practiceBudget``.
    ///
    /// - Throws: the kernel's refusal of the copy (never for a certified level).
    public static func practiceLevel(of level: AmethystEscapeLevel)
        throws(AmethystEscapeError) -> AmethystEscapeLevel {
        try AmethystEscapeLevel(id: level.id, seed: level.seed, difficulty: level.difficulty, sectors: level.sectors,
                                shells: level.shells, start: level.start,
                                budget: AmethystEscapeMode.practice.budget(base: level.budget),
                                tutorial: level.tutorial)
    }

    /// The level a play of `certified` in `mode` uses: the practice copy in practice mode, otherwise the certified
    /// level.
    ///
    /// - Throws: as ``practiceLevel(of:)``.
    static func playedLevel(of certified: AmethystEscapeGenerated,
                            mode: AmethystEscapeMode) throws(AmethystEscapeError) -> AmethystEscapeLevel {
        mode == .practice ? try practiceLevel(of: certified.level) : certified.level
    }

    /// The opening state of manifest number `number`: campaign mode, the levels up to `number` open, none won, the
    /// tutorial at its initial step.
    ///
    /// - Throws: as ``level(number:)``.
    public static func opening(number: Int) throws(AmethystEscapeError) -> AmethystEscapeExperienceCore {
        let certified = try generated(number: number)
        let play = try freshPlay(of: certified.level)
        var progress = AmethystEscapeProgress()
        progress.open(through: number)
        let tutorial = AmethystEscapeTutorialStep.initial(level: number)
        let smallest = certified.solution.smallest
        let opening = Opening(play: play, progress: progress, tutorial: tutorial, certifiedSmallest: smallest)
        return AmethystEscapeExperienceCore(levelNumber: number, play: play, progress: progress, mode: .campaign,
                                            tutorial: tutorial, certifiedSmallest: smallest, openingNumber: number,
                                            opening: opening)
    }

    /// The hint of `level` (1 … 3) for the current play (``AmethystEscapeHints/hint(level:play:)``); nil when the play
    /// is won (or not yet playing). Reads only.
    public func hint(level: Int) -> AmethystEscapeHint? {
        AmethystEscapeHints.hint(level: level, play: play)
    }

    /// The explanation of the current play's failure; nil unless the play failed.
    public var failureExplanation: AmethystEscapeFailureExplanation? {
        AmethystEscapeFailureExplanation(play: play)
    }

    /// An immutable copy of the play and the level number for drawing at the presenter's presentation time `time`
    /// (seconds; a non-finite time becomes 0). Reads only; the state and its digest do not change.
    public func snapshot(time: Double) -> AmethystEscapeSceneSnapshot {
        AmethystEscapeSceneSnapshot(play: play, levelNumber: levelNumber, time: time)
    }

    /// The tier the host quality tier draws: `AmethystEscapeTier.of(qualityTier)` (both ordered richest first).
    public var renderTier: AmethystEscapeTier { AmethystEscapeTier.of(qualityTier) }

    // MARK: Quality

    /// Three quality tiers: level-0 (richest) … level-2 (cheapest).
    public static var qualityTiers: Int { AmethystEscapeTier.all.count }

    /// One level per host tier, best first: the element share is the bevel segments over the best tier's 3, the
    /// iteration share the highlight layers over 3 and the effect passes the glow shells; every level draws at the full
    /// resolution.
    public static var qualityProfile: QualityProfile {
        let best = AmethystEscapeTier.all[0]
        var levels: [QualityLevel] = []
        for hostTier in 0..<AmethystEscapeTier.all.count {
            let tier = AmethystEscapeTier.of(hostTier)
            levels.append(QualityLevel(name: tier.name, resolutionShare: 1,
                                       elementShare: Double(tier.bevelSegments) / Double(best.bevelSegments),
                                       iterationShare: Double(tier.highlightLayers) / Double(best.highlightLayers),
                                       effectPasses: tier.glowShells))
        }
        return (try? QualityProfile(levels: levels)) ?? .uniform(levels: levels.count)
    }

    /// Stores `tier` clamped to 0 ..< `qualityTiers`; the state and its digest do not change.
    public mutating func setQualityTier(_ tier: Int) {
        qualityTier = min(max(tier, 0), Self.qualityTiers - 1)
    }

    /// Equal states: the level number, the play, the progress, the mode and the tutorial step (not the quality tier or
    /// the opening level).
    public static func == (lhs: AmethystEscapeExperienceCore, rhs: AmethystEscapeExperienceCore) -> Bool {
        lhs.levelNumber == rhs.levelNumber && lhs.play == rhs.play && lhs.progress == rhs.progress
            && lhs.mode == rhs.mode && lhs.tutorial == rhs.tutorial
    }

    // MARK: Contract

    /// Schema 2 with the step 1 → 2 (``migratedToSchemaTwo(_:)``); a payload that does not decode is refused.
    public static var migrations: MigrationChain {
        MigrationChain(currentVersion: schemaVersion, steps: [1: { payload in try migratedToSchemaTwo(payload) }])
    }

    /// The schema-2 object of a schema-1 object `{"level", "records"}` (feature 365): no won levels with the levels up
    /// to the saved level open, campaign mode, no tutorial key (restore starts the tutorial at its initial step).
    ///
    /// - Throws: ``AmethystEscapeRestoreRefusal/damaged`` when `object` is not a schema-1 object.
    public static func migratedToSchemaTwo(_ object: [String: Any]) throws -> [String: Any] {
        guard let level = object["level"] as? Int, object["records"] is [Any] else {
            throw AmethystEscapeRestoreRefusal.damaged
        }
        var progress = AmethystEscapeProgress()
        progress.open(through: level)
        var migrated = object
        migrated["progress"] = try JSONSerialization.jsonObject(with: try payloadEncoder().encode(progress))
        migrated["mode"] = try JSONSerialization.jsonObject(
            with: try payloadEncoder().encode(AmethystEscapeMode.campaign))
        return migrated
    }

    /// The encoder of payloads and digested values: sorted keys, unescaped slashes.
    static func payloadEncoder() -> JSONEncoder {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return encoder
    }

    /// The declared controls, built once: the shell and step ranges as `Double` ranges.
    private static let declaredControls: [ExperienceControl] = [
        ExperienceControl(id: "shell.rotate", ranges: [declared(shellRange), declared(stepRange)]),
        ExperienceControl(id: "pearl.advance"),
        ExperienceControl(id: "play.undo"),
        ExperienceControl(id: "play.redo"),
        ExperienceControl(id: "level.next"),
        ExperienceControl(id: "level.select", ranges: [declared(levelNumbers)]),
        ExperienceControl(id: "mode.daily", ranges: [declared(AmethystEscapeProgress.dailyYears), 1...12, 1...31]),
        ExperienceControl(id: "mode.practice"),
        ExperienceControl(id: "mode.campaign"),
        ExperienceControl(id: "tutorial.dismiss"),
    ]

    /// `range` as the `Double` range a control declares.
    private static func declared(_ range: ClosedRange<Int>) -> ClosedRange<Double> {
        Double(range.lowerBound)...Double(range.upperBound)
    }

    /// The ten controls with their declared ranges (see the file header); all but `shell.rotate`, `level.select` and
    /// `mode.daily` take no values.
    public static var controls: [ExperienceControl] { declaredControls }

    /// The opening state of level `seed % 100 + 1`, in stage `playing`, campaign mode, the levels up to it open; no
    /// clock is read.
    ///
    /// - Throws: `ExperienceFailure` with the kernel's reason code when the level cannot be generated.
    public static func prepare(seed: UInt64) async throws -> AmethystEscapeExperienceCore {
        try Task.checkCancellation()
        let number = levelNumber(forSeed: seed)
        do throws(AmethystEscapeError) {
            return try opening(number: number)
        } catch {
            throw ExperienceFailure(code: error.reasonCode, message: "Amethyst Escape level \(number): \(error)")
        }
    }

    /// A host step changes nothing: the crystal moves only on an action, and the highlights move with the presenter's
    /// time, not the state.
    public mutating func update(step: Int) {}

    /// Carries out a well-formed action (see the file header); a refused action changes nothing.
    public mutating func apply(_ action: ExperienceAction) -> ActionResult {
        if let refusal = ExperienceInput.validate(control: action.control, values: action.values,
                                                  controls: Self.declaredControls) {
            return .rejected(refusal)
        }
        var values: [Int] = []
        for value in action.values {
            guard let whole = Self.whole(value) else {
                return .rejected(.rule(code: AmethystEscapeExperienceRule.notWhole))
            }
            values.append(whole)
        }
        do throws(AmethystEscapeError) {
            switch action.control {
            case "shell.rotate":
                try play.apply(.rotate(values[0], values[1]), expecting: play.fingerprint)
                advanceTutorial()
                recordIfWon()
            case "pearl.advance":
                try play.apply(.advance, expecting: play.fingerprint)
                advanceTutorial()
                recordIfWon()
            case "play.undo":
                try play.undo()
            case "play.redo":
                try play.redo()
                advanceTutorial()
                recordIfWon()
            case "level.next":
                guard let next = progress.nextOpen(after: levelNumber) else {
                    return .rejected(.rule(code: AmethystEscapeExperienceRule.locked))
                }
                try open(number: next, mode: .campaign)
            case "level.select":
                guard progress.isOpen(values[0]) else {
                    return .rejected(.rule(code: AmethystEscapeExperienceRule.locked))
                }
                try open(number: values[0], mode: .campaign)
            case "mode.daily":
                guard let daily = AmethystEscapeProgress.dailyLevel(year: values[0], month: values[1],
                                                                    day: values[2]) else {
                    return .rejected(.rule(code: AmethystEscapeExperienceRule.date))
                }
                try open(number: daily, mode: .daily(level: daily))
            case "mode.practice":
                try open(number: levelNumber, mode: .practice)
            case "mode.campaign":
                try open(number: progress.isOpen(levelNumber) ? levelNumber : progress.frontier, mode: .campaign)
            default:   // tutorial.dismiss
                tutorial = tutorial.dismissed()
            }
        } catch {
            return .rejected(.rule(code: error.reasonCode))
        }
        return .accepted
    }

    /// `value` as an `Int` when it is a finite whole number; nil otherwise.
    static func whole(_ value: Double) -> Int? {
        guard value.isFinite, value == value.rounded() else { return nil }
        return Int(value)
    }

    /// Advances the tutorial step by the play's latest accepted record
    /// (`AmethystEscapeTutorialStep.advanced(after:ended:)`): a turn or an advance moves it on, the end of the level
    /// ends it; an undo or a redo never moves the step back.
    private mutating func advanceTutorial() {
        guard tutorial != .done else { return }
        let ended = play.stage == .won || play.stage == .failed
        tutorial = tutorial.advanced(after: play.records.last?.kind, ended: ended)
    }

    /// A fresh play of manifest number `number` in `mode` (the practice copy in practice mode) with the level's initial
    /// tutorial step; the records of the level left are dropped. Changes nothing when the kernel refuses.
    private mutating func open(number: Int, mode: AmethystEscapeMode) throws(AmethystEscapeError) {
        let certified = try Self.generated(number: number)
        let fresh = try Self.freshPlay(of: try Self.playedLevel(of: certified, mode: mode))
        levelNumber = number
        play = fresh
        self.mode = mode
        certifiedSmallest = certified.solution.smallest
        tutorial = AmethystEscapeTutorialStep.initial(level: number)
    }

    /// After an accepted action that won the play: records the moves spent against the certified smallest move count
    /// in the current mode (campaign opens the next level; daily does not; practice records nothing). A won play is
    /// final, so a win is recorded once.
    private mutating func recordIfWon() {
        guard play.stage == .won else { return }
        progress.record(level: levelNumber, moves: play.moves, smallest: certifiedSmallest, mode: mode)
    }

    /// Back to the opening state the seed chose (progress included); the quality tier, which is not state, is kept.
    public mutating func reset() {
        levelNumber = openingNumber
        play = opening.play
        progress = opening.progress
        mode = .campaign
        tutorial = opening.tutorial
        certifiedSmallest = opening.certifiedSmallest
    }

    /// `won` or `failed` while the play is in that stage; nil otherwise.
    public var outcome: ExperienceOutcome? {
        switch play.stage {
        case .won: ExperienceOutcome(code: Self.wonCode)
        case .failed: ExperienceOutcome(code: Self.failedCode)
        default: nil
        }
    }

    /// "r02-g07.amethyst-escape.v2", then the level number, the play's fingerprint (level, offsets, pearl, moves,
    /// stage, failure), the progress and the mode (their sorted JSON); never the tutorial step.
    public func writeDigest(into builder: inout DigestBuilder) throws(DigestError) {
        builder.add(Self.digestDomain)
        builder.add(levelNumber)
        // The play's fingerprint and not its record history, so undo restores the earlier digest exactly.
        builder.add(play.fingerprint)
        let encoder = Self.payloadEncoder()
        builder.add(String(decoding: (try? encoder.encode(progress)) ?? Data(), as: UTF8.self))
        builder.add(String(decoding: (try? encoder.encode(mode)) ?? Data(), as: UTF8.self))
    }

    // MARK: Snapshot

    /// The payload's JSON form (schema 2); `tutorial` is absent in a migrated schema-1 payload.
    private struct Payload: Codable {
        var level: Int
        var mode: AmethystEscapeMode
        var progress: AmethystEscapeProgress
        var records: [AmethystEscapeRecord]
        var tutorial: AmethystEscapeTutorialStep?
    }

    /// The JSON object `{"level", "mode", "progress", "records", "tutorial"}` with sorted keys and unescaped slashes.
    public func snapshotPayload() throws -> Data {
        try Self.payloadEncoder().encode(Payload(level: levelNumber, mode: mode, progress: progress,
                                                 records: play.records, tutorial: tutorial))
    }

    /// The core of `payload` (schema 2): the records replayed on a fresh play of the saved level (the practice copy in
    /// practice mode) with the saved progress, mode and tutorial step (the initial step when absent); a reset returns
    /// to the opening state `seed` chooses.
    ///
    /// - Throws: ``AmethystEscapeRestoreRefusal`` for a damaged payload (invalid progress, an unknown mode or a daily
    ///   mode naming another level among them), a level number outside 1 … 100 or a level or trace the kernel
    ///   refuses.
    public static func restore(payload: Data, seed: UInt64) throws -> AmethystEscapeExperienceCore {
        guard let decoded = try? JSONDecoder().decode(Payload.self, from: payload) else {
            throw AmethystEscapeRestoreRefusal.damaged
        }
        guard levelNumbers.contains(decoded.level) else {
            throw AmethystEscapeRestoreRefusal.levelNumber(decoded.level)
        }
        if case .daily(let daily) = decoded.mode, daily != decoded.level {
            throw AmethystEscapeRestoreRefusal.damaged
        }
        do throws(AmethystEscapeError) {
            let certified = try generated(number: decoded.level)
            let play = try AmethystEscapePlay.replay(level: try playedLevel(of: certified, mode: decoded.mode),
                                                     records: decoded.records)
            let tutorial = decoded.tutorial ?? AmethystEscapeTutorialStep.initial(level: decoded.level)
