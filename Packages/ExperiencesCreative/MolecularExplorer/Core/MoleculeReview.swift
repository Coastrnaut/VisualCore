// MoleculeReview — feature 114 (A15-P05) T-A15-504 (FR-A15-520, FR-A15-521; clarification Q5; data-model "Review
// document"; contracts/import.md; SC-A15-504). The scientific review of Molecular Explorer, host-free:
// - `inferredStatement`, the line the panel shows under the bonds: "Bonds marked inferred are estimated from atom
//   distances."; `displayStatement` is the legend's closing note "Display radii, not measured sizes.";
// - `claimWords`, the safety, toxicity, medical and therapeutic words no shown sentence may contain, and
//   `claimWords(in:)`, which finds them as whole words (letters only, split at every other character) ignoring case,
//   in order of appearance and each once;
// - `document()`, the text of `docs/apps/molecular-explorer/data-review.md`, which a test compares with the bundled
//   data byte for byte: the title "# Molecular Explorer — data review", a note on how it is made, "## Elements" (one
//   row per element and stored quantity in `ElementQuantity` order: the element, the quantity, the value as stored,
//   its units, source title, publisher, link and license, all from `Elements.sources`), "## Molecules" (one row per
//   library molecule: title, formula, atom and bond counts, the units of its coordinates, source title, publisher, link
//   and license, from its structure record), "## Imported molecules" (the source and license an imported molecule
//   shows) and "## Statements" (the display convention and the inferred-bond statement). It is deterministic (no
//   dates, radii with two decimals in the POSIX format), uses LF line endings and ends with a newline.
import Foundation

/// The provenance and wording review of every bundled value and every displayed statement.
public enum MoleculeReview {
    /// The document title.
    public static let title = "Molecular Explorer — data review"
    /// The line shown under the bonds.
    public static let inferredStatement = "Bonds marked inferred are estimated from atom distances."
    /// The legend's closing note (the same words as the presenter's legend note).
    public static let displayStatement = "Display radii, not measured sizes."
    /// The words no sentence the experience shows may contain (clarification Q5), lower case.
    public static let claimWords: [String] = [
        "safe", "safety", "toxic", "toxicity", "poison", "hazard", "hazardous", "medical", "medicine", "medicinal",
        "drug", "therapy", "therapeutic", "cure", "treatment", "dose", "health", "stimulant",
    ]

    /// The claim words found in `sentence` as whole words, ignoring case, in order of appearance and each once
    /// (lower case); empty when there is none.
    public static func claimWords(in sentence: String) -> [String] {
        let wanted = Set(claimWords)
        var found: [String] = []
        for word in sentence.split(whereSeparator: { !$0.isLetter }) {
            let lower = word.lowercased()
            if wanted.contains(lower) && !found.contains(lower) { found.append(lower) }
        }
        return found
    }

    /// The value of `quantity` for `element` as the review lists it: the name, the atomic number, a radius with two
    /// decimals, or the colour's six hex digits in code style.
    static func value(_ element: Element, _ quantity: ElementQuantity) -> String {
        switch quantity {
        case .name: return element.name
        case .atomicNumber: return String(element.atomicNumber)
        case .covalentRadius: return ElementAudit.format(element.covalentRadius)
        case .vanDerWaalsRadius: return ElementAudit.format(element.vanDerWaalsRadius)
        case .color: return "`\(element.colorHex)`"
        }
    }

    /// `text`, or "—" when it is empty.
    static func shown(_ text: String) -> String {
        text.isEmpty ? "—" : text
    }

    /// The text of `docs/apps/molecular-explorer/data-review.md` for the bundled data (see the file header).
    public static func document() -> String {
        var lines: [String] = [
            "# \(title)",
            "",
            "Generated by `MoleculeReview.document()` from the element catalog (`Elements`), the curated library "
                + "(`MoleculeLibrary`) and the panel's statements of Molecular Explorer (feature 114, A15-P05). A test "
                + "compares this file with the data; regenerate it with `UPDATE_DATA_REVIEW=1` (or "
                + "`TEST_RUNNER_UPDATE_DATA_REVIEW=1` through xcodebuild). Every value the experience stores and "
                + "displays is listed with its units, source and license.",
            "",
            "## Elements",
            "",
            "| Element | Quantity | Value | Units | Source | Publisher | Link | License |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for element in Elements.all {
            for quantity in ElementQuantity.allCases {
                guard let record = Elements.source(symbol: element.symbol, quantity: quantity) else {
                    lines.append("| \(element.name) (\(element.symbol)) | \(quantity.rawValue) | "
                                 + "\(value(element, quantity)) | \(shown(quantity.units)) | (no source record) | — | "
                                 + "— | — |")
                    continue
                }
                lines.append("| \(element.name) (\(element.symbol)) | \(quantity.rawValue) | "
                             + "\(value(element, quantity)) | \(shown(record.units)) | \(record.title) | "
                             + "\(record.publisher) | \(shown(record.link)) | \(record.license) |")
            }
        }
        lines += ["", "## Molecules", "",
                  "| Molecule | Formula | Atoms | Bonds | Units | Source | Publisher | Link | License |",
                  "|---|---|---:|---:|---|---|---|---|---|"]
        for molecule in MoleculeLibrary.molecules {
            let source = molecule.source
            lines.append("| \(molecule.title) | \(molecule.formula) | \(molecule.atoms.count) | "
                         + "\(molecule.bonds.count) | \(shown(source.units)) | \(source.title) | \(source.publisher) | "
                         + "\(shown(source.link)) | \(source.license) |")
        }
        let imported = ImportedMolecule.source
        lines += ["", "## Imported molecules", "",
                  "An imported molecule is the person's own data: its atoms come from the chosen file (coordinates in "
                    + "\(imported.units)), its bonds are inferred from the atom distances, and its source reads "
                    + "\"\(imported.title)\" with the license `\(imported.license)` (\"your own data\"). Nothing of it "
                    + "is bundled.",
                  "", "## Statements", "",
                  "- \(displayStatement) (the closing note of both display legends)",
                  "- \(inferredStatement) (the line under the bonds in the panel)"]
        return lines.joined(separator: "\n") + "\n"
    }
}
