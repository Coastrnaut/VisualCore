// SimulationValidationTests — feature 121 (A16-P05) T-A16-503 (FR-A16-501–503; SC-A16-501–503; clarifications Q1–Q5;
// contracts/report.md). The numerical validation report of Simulation Lab, from short runs on the simulator:
// - running mirrors: per family, 120 frames at ×4 through the presenter, the largest |GPU − CPU| after every frame
//   against its tolerance (0 for the automaton, 0.01 for reaction-diffusion and the wave);
// - fixtures: the 16 × 16 ten-step runs of A16-P03 against the float16 and toward-zero references;
// - stability limits: 600 iterations at Δt 1.5625 (reaction-diffusion) and at the Courant limit c 1, Δt 1/√2 (wave) on
//   the CPU model and on the GPU pair, every cell finite; 1 % above each limit refused with its sentence;
// - bounds: the largest GPU steps in a frame ≤ 128, the presenter's targets ≤ 262,144 bytes, the registry within its
//   budget;
// - steps per second: 600 CPU iterations per family timed with ContinuousClock, a simulator figure, never asserted.
// Every bound is asserted. With `UPDATE_VALIDATION_REPORT=1` (on the simulator `TEST_RUNNER_UPDATE_VALIDATION_REPORT=1`)
// the report is written to `docs/apps/simulation-lab/validation-report.md`; otherwise its deterministic lines (all but
// the steps-per-second section) must equal the committed file's. Without floating-point targets the test fails and
// writes nothing.
import Foundation
import UIKit
import XCTest
@testable import SimulationLabExperience
import SimulationLabCore
import VisualCoreExperience
import VisualCoreExperienceHost
import VisualCoreRendering
import VisualCoreSimulation

@MainActor
final class SimulationValidationTests: XCTestCase {
    /// The committed report.
    static let reportURL = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
        .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        .appendingPathComponent("docs/apps/simulation-lab/validation-report.md")
    /// The heading of the section left out of the comparison.
    static let timingHeading = "## Steps per second (simulator figure, not a device claim)"

    /// The non-finite values of `grid`.
    private func nonFinite(_ grid: FieldGrid) -> Int { grid.values.filter { !$0.isFinite }.count }

    /// `value` with four decimals.
    private func f4(_ value: Float) -> String { String(format: "%.4f", Double(value)) }

    func testTheValidationReport() async throws {
        var lines = ["# Simulation Lab validation report", "",
                     "Runtime: iOS \(UIDevice.current.systemVersion) simulator. Generated by SimulationValidationTests "
                     + "(`UPDATE_VALIDATION_REPORT=1`; feature 121, A16-P05). The iOS 26 section is added at X-A16; "
                     + "device figures wait for the device campaign.", ""]

        // Running mirrors and bounds.
        lines += ["## Running mirrors (64 × 64, ×4, 120 frames)", "",
                  "| Family | Max \\|GPU − CPU\\| | Tolerance | Within |", "|---|---|---|---|"]
        var maxSteps = 0, ownedBytes = 0, registryBytes = 0, budget = 0
        for family in 0..<3 {
            let session = ExperienceSession()
            let shell = try await SimulationTest.open(session)
            let presenter = shell.presenter
            if family > 0 { XCTAssertTrue(presenter.send("sim.family", [Double(family)], through: shell.port).isAccepted) }
            XCTAssertTrue(presenter.send("sim.speed", [4], through: shell.port).isAccepted)
            guard presenter.floatSupported == true else {
                XCTFail("Floating-point render targets are not available")
                session.close()
                return
            }
            var worst: Float = 0
            for _ in 0..<120 {
                try SimulationTest.frames(session, 1)
                let core = try SimulationTest.core(shell)
                let gpu: FieldGrid
                switch core.kind {
                case .automaton: gpu = try XCTUnwrap(presenter.automaton).readBack()
                case .reactionDiffusion: gpu = try XCTUnwrap(presenter.grayScott).readBack()
                case .wave: gpu = try XCTUnwrap(presenter.wave).readBack().current
                }
                worst = max(worst, try XCTUnwrap(gpu.maxAbsDifference(core.model.field.current)))
            }
            let tolerance: Float = family == 0 ? 0 : 0.01
            XCTAssertLessThanOrEqual(worst, tolerance, "family \(family)")
            lines.append("| \(SimulationCore.familyTitle(index: family)) | \(f4(worst)) | \(f4(tolerance)) | "
                         + "\(worst <= tolerance ? "yes" : "no") |")
            maxSteps = max(maxSteps, presenter.maxGPUStepsInFrame)
            ownedBytes = presenter.ownedTargetBytes
            let registry = try XCTUnwrap(session.renderHost).resources
            registryBytes = max(registryBytes, registry.stats.totalBytes)
            budget = registry.budget.total
            session.close()
        }

        // Fixtures.
        lines += ["", "## Fixtures (16 × 16, 10 steps, seed 1)", "",
                  "| Family | Max against float16 | Max against toward zero | Tolerance |", "|---|---|---|---|"]
        let reactionStart = Seeding.reactionStart(gridSize: 16, seed: 1)
        let waveStart = Seeding.waveStart(gridSize: 16, seed: 1)
        var reactionGPU: FieldGrid?, waveGPU: FieldGrid?
        var limitReactionGPU: FieldGrid?, limitWaveGPU: FieldGrid?
        let reactionLimit = SimulationSpec.reactionTimeStepLimit, courantLimit = SimulationSpec.courantLimit
        try withFloatContext { registry in
            let gs = try GrayScottGPU(registry: registry, gridSize: 16)
            defer { gs.release() }
            _ = gs.load(reactionStart)
            try gs.step(feed: 0.035, kill: 0.065, timeStep: 1, count: 10)
            reactionGPU = gs.readBack()
            _ = gs.load(reactionStart)
            try gs.step(feed: 0.035, kill: 0.065, timeStep: Float(reactionLimit), count: 600)
            limitReactionGPU = gs.readBack()
            let wave = try WaveGPU(registry: registry, gridSize: 16)
            defer { wave.release() }
            _ = wave.load(SimulationField(current: waveStart, previous: waveStart))
            try wave.step(courant: 0.5, damping: 0.002, count: 10)
            waveGPU = wave.readBack().current
            _ = wave.load(SimulationField(current: waveStart, previous: waveStart))
            try wave.step(courant: Float(courantLimit), damping: 0.002, count: 600)
            limitWaveGPU = wave.readBack().current
        }
        func reactionReference(_ precision: StoragePrecision) -> FieldGrid {
            var grid = reactionStart
            for _ in 0..<10 { grid = GrayScott.step(grid, feed: 0.035, kill: 0.065, timeStep: 1, precision: precision) }
            return grid
        }
        func waveReference(_ precision: StoragePrecision) -> FieldGrid {
            var current = waveStart, previous = waveStart
            for _ in 0..<10 {
                let next = WaveField.step(current: current, previous: previous, courant: 0.5, damping: 0.002,
                                          precision: precision)
                previous = current
                current = next
            }
            return current
        }
        let fixtures: [(String, FieldGrid, FieldGrid, FieldGrid)] = [
            ("Reaction-diffusion", try XCTUnwrap(reactionGPU), reactionReference(.float16),
             reactionReference(.float16TowardZero)),
            ("Wave field", try XCTUnwrap(waveGPU), waveReference(.float16), waveReference(.float16TowardZero)),
        ]
        for (name, gpu, nearest, towardZero) in fixtures {
            let a = try XCTUnwrap(gpu.maxAbsDifference(nearest)), b = try XCTUnwrap(gpu.maxAbsDifference(towardZero))
            XCTAssertLessThanOrEqual(min(a, b), 0.01, name)
            lines.append("| \(name) | \(f4(a)) | \(f4(b)) | 0.0100 |")
        }

        // Stability limits.
        lines += ["", "## Stability limits (600 iterations)", "",
                  "| Family | Limit | CPU non-finite cells | GPU non-finite cells (16 × 16) | 1 % beyond the limit |",
                  "|---|---|---|---|---|"]
        var reactionSpec = SimulationSpec.standard(.reactionDiffusion)
        reactionSpec.timeStep = reactionLimit
        var waveSpec = SimulationSpec.standard(.wave)
        waveSpec.timeStep = courantLimit
        var reactionModel = try SimulationModel(spec: reactionSpec)
        var waveModel = try SimulationModel(spec: waveSpec)
        for _ in 0..<600 { reactionModel.step(); waveModel.step() }
        var reactionCore = simulationApplied(SimulationCore(seed: 1), "sim.family", [1]).0
        var waveCore = simulationApplied(SimulationCore(seed: 1), "sim.family", [2]).0
        let reactionRefusal = try XCTUnwrap(reactionCore.timeStepRefusal(reactionLimit * 1.01))
        let waveRefusal = try XCTUnwrap(waveCore.timeStepRefusal(courantLimit * 1.01))
        XCTAssertFalse(simulationApplied(reactionCore, "sim.timestep", [reactionLimit * 1.01]).1.isAccepted)
        XCTAssertFalse(simulationApplied(waveCore, "sim.timestep", [courantLimit * 1.01]).1.isAccepted)
        reactionCore = simulationApplied(reactionCore, "sim.timestep", [reactionLimit]).0
        waveCore = simulationApplied(waveCore, "sim.timestep", [courantLimit]).0
        XCTAssertEqual(reactionCore.model.spec.timeStep, reactionLimit, "the limit itself is accepted")
        XCTAssertEqual(waveCore.model.spec.timeStep, courantLimit)
        let limits: [(String, String, Int, Int, String)] = [
            ("Reaction-diffusion", "Δt 1.5625", nonFinite(reactionModel.field.current),
             nonFinite(try XCTUnwrap(limitReactionGPU)), reactionRefusal.sentence),
            ("Wave field", "Courant number 0.7071 (c 1, Δt 1/√2)", nonFinite(waveModel.field.current),
             nonFinite(try XCTUnwrap(limitWaveGPU)), waveRefusal.sentence),
        ]
        for (name, limit, cpu, gpu, sentence) in limits {
            XCTAssertEqual(cpu, 0, name)
            XCTAssertEqual(gpu, 0, name)
            lines.append("| \(name) | \(limit) | \(cpu) | \(gpu) | refused: \"\(sentence)\" |")
        }

        // Bounds.
        XCTAssertLessThanOrEqual(maxSteps, SimulationPresenter.maxStepsPerFrame)
        XCTAssertLessThanOrEqual(ownedBytes, 262_144)
        XCTAssertLessThanOrEqual(registryBytes, budget)
        lines += ["", "## Bounds", "",
                  "- Largest GPU steps in one frame: \(maxSteps) (cap \(SimulationPresenter.maxStepsPerFrame); a larger "
                  + "jump loads the mirror from the CPU instead of stepping it, `GPURebuildTests`).",
                  "- Presenter targets: \(ownedBytes) bytes (bound 262144: the 64 × 64 display target and the "
                  + "automaton, Gray-Scott and wave pairs).",
                  "- Registry: at most \(registryBytes) bytes during the runs, within its budget of \(budget) bytes.",
                  "", "## Boundary rules", "",
                  "- Automaton and reaction-diffusion wrap at the edges; the wave holds a fixed zero border "
                  + "(`BoundaryRuleTests`, `WaveBorderTests`).",
                  "- A canvas size change reloads the grid-sized targets and a context recreation makes them new; the "
                  + "next frame equals the CPU field within tolerance (`SizeChangeTests`).", ""]

        // Steps per second (reported, never asserted).
        lines += [Self.timingHeading, ""]
        let clock = ContinuousClock()
        for kind in SimulationKind.allCases {
            var model = try SimulationModel(spec: .standard(kind))
            let elapsed = clock.measure { for _ in 0..<600 { model.step() } }
            let seconds = Double(elapsed.components.seconds) + Double(elapsed.components.attoseconds) * 1e-18
            lines.append("- \(kind.title): \(Int((600 / max(seconds, 1e-9)).rounded())) CPU iterations per second.")
        }
        let report = lines.joined(separator: "\n") + "\n"

        let environment = ProcessInfo.processInfo.environment
        if environment["UPDATE_VALIDATION_REPORT"] == "1" {
            try Data(report.utf8).write(to: Self.reportURL)
        }
        let committed = (try? String(contentsOf: Self.reportURL, encoding: .utf8)) ?? ""
        XCTAssertEqual(Self.deterministic(committed), Self.deterministic(report),
                       "Regenerate the report with UPDATE_VALIDATION_REPORT=1.")
    }

    /// The lines before the steps-per-second section.
    static func deterministic(_ text: String) -> [Substring] {
        let lines = text.split(separator: "\n", omittingEmptySubsequences: false)
        return Array(lines.prefix { !$0.hasPrefix(timingHeading) })
    }
}
