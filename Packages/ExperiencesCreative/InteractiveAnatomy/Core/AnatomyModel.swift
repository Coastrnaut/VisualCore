// AnatomyModel — feature 124 (A17-P01) T-A17-103 (data-model "AnatomyRegion (schema 1)"; contracts/core.md). The
// versioned content schema of one anatomical region: its coordinate convention and bounds, its procedural mesh
// declarations, its structures (names, layer, parent, neighbours, meshes, description, sources) and its manifest
// (licences, review status, citations).
//
// Written as JSON with sorted keys; property names are the JSON keys and a nil optional is left out. The region of
// this phase is `region.knee.right`: one root (`knee.joint`, no layer, no meshes) and fourteen parts in three layers.
// Decoding and validation live in `AnatomyContent`; a refusal is a `ContentRefusal`.
import Foundation
import VisualCoreMath

/// The three layers a part of a region belongs to; the root of a region has no layer.
public enum AnatomyLayer: String, Codable, CaseIterable, Sendable {
    /// Bones.
    case bones
    /// Articular cartilage and menisci.
    case cartilage
    /// Ligaments and tendons.
    case ligaments
}

/// One procedural mesh a structure is drawn with; the geometry is generated by code from its kind.
public struct ProceduralMeshDeclaration: Codable, Equatable, Sendable {
    /// The four procedural mesh families.
    public enum Kind: String, Codable, CaseIterable, Sendable {
        /// A profile curve revolved about an axis.
        case revolution
        /// A circle swept along a path.
        case tube
        /// A planar outline extruded along its normal.
        case extrusion
        /// A (possibly scaled) sphere.
        case sphere
    }

    /// The mesh identifier, `mesh.<structure>.<part>`.
    public var id: String
    /// The procedural family that generates the mesh.
    public var kind: Kind

    /// Creates a mesh declaration.
    public init(id: String, kind: Kind) {
        self.id = id
        self.kind = kind
    }
}

/// The coordinate convention of a region: the unit and the axis that points superior, anterior and lateral.
public struct CoordinateConvention: Codable, Equatable, Sendable {
    /// The length unit, `cm`.
    public var unit: String
    /// The axis that points superior, `+Y`.
    public var superior: String
    /// The axis that points anterior, `+Z`.
    public var anterior: String
    /// The axis that points lateral, `+X`.
    public var lateral: String

    /// Creates a coordinate convention.
    public init(unit: String, superior: String, anterior: String, lateral: String) {
        self.unit = unit
        self.superior = superior
        self.anterior = anterior
        self.lateral = lateral
    }
}

/// An axis-aligned box in region coordinates; a valid box is finite with `min` below `max` on every axis.
public struct BoundingBox: Codable, Equatable, Sendable {
    /// The lower corner.
    public var min: Vec3
    /// The upper corner.
    public var max: Vec3

    /// Creates a bounding box.
    public init(min: Vec3, max: Vec3) {
        self.min = min
        self.max = max
    }
}

/// One anatomical structure of a region: the root (the whole joint) or one of its parts.
public struct AnatomicalStructure: Codable, Equatable, Sendable, Identifiable {
    /// The structure identifier, `knee.<name>`.
    public var id: String
    /// The Terminologia Anatomica name.
    public var standardName: String
    /// The plain English name, used as the label text.
    public var englishName: String
    /// Other common names; none collides with another structure's names.
    public var synonyms: [String]
    /// The layer of a part; nil only for the root.
    public var layer: AnatomyLayer?
    /// The identifier of the parent structure; nil only for the root.
    public var parent: String?
    /// The identifiers of the structures this one touches.
    public var neighbours: [String]
    /// The identifiers of the meshes that draw this structure (1–3 for a part, none for the root).
    public var meshIDs: [String]
    /// An original plain-language description of form, position and connections (1–3 sentences, ≤ 400 characters).
    public var description: String
    /// The identifiers of the manifest citations this structure rests on (at least one).
    public var sourceRefs: [String]

    /// Creates a structure.
    public init(id: String, standardName: String, englishName: String, synonyms: [String], layer: AnatomyLayer?,
                parent: String?, neighbours: [String], meshIDs: [String], description: String, sourceRefs: [String]) {
        self.id = id
        self.standardName = standardName
        self.englishName = englishName
        self.synonyms = synonyms
        self.layer = layer
        self.parent = parent
        self.neighbours = neighbours
        self.meshIDs = meshIDs
        self.description = description
        self.sourceRefs = sourceRefs
    }
}

/// One source the content rests on.
public struct Citation: Codable, Equatable, Sendable {
    /// The citation identifier referenced by `AnatomicalStructure.sourceRefs`.
    public var id: String
    /// The title of the work.
    public var title: String
    /// The edition of the work.
    public var edition: String
    /// The section of the work.
    public var section: String
    /// The licence of the work: one of `ContentManifest.allowedLicenses`.
    public var license: String

    /// Creates a citation.
    public init(id: String, title: String, edition: String, section: String, license: String) {
        self.id = id
        self.title = title
        self.edition = edition
        self.section = section
        self.license = license
    }
}

/// Whether a clinician reviewed the content, and if so who and when.
public struct ReviewStatus: Codable, Equatable, Sendable {
    /// The status value of content no clinician reviewed.
    public static let notReviewed = "not-reviewed"
    /// The status value of reviewed content.
    public static let reviewed = "reviewed"

    /// The review status, `not-reviewed` or `reviewed`.
    public var status: String
    /// The reviewer's name, present only once reviewed.
    public var reviewer: String?
    /// The review date (ISO 8601), present only once reviewed.
    public var date: String?

    /// Creates a review status.
    public init(status: String, reviewer: String? = nil, date: String? = nil) {
        self.status = status
        self.reviewer = reviewer
        self.date = date
    }
}

/// The licences, review status and citations of a region's content.
public struct ContentManifest: Codable, Equatable, Sendable {
    /// The licences content may carry: public domain, original work, or uncopyrightable facts.
    public static let allowedLicenses: Set<String> = ["public-domain", "original", "facts"]

    /// The licence of the text.
    public var textLicense: String
    /// The licence of the geometry.
    public var geometryLicense: String
    /// The clinical review status.
    public var review: ReviewStatus
    /// The sources the content rests on.
    public var citations: [Citation]

    /// Creates a manifest.
    public init(textLicense: String, geometryLicense: String, review: ReviewStatus, citations: [Citation]) {
        self.textLicense = textLicense
        self.geometryLicense = geometryLicense
        self.review = review
        self.citations = citations
    }

    /// The sentence shown with the content: "Not reviewed by a clinician." unless the status is `reviewed` with a
    /// reviewer and a date, then "Reviewed by <reviewer> on <date>.".
    public var reviewSentence: String {
        if review.status == ReviewStatus.reviewed, let reviewer = review.reviewer, let date = review.date,
           !reviewer.isEmpty, !date.isEmpty {
            return "Reviewed by \(reviewer) on \(date)."
        }
        return "Not reviewed by a clinician."
    }
}

/// One anatomical region (schema 1): convention, bounds, meshes, structures and manifest.
public struct AnatomyRegion: Codable, Equatable, Sendable {
    /// The schema version this code reads and writes.
    public static let schemaVersion = 1

    /// The schema version of the content.
    public var schema: Int
    /// The region identifier, `region.<name>.<side>`.
    public var id: String
    /// The body systems the region covers.
    public var systems: [String]
    /// The coordinate convention.
    public var convention: CoordinateConvention
    /// The bounds every mesh lies in.
    public var bounds: BoundingBox
    /// The version of the content itself, raised with every content change.
    public var contentVersion: Int
    /// The procedural meshes; each belongs to exactly one structure.
    public var meshes: [ProceduralMeshDeclaration]
    /// The structures, the root first by convention.
    public var structures: [AnatomicalStructure]
    /// The licences, review status and citations.
    public var manifest: ContentManifest

    /// Creates a region.
    public init(schema: Int, id: String, systems: [String], convention: CoordinateConvention, bounds: BoundingBox,
                contentVersion: Int, meshes: [ProceduralMeshDeclaration], structures: [AnatomicalStructure],
                manifest: ContentManifest) {
        self.schema = schema
        self.id = id
        self.systems = systems
        self.convention = convention
        self.bounds = bounds
        self.contentVersion = contentVersion
        self.meshes = meshes
        self.structures = structures
        self.manifest = manifest
    }

    /// The structure with the given identifier, or nil.
    public func structure(_ id: String) -> AnatomicalStructure? {
        structures.first { $0.id == id }
    }

    /// The first structure without a parent (a valid region has exactly one), or nil.
    public var root: AnatomicalStructure? {
        structures.first { $0.parent == nil }
    }
}

/// The label of one part: its English name anchored at its first mesh.
public struct AnatomyLabel: Equatable, Sendable {
    /// The identifier of the labelled structure.
    public let structureID: String
    /// The label text, the structure's English name.
    public let text: String
    /// The identifier of the mesh the label is anchored at.
    public let anchorMeshID: String

    /// Creates a label.
    public init(structureID: String, text: String, anchorMeshID: String) {
        self.structureID = structureID
        self.text = text
        self.anchorMeshID = anchorMeshID
    }
}
