// LicenseAudit — feature 089 (A12-P01) T-A12-103 (FR-A12-113; clarification 5; G-CONTENTLICENSES; SC-A12-105). The
// content license audit of the Tiny Worlds catalog: one row per preset (in catalog order, role `preset`), then one per
// palette (in catalog order, role `palette`) with its id, name, author and license; the problems (a missing author or
// license, or a license outside the allowed list); and the Markdown text of `docs/apps/tiny-worlds/content-licenses.md`,
// which a test compares with the bundled catalog. The text is deterministic (no dates), so regenerating it from an
// unchanged catalog gives the same bytes.
//
// Feature 091 (A12-P03) T-A12-302 (FR-A12-301; clarification Q1; G-PROPS): after the palettes come one row per prop
// (role `prop`) and one per prop palette (role `prop-palette`), and the document gains a prop table and a prop palette
// table; the summary line counts all four kinds.
//
// Feature 092 (A12-P04) T-A12-402 (FR-A12-406; clarification Q2; G-PACKS): after the prop palettes come one row per
// pack (role `pack`), and the document gains a pack table `Id | Name | Preset | Author | License`; the summary line
// counts the packs too.
import Foundation

/// One audited piece of content: a preset, a palette, a prop, a prop palette or a pack.
public struct LicenseRow: Codable, Equatable, Sendable {
    /// The content id (kebab-case).
    public var id: String
    /// The display name.
    public var name: String
    /// The author.
    public var author: String
    /// The license.
    public var license: String
    /// The role: ``ContentKind/preset``, ``ContentKind/palette``, ``ContentKind/prop``,
    /// ``ContentKind/propPalette`` or ``ContentKind/pack``.
    public var role: ContentKind

    /// Creates an audit row.
    public init(id: String, name: String, author: String, license: String, role: ContentKind) {
        self.id = id; self.name = name; self.author = author; self.license = license; self.role = role
    }
}

/// The content license audit of a Tiny Worlds content catalog.
public enum LicenseAudit {
    /// The document title.
    public static let title = "Tiny Worlds — content licenses"

    /// One row per preset, then per palette, per prop, per prop palette and per pack, each in catalog order.
    public static func rows(_ catalog: ContentCatalog) -> [LicenseRow] {
        catalog.presets.map {
            LicenseRow(id: $0.id, name: $0.name, author: $0.author, license: $0.license, role: .preset)
        } + catalog.palettes.map {
            LicenseRow(id: $0.id, name: $0.name, author: $0.author, license: $0.license, role: .palette)
        } + catalog.props.map {
            LicenseRow(id: $0.id, name: $0.name, author: $0.author, license: $0.license, role: .prop)
        } + catalog.propPalettes.map {
            LicenseRow(id: $0.id, name: $0.name, author: $0.author, license: $0.license, role: .propPalette)
        } + catalog.packs.map {
            LicenseRow(id: $0.id, name: $0.name, author: $0.author, license: $0.license, role: .pack)
        }
    }

    /// The audit's problems, empty when every row has an author and an allowed license; one line per problem, such as
    /// "preset island: missing-license" or "palette island: unsupported-license".
    public static func problems(_ catalog: ContentCatalog) -> [String] {
        problems(rows(catalog))
    }

    /// The problems of `rows`, one line per problem: "<role> <id>: <reason>".
    public static func problems(_ rows: [LicenseRow]) -> [String] {
        rows.compactMap { row in
            guard let error = ContentCatalog.licenseError(author: row.author, license: row.license) else { return nil }
            return "\(row.role.rawValue) \(row.id): \(error.rawValue)"
        }
    }

    /// The Markdown document: the title, a short provenance note, a table `Id | Name | Palette | Author | License`
    /// with every preset, a table `Id | Name | Sea or void | Low land | High land | Author | License` with every
    /// palette (colours as `#RRGGBB`, alpha below 1 appended as `/AA` in hexadecimal), a table
    /// `Id | Name | Palette | Author | License` with every prop, a table
    /// `Id | Name | Base | Main | Accent | Author | License` with every prop palette, a table
    /// `Id | Name | Preset | Author | License` with every pack, and a summary line
    /// "N presets, P palettes, Q props, R prop palettes, S packs; X problems.". Cell text has `|` escaped and line
    /// breaks replaced by spaces.
    public static func markdown(_ catalog: ContentCatalog) -> String {
        var lines: [String] = [
            "# \(title)",
            "",
            "Every world and every prop of Tiny Worlds is generated by code (worlds from a seed), and every preset,",
            "prop, palette and pack is original data in this repository. These tables are generated from",
            "`ContentCatalog.bundled` by `LicenseAudit.markdown(_:)`, and a test checks that they match it. "
                + "Allowed licenses: "
                + "\(ContentCatalog.allowedLicenses.joined(separator: ", ")).",
            "",
            "| Id | Name | Palette | Author | License |",
            "|---|---|---|---|---|",
        ]
        for preset in catalog.presets {
            let cells = [preset.id, preset.name, preset.palette, preset.author, preset.license].map(cell)
            lines.append("| " + cells.joined(separator: " | ") + " |")
        }
        lines += [
            "",
            "| Id | Name | Sea or void | Low land | High land | Author | License |",
            "|---|---|---|---|---|---|---|",
        ]
        func paletteRow(_ palette: Palette) -> String {
            let colors = (0..<ContentCatalog.colorCount).map { index in
                palette.colors.indices.contains(index) ? hex(palette.colors[index]) : ""
            }
            let cells = [palette.id, palette.name] + colors + [palette.author, palette.license]
            return "| " + cells.map(cell).joined(separator: " | ") + " |"
        }
        lines += catalog.palettes.map(paletteRow)
        lines += [
            "",
            "| Id | Name | Palette | Author | License |",
            "|---|---|---|---|---|",
        ]
        for prop in catalog.props {
            let cells = [prop.id, prop.name, prop.palette, prop.author, prop.license].map(cell)
            lines.append("| " + cells.joined(separator: " | ") + " |")
        }
        lines += [
            "",
            "| Id | Name | Base | Main | Accent | Author | License |",
            "|---|---|---|---|---|---|---|",
        ]
        lines += catalog.propPalettes.map(paletteRow)
        lines += [
            "",
            "| Id | Name | Preset | Author | License |",
            "|---|---|---|---|---|",
        ]
        for pack in catalog.packs {
            let cells = [pack.id, pack.name, pack.preset, pack.author, pack.license].map(cell)
            lines.append("| " + cells.joined(separator: " | ") + " |")
        }
        func counted(_ count: Int, _ noun: String) -> String { "\(count) \(noun)\(count == 1 ? "" : "s")" }
        lines.append("")
        lines.append("\(counted(catalog.presets.count, "preset")), \(counted(catalog.palettes.count, "palette")), "
                     + "\(counted(catalog.props.count, "prop")), "
                     + "\(counted(catalog.propPalettes.count, "prop palette")), "
                     + "\(counted(catalog.packs.count, "pack")); "
                     + "\(problems(catalog).count) problems.")
        return lines.joined(separator: "\n") + "\n"
    }

    /// `color` as `#RRGGBB` (components rounded to 0…255), with `/AA` appended when alpha is below 1; "?" for a
    /// non-finite colour.
    public static func hex(_ color: RGBA) -> String {
        guard color.isFiniteColor else { return "?" }
        func byte(_ value: Double) -> String {
            let scaled = Int((min(max(value, 0), 1) * 255).rounded())
            let digits = String(scaled, radix: 16, uppercase: true)
            return digits.count == 1 ? "0" + digits : digits
        }
        let rgb = "#" + byte(color.r) + byte(color.g) + byte(color.b)
        return color.a < 1 ? rgb + "/" + byte(color.a) : rgb
    }

    /// `text` safe for a Markdown table cell.
    private static func cell(_ text: String) -> String {
        let flat = text.replacingOccurrences(of: "\r", with: " ").replacingOccurrences(of: "\n", with: " ")
        let escaped = flat.replacingOccurrences(of: "|", with: "\\|")
        return escaped.isEmpty ? "—" : escaped
    }
}
