// clarifications Q2, Q3; data-model "ScientificReview"; contracts/review.md). The model statement of Solar System
// Explorer (clarification Q3, shown as "About this model" in the controls and in the review) and the text of
// `docs/apps/solar-system-explorer/scientific-review.md`, which a test compares with the committed file:
//   - "# Solar System Explorer — scientific review" and a note on how the document is generated;
//   - "## The model": the statement and the source of the orbital elements (Standish, JPL);
//   - "## Checks against published events": a table `Event | Published | Model | Offset (days) | Tolerance | Source |
//     Result` with one row per `EventFixture.bundled` (the model date is the `SimulatedDate` label of the model day
//     rounded to a whole day, the offset has two decimals);
//   - "## Data sources": a link to `data-sources.md` and its closing line "N values; X problems." taken from
//     `CitationAudit.markdown(.bundled)`;
//   - "## Tour captions": every caption of `Tour.bundled`;
//   - "## Scale labels": both `ScaleMode` labels.
// Deterministic (no dates or clocks), LF line endings, ending with a single newline.
import Foundation

/// The model statement and the scientific review document of Solar System Explorer.
public enum ScientificReview {
    /// The document title.
    public static let title = "Solar System Explorer — scientific review"

    /// The model statement of clarification Q3, shown as "About this model" and in the review.
    public static let modelStatement = "Positions come from an approximate model: Kepler orbits from the planets' mean "
        + "elements at epoch J2000.0 (E. M. Standish, JPL), held fixed, for dates from 1950 to 2050. They are not an "
        + "ephemeris. In the enhanced view, sizes and distances are enlarged and not to scale."

    /// The closing line of the data-sources document, "N values; X problems.".
    public static func dataSourcesSummary(_ catalog: BodyCatalog = .bundled) -> String {
        let text = CitationAudit.markdown(catalog)
        let lines = text.split(separator: "\n", omittingEmptySubsequences: true)
        return lines.last.map { String($0) } ?? ""
    }

    /// `text` safe for a Markdown table cell: `|` escaped, line breaks replaced by spaces, "—" when empty.
    private static func cell(_ text: String) -> String {
        let flat = text.replacingOccurrences(of: "\r", with: " ").replacingOccurrences(of: "\n", with: " ")
        let escaped = flat.replacingOccurrences(of: "|", with: "\\|")
        return escaped.isEmpty ? "—" : escaped
    }

    /// The model date of a result: the `SimulatedDate` label of the model day rounded to a whole day, "—" when the
    /// day is not finite or outside the model's range.
    public static func modelDateLabel(_ result: EventResult) -> String {
        guard result.modelDay.isFinite, let date = SimulatedDate(dayOffset: result.modelDay.rounded()) else {
            return "—"
        }
        return date.label
    }

    /// The offset of a result with two decimals, "—" when not finite.
    public static func offsetText(_ result: EventResult) -> String {
        result.offsetDays.isFinite ? String(format: "%.2f", result.offsetDays) : "—"
    }

    /// The Markdown document (see the file header).
    public static func markdown() -> String {
        var lines: [String] = [
            "# \(title)",
            "",
            "Generated by `ScientificReview.markdown()` from the bundled orbit model, catalog and tours; a test checks "
                + "that this file matches it. It records what the model is, how it compares with published events and "
                + "where every number shown comes from.",
            "",
            "## The model",
            "",
            modelStatement,
            "",
            "Orbital elements: \(SourceRecord.standishTitle), \(SourceRecord.standishPublisher) "
                + "(\(SourceRecord.standishLink)).",
            "",
            "## Checks against published events",
            "",
            "Each event is searched day by day within \(EventChecks.windowDays) days of its published date and refined "
                + "to 0.01 day: an opposition is the day when the planet's and Earth's heliocentric ecliptic longitudes "
                + "are equal, a perihelion the day of Earth's least distance from the Sun. The model's Earth is the "
                + "Earth–Moon barycentre. The offset is the model's day minus the published day (noon UTC).",
            "",
            "| Event | Published | Model | Offset (days) | Tolerance | Source | Result |",
            "|---|---|---|---|---|---|---|",
        ]
        for result in EventChecks.evaluateBundled() {
            let fixture = result.fixture
            let tolerance = "±" + Units.storedText(fixture.toleranceDays) + " days"
            let cells: [String] = [fixture.name, fixture.publishedDate, modelDateLabel(result), offsetText(result),
                                   tolerance, fixture.source, result.passed ? "pass" : "fail"]
            lines.append("| " + cells.map(cell).joined(separator: " | ") + " |")
        }
        lines += [
            "",
            "## Data sources",
            "",
            "Every stored value, its units, source, epoch and license are listed in "
                + "[data-sources.md](data-sources.md), generated from the same catalog:",
            "",
            dataSourcesSummary(),
            "",
            "## Tour captions",
            "",
        ]
        for tour in Tour.bundled {
            for (index, stop) in tour.stops.enumerated() {
                lines.append("- \(tour.title), stop \(index + 1) of \(tour.stops.count): \(stop.caption)")
            }
        }
        lines += [
            "",
            "## Scale labels",
            "",
        ]
        for mode in ScaleMode.allCases {
            lines.append("- \(mode.name): \(mode.label)")
        }
        return lines.joined(separator: "\n") + "\n"
    }
}
