#!/usr/bin/env python3
"""Generate CVisualCoreGL: the OpenGL ES 3.0 entry-point table loaded through eglGetProcAddress
(T-F010; Constitution I; ADR-0002).

Reads the iOS SDK's OpenGLES/ES3/gl.h only as a *list* of the standard ES 3.0 constants and function
signatures (identical to Khronos GLES3/gl3.h), and writes a self-contained header + C file that never
include or link Apple's OpenGLES.framework:

  * `#define GL_*` constants and standard GL scalar typedefs;
  * `struct VCGLTable` of function pointers and `int vcglLoad(VCGLLoader, void *user)`;
  * one `vcglName(...)` wrapper per function that calls through the table.

The table is filled from ANGLE's `eglGetProcAddress` (no dlsym), mirroring the reference
`CANGLE.c` approach in the owner's ProjectM-iOS (MIT).

Usage: python3 scripts/generate_vcgl.py [--check]
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "Packages" / "VisualCoreRendering" / "Sources" / "CVisualCoreGL"
HEADER = OUT_DIR / "include" / "CVisualCoreGL.h"
SOURCE = OUT_DIR / "CVisualCoreGL.c"
FUNC = re.compile(r"^GL_API\s+(.+?)\s+GL_APIENTRY\s+(gl\w+)\s*\(([^)]*)\)", re.M)
CONST = re.compile(r"^#define\s+(GL_[A-Z0-9_x]+)\s+(0x[0-9A-Fa-f]+[uUlL]*|\d+[uUlL]*)\s*$", re.M)
SKIP_CONST = {"GL_ES_VERSION_2_0", "GL_ES_VERSION_3_0"}
TYPES = """typedef void GLvoid;
typedef char GLchar;
typedef unsigned int GLenum;
typedef unsigned char GLboolean;
typedef unsigned int GLbitfield;
typedef signed char GLbyte;
typedef short GLshort;
typedef int GLint;
typedef int GLsizei;
typedef unsigned char GLubyte;
typedef unsigned short GLushort;
typedef unsigned int GLuint;
typedef float GLfloat;
typedef float GLclampf;
typedef int32_t GLfixed;
typedef intptr_t GLintptr;
typedef intptr_t GLsizeiptr;
typedef unsigned short GLhalf;
typedef int64_t GLint64;
typedef uint64_t GLuint64;
typedef struct __GLsync *GLsync;"""


def sdk_header() -> tuple[str, str]:
    sdk = subprocess.run(["xcrun", "--sdk", "iphoneos", "--show-sdk-path"], capture_output=True, text=True,
                         check=True).stdout.strip()
    ver = subprocess.run(["xcrun", "--sdk", "iphoneos", "--show-sdk-version"], capture_output=True, text=True,
                         check=True).stdout.strip()
    return (Path(sdk) / "System/Library/Frameworks/OpenGLES.framework/Headers/ES3/gl.h").read_text(), ver


def arg_names(params: str) -> list[str]:
    params = params.strip()
    if params in ("", "void"):
        return []
    names = []
    for p in params.split(","):
        m = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", p.strip())
        if not m:
            raise ValueError("cannot parse parameter: " + p)
        names.append(m.group(1))
    return names


def render(text: str, sdk_version: str) -> tuple[str, str]:
    funcs = sorted({m.group(2): (m.group(1).strip(), m.group(3).strip()) for m in FUNC.finditer(text)}.items())
    consts = [(n, v) for n, v in CONST.findall(text) if n not in SKIP_CONST]
    seen, uniq = set(), []
    for n, v in consts:
        if n not in seen:
            seen.add(n)
            uniq.append((n, v))
    banner = (f"// GENERATED by scripts/generate_vcgl.py from the iOS {sdk_version} SDK ES3/gl.h signature list\n"
              f"// ({len(funcs)} functions, {len(uniq)} constants). Do not edit. Apple's OpenGLES.framework is\n"
              "// never included or linked: entry points are resolved from ANGLE's eglGetProcAddress.\n")
    h = [banner, "#ifndef CVISUALCOREGL_H", "#define CVISUALCOREGL_H", "", "#include <stdint.h>", "#include <stddef.h>", "",
         TYPES, ""]
    h += [f"#define {n} {v}" for n, v in uniq]
    h += ["", "typedef void *(*VCGLLoader)(const char *name, void *user);", "",
          "/// Fills the table from `loader`. Returns the number of entry points that could not be resolved",
          "/// (0 = complete). Safe to call more than once; must run before any vcgl* call.",
          "int vcglLoad(VCGLLoader loader, void *user);",
          "/// Number of entry points in the table, and whether all were resolved.",
          "int vcglEntryCount(void);", "int vcglIsLoaded(void);", ""]
    c = [banner, '#include "CVisualCoreGL.h"', "", "typedef struct {"]
    for name, (ret, params) in funcs:
        c.append(f"    {ret} (*{name})({params});")
    c += ["} VCGLTable;", "", "static VCGLTable vcgl_table;", "static int vcgl_loaded;", "",
          "int vcglLoad(VCGLLoader loader, void *user) {", "    int missing = 0;"]
    for name, (ret, params) in funcs:
        c.append(f'    vcgl_table.{name} = ({ret} (*)({params}))loader("{name}", user);')
        c.append(f"    if (!vcgl_table.{name}) missing++;")
    c += ["    vcgl_loaded = (missing == 0);", "    return missing;", "}", "",
          f"int vcglEntryCount(void) {{ return {len(funcs)}; }}", "int vcglIsLoaded(void) { return vcgl_loaded; }", ""]
    for name, (ret, params) in funcs:
        args = ", ".join(arg_names(params))
        wrapper = "vcgl" + name[2:]
        h.append(f"{ret} {wrapper}({params});")
        ret_kw = "" if ret == "void" else "return "
        c.append(f"{ret} {wrapper}({params}) {{ {ret_kw}vcgl_table.{name}({args}); }}")
    h += ["", "#endif", ""]
    return "\n".join(h), "\n".join(c) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text, ver = sdk_header()
    header, source = render(text, ver)
    if args.check:
        stale = [p for p, body in ((HEADER, header), (SOURCE, source)) if not p.exists() or p.read_text() != body]
        print("stale: " + ", ".join(map(str, stale)) if stale else "CVisualCoreGL up to date")
        return 1 if stale else 0
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(header)
    SOURCE.write_text(source)
    print(f"wrote {HEADER.relative_to(ROOT)} and {SOURCE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
