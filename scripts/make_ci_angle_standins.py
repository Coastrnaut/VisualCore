#!/usr/bin/env python3
"""Generate link-only ANGLE stand-in frameworks for CI, where the real ANGLE build is never available
(feature UA-F10 T-U10-004; FR-U10-002; specs/196-ua-f10-build-ci/research.md R1, contracts/tools.md).

  python3 scripts/make_ci_angle_standins.py --out External/projectm-ios/Build/ANGLEFrameworks
  python3 scripts/make_ci_angle_standins.py --out Build/standin-check --dry-run

The real `libEGL.xcframework` and `libGLESv2.xcframework` are built locally and never committed. CI only has to link
the app, so this tool parses the `egl*` prototypes of `CVisualCoreEGL.h`, generates a C file that defines each of
them with the same signature and the body `abort();`, and compiles `arm64` and `x86_64` simulator slices with
`xcrun --sdk iphonesimulator clang -dynamiclib`. They are joined with `lipo`, wrapped in `libEGL.framework` and
then in `libEGL.xcframework` by `xcodebuild -create-xcframework`. `libGLESv2` is built the same way and holds only
the marker symbol. Every binary carries the string of `MARKER`; a stand-in can never be mistaken for a real
framework, and a real framework found in the output folder (no marker) is never overwritten.

With `--dry-run` only the generated C file is written to `--out` and the plan is printed; nothing is compiled.

Exit codes: 0 stand-ins written; 1 a build step failed (named); 2 bad input or a real framework in the output folder.
"""
from __future__ import annotations

import argparse
import plistlib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_HEADER = "Packages/VisualCoreRendering/Sources/CVisualCoreEGL/include/CVisualCoreEGL.h"
MARKER = "VisualCore CI link-only ANGLE stand-in; never shipped"
MARKER_SYMBOL = "vc_ci_angle_standin"
ARCHS = ("arm64", "x86_64")
FRAMEWORKS = ("libEGL", "libGLESv2")
PROTOTYPE = re.compile(r"^([A-Za-z_][^;(){}#]*?[\s*])(egl[A-Za-z0-9_]+)\s*\(([^;{}]*)\)\s*;", re.MULTILINE)
MIN_IOS = re.compile(r"\d+(\.\d+){0,2}$")


class StepError(Exception):
    """A named build step failed."""


def parse_prototypes(text: str) -> list[tuple[str, str, str]]:
    """Return (return type, name, parameters) of every `egl*` function prototype in a C header text.

    Prototypes may span lines; whitespace inside the parameter list is collapsed. Non-`egl` functions are skipped.
    """
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    result = []
    for match in PROTOTYPE.finditer(text):
        ret = " ".join(match.group(1).split())
        if ret.startswith("typedef") or ret.startswith("#"):
            continue
        params = " ".join(match.group(3).split())
        result.append((ret, match.group(2), params))
    return result


def marker_definition() -> str:
    """Return the C definition of the exported marker string."""
    return f'__attribute__((used, visibility("default"))) const char {MARKER_SYMBOL}[] = "{MARKER}";\n'


def generate_c(header_path: Path | str, prototypes: list[tuple[str, str, str]]) -> str:
    """Return C source defining every prototype with `abort();` and exporting the marker string."""
    lines = [
        "// Generated by scripts/make_ci_angle_standins.py (UA-F10 T-U10-004). Link-only; never shipped.",
        "#include <stdlib.h>",
        f'#include "{Path(header_path).resolve()}"',
        "",
        marker_definition(),
    ]
    for ret, name, params in prototypes:
        lines.append(f'__attribute__((visibility("default"))) {ret} {name}({params}) {{')
        lines.append("    abort();")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def is_standin(binary_path: Path | str) -> bool:
    """True when the file exists and contains the stand-in marker string."""
    try:
        return MARKER.encode() in Path(binary_path).read_bytes()
    except OSError:
        return False


def framework_binaries(xcframework: Path, name: str) -> list[Path]:
    """Every file named `name` inside `xcframework` (any slice, any layout)."""
    return [p for p in xcframework.rglob(name) if p.is_file()]


def check_output(out: Path) -> str | None:
    """Return a refusal message when `out` holds a framework that is not a stand-in, else None."""
    for name in FRAMEWORKS:
        xcf = out / f"{name}.xcframework"
        if not xcf.exists():
            continue
        binaries = framework_binaries(xcf, name)
        if not binaries or not all(is_standin(b) for b in binaries):
            return f"{xcf} exists and is not a stand-in (no marker); refusing to overwrite a real framework"
    return None


def run_step(step: str, cmd: list[str]) -> None:
    """Run one build command; raise StepError naming the step on failure."""
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise StepError(f"{step}: {exc}") from exc
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip().splitlines()[-10:]
        raise StepError(f"{step} (exit {proc.returncode}): " + "\n".join(detail))


def info_plist(name: str, min_ios: str) -> bytes:
    """Minimal framework Info.plist."""
    return plistlib.dumps({
        "CFBundleExecutable": name,
        "CFBundleIdentifier": f"dev.visualcore.ci.{name}",
        "CFBundlePackageType": "FMWK",
        "CFBundleShortVersionString": "1.0",
        "CFBundleVersion": "1",
        "MinimumOSVersion": min_ios,
        "CFBundleSupportedPlatforms": ["iPhoneSimulator"],
    })


def build_framework(name: str, source: Path, work: Path, out: Path, min_ios: str) -> Path:
    """Compile, lipo and wrap one stand-in; return the xcframework path."""
    slices = []
    for arch in ARCHS:
        obj = work / f"{name}-{arch}.dylib"
        run_step(f"clang {name} {arch}", [
            "xcrun", "--sdk", "iphonesimulator", "clang", "-target", f"{arch}-apple-ios{min_ios}-simulator",
            "-dynamiclib", "-install_name", f"@rpath/{name}.framework/{name}", "-O1", "-o", str(obj), str(source),
        ])
        slices.append(str(obj))
    fw = work / f"{name}.framework"
    fw.mkdir()
    run_step(f"lipo {name}", ["lipo", "-create", *slices, "-output", str(fw / name)])
    (fw / "Info.plist").write_bytes(info_plist(name, min_ios))
    xcf = out / f"{name}.xcframework"
    if xcf.exists():
        shutil.rmtree(xcf)
    run_step(f"create-xcframework {name}", [
        "xcodebuild", "-create-xcframework", "-framework", str(fw), "-output", str(xcf),
    ])
    return xcf


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True, help="output folder for the two .xcframework bundles")
    parser.add_argument("--header", default=DEFAULT_HEADER, help="EGL header, relative to --root or absolute")
    parser.add_argument("--root", default=str(ROOT), help="repository root (default: this repository)")
    parser.add_argument("--dry-run", action="store_true", help="write the C file and print the plan only")
    parser.add_argument("--min-ios", default="26.0", help="minimum iOS version of the slices")
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return 0 if exc.code == 0 else 2

    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f"error: --root {root} is not a folder", file=sys.stderr)
        return 2
    if not MIN_IOS.match(args.min_ios):
        print(f"error: --min-ios {args.min_ios!r} is not a version", file=sys.stderr)
        return 2
    header = Path(args.header)
    header = header if header.is_absolute() else root / header
    try:
        text = header.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        print(f"error: cannot read header {header}: {exc}", file=sys.stderr)
        return 2
    prototypes = parse_prototypes(text)
    if not prototypes:
        print(f"error: no egl* prototypes in {header}", file=sys.stderr)
        return 2

    out = Path(args.out)
    out = out if out.is_absolute() else Path.cwd() / out
    if out.exists() and not out.is_dir():
        print(f"error: --out {out} is not a folder", file=sys.stderr)
        return 2
    if out.is_dir():
        refusal = check_output(out)
        if refusal:
            print(f"error: {refusal}", file=sys.stderr)
            return 2

    egl_c = generate_c(header, prototypes)
    gles_c = "// Generated by scripts/make_ci_angle_standins.py (UA-F10 T-U10-004). Link-only; never shipped.\n" \
        + marker_definition()

    if args.dry_run:
        out.mkdir(parents=True, exist_ok=True)
        c_file = out / "libEGL-standin.c"
        c_file.write_text(egl_c, encoding="utf-8")
        print(f"dry run: wrote {c_file} ({len(prototypes)} egl functions)")
        for name in FRAMEWORKS:
            print(f"plan: {name}.framework <- clang {'+'.join(ARCHS)} ios{args.min_ios}-simulator, lipo, "
                  f"xcodebuild -create-xcframework -> {out / (name + '.xcframework')}")
        return 0

    out.mkdir(parents=True, exist_ok=True)
    try:
        with tempfile.TemporaryDirectory(prefix="vc-standin-") as tmp:
            work = Path(tmp)
            sources = {"libEGL": egl_c, "libGLESv2": gles_c}
            for name in FRAMEWORKS:
                src = work / f"{name}-standin.c"
                src.write_text(sources[name], encoding="utf-8")
                xcf = build_framework(name, src, work, out, args.min_ios)
                print(f"wrote {xcf}")
    except StepError as exc:
        print(f"error: build step failed: {exc}", file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"error: build step failed: file system: {exc}", file=sys.stderr)
        return 1
    print(f"stand-ins ready: {len(prototypes)} egl functions in libEGL, marker {MARKER_SYMBOL}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
