#!/usr/bin/env python3
"""Public-API review (feature 010 T-F901; FR-F901, SC-F901; contract specs/010-stabilization-release/contracts/
release-contract.md). Every public declaration in VisualCore package sources must carry a `///` documentation comment
(or end a `/** */` block) on the line(s) above it, and the normalized public surface must match the committed baseline
`docs/api/visualcore-public-api.txt`. `--update` rewrites the baseline deliberately (an intentional API change).
Exit 0 ok, 1 undocumented or changed (names listed), 2 usage error.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODIFIERS = r"(?:(?:static|class|final|override|mutating|nonmutating|nonisolated|required|convenience|indirect|lazy|weak|dynamic|"
MODIFIERS += r"(?:private|fileprivate|internal|public)\(set\))\s+)*"
DECL = re.compile(r"^(\s*)(?:@[\w.]+(?:\([^)]*\))?\s+)*(?:public|open)\s+" + MODIFIERS +
                  r"(class|struct|enum|protocol|actor|typealias|func|init|var|let|subscript)\b(.*)$")
SKIP = {".build", "Build", "DerivedData", ".swiftpm", "Tests"}


def sources(packages: Path) -> list[Path]:
    return sorted(p for p in packages.rglob("*.swift")
                  if p.name != "Package.swift" and not (SKIP & set(p.relative_to(packages).parts)))


def module_of(path: Path, packages: Path) -> str:
    parts = path.relative_to(packages).parts
    return parts[2] if len(parts) > 3 and parts[1] == "Sources" else parts[0]


def documented(lines: list[str], i: int) -> bool:
    j = i - 1
    while j >= 0 and (lines[j].strip().startswith("@") or lines[j].strip() == ""):
        if lines[j].strip() == "":
            return False
        j -= 1
    return j >= 0 and (lines[j].strip().startswith("///") or lines[j].strip().endswith("*/"))


def normalize(kind: str, rest: str, line: str) -> str:
    text = line.strip()
    for stop in (" {", "{"):
        if stop in text and kind not in ("var", "let"):
            text = text.split(stop, 1)[0]
    if kind in ("var", "let"):
        text = re.split(r"\s*(?:=|\{)", text, maxsplit=1)[0]
    text = re.sub(r"\s*//.*$", "", text)
    return re.sub(r"\s+", " ", text).strip()


def scan(packages: Path) -> tuple[list[str], list[str]]:
    surface, undocumented = [], []
    for f in sources(packages):
        lines = f.read_text(errors="replace").splitlines()
        in_block_comment = False
        for i, line in enumerate(lines):
            s = line.strip()
            if s.startswith("/*") and not s.endswith("*/"):
                in_block_comment = True
            if in_block_comment:
                if s.endswith("*/"):
                    in_block_comment = False
                continue
            m = DECL.match(line)
            if not m:
                continue
            kind = m.group(2)
            module = module_of(f, packages)
            entry = f"{module} | {kind} | {normalize(kind, m.group(3), line)}"
            surface.append(entry)
            if not documented(lines, i):
                undocumented.append(f"{f.relative_to(packages.parent)}:{i + 1}: {normalize(kind, m.group(3), line)}")
    return sorted(set(surface)), undocumented


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--packages", type=Path, default=Path("Packages"))
    ap.add_argument("--baseline", type=Path, default=Path("docs/api/visualcore-public-api.txt"))
    ap.add_argument("--update", action="store_true", help="rewrite the baseline (intentional API change)")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    packages, baseline = root / args.packages, root / args.baseline
    if not packages.is_dir():
        print(f"error: {packages} not found", file=sys.stderr)
        return 2
    surface, undocumented = scan(packages)
    print(f"public declarations: {len(surface)}; undocumented: {len(undocumented)}")
    for u in undocumented:
        print(f"UNDOCUMENTED {u}")
    if args.update:
        baseline.parent.mkdir(parents=True, exist_ok=True)
        baseline.write_text("# VisualCore public API baseline — generated by scripts/check_public_api.py --update\n"
                            + "\n".join(surface) + "\n")
        print(f"baseline written: {baseline.relative_to(root)} ({len(surface)} lines)")
        return 1 if undocumented else 0
    if not baseline.exists():
        print(f"FAIL: no baseline at {args.baseline}; run with --update after review")
        return 1
    recorded = [l for l in baseline.read_text().splitlines() if l and not l.startswith("#")]
    added, removed = sorted(set(surface) - set(recorded)), sorted(set(recorded) - set(surface))
    for a in added:
        print(f"ADDED   {a}")
    for r in removed:
        print(f"REMOVED {r}")
    if undocumented or added or removed:
        print(f"FAIL: {len(undocumented)} undocumented, {len(added)} added, {len(removed)} removed")
        return 1
    print("PASS: public API documented and matches the baseline")
    return 0


if __name__ == "__main__":
    sys.exit(main())
